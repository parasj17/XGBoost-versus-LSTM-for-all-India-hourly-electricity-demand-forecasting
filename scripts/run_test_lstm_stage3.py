"""Single test evaluation of the equal-budget LSTM (stage 3; protocol deviation log 2026-10-16).

Reads reports/tables/lstm_stage3_config.json (selected on VALIDATION by run_lstm_stage3.py). For every horizon the L4_full_A LSTM is fitted on the training period only
(targets <= 2023-12-31) with 3 seeds and the validation-chosen number of epochs, exactly as in the frozen test run, and scored on the test period. Predictions are saved to
data/interim/predictions/lstm_stage3_h{h}.npz and compared (paired MAE difference, 95% block bootstrap) with the saved predictions of XGBoost S4, ridge and the original
frozen LSTM L4.
  py scripts/run_test_lstm_stage3.py --check   dry run on the VALIDATION period (test not loaded, 2 epochs, nothing saved)
  py scripts/run_test_lstm_stage3.py           the single test run (lock file reports/tables/LSTM_STAGE3_TEST_DONE.lock)
Output: reports/lstm_stage3_test.md
"""
import argparse
import importlib
import json
import sys
import time
from pathlib import Path

import numpy as np
import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "scripts"))
rb = importlib.import_module("run_baselines")
rl = importlib.import_module("run_lstm")
rt = importlib.import_module("run_test_evaluation")
T = ROOT / "reports" / "tables"
LOCK = T / "LSTM_STAGE3_TEST_DONE.lock"
PRED = ROOT / "data" / "interim" / "predictions"


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()
    commit, dirty = rb.git_state()
    if not args.check:
        if LOCK.exists():
            sys.exit("The stage-3 test evaluation was already run.")
        if dirty:
            sys.exit("Working tree is not clean: commit first.")
    cfg = json.loads((T / "lstm_stage3_config.json").read_text(encoding="utf-8"))
    ev_start, ev_end = (rb.VAL_START, rb.VAL_END) if args.check else (rt.TEST_START, rt.TEST_END)
    df = pd.read_csv(rb.SRC, parse_dates=["timestamp"]).set_index("timestamp").loc[:ev_end]
    y_all = df["electricity_demand_mw"].ffill().to_numpy(dtype=float)
    rng = np.random.default_rng(0)
    md = ["# " + ("CHECK on validation (not a result)" if args.check else "Equal-budget LSTM on the test period (single run)") + " (generated by `scripts/run_test_lstm_stage3.py`)", "",
          f"Git commit `{(commit or 'n/a')[:10]}`. L4_full_A LSTM with the configuration selected on validation among 90 trials per horizon (`reports/lstm_stage3.md`), fitted on the training "
          "period only, epochs fixed from validation, 3 seeds, mean prediction. The original frozen LSTM L4 and XGBoost S4 are taken from the saved predictions of the frozen test run.", "",
          "| horizon | equal-budget LSTM MAE (MW) | original LSTM L4 | XGBoost S4 | ridge | equal-budget minus original (95% CI) | equal-budget minus XGBoost (95% CI) | per-seed MAE |", "|---:|---:|---:|---:|---:|---|---|---|"]
    for h in rb.HORIZONS if not args.check else [24]:
        c = cfg[str(h)]
        b = rb.build(df, h)
        Xs = {n: rb.design(b, rel, full) for n, (rel, full) in
              {"g01_abs": (False, False), "g01_rel": (True, False), "full_abs": (False, True), "full_rel": (True, True)}.items()}
        need = pd.concat(Xs.values(), axis=1).notna().all(axis=1) & b["y"].notna() & b["anchors"]["a24"].notna()
        if h <= 168:
            need &= b["anchors"]["a168"].notna()
        valid = need & b["target_obs"]
        in_tr = valid & (b["T"] <= rb.TRAIN_END)
        in_ev = valid & (b["T"] >= ev_start) & (b["T"] <= ev_end)
        a24 = b["anchors"]["a24"]
        a24v = a24.fillna(1.0).to_numpy()
        pos = np.arange(len(df))
        idx_tr, idx_ev = pos[in_tr.to_numpy()], pos[in_ev.to_numpy()]
        y_ev, a_ev = b["target"].to_numpy()[idx_ev], a24v[idx_ev]
        z_all = ((b["target"] / a24 - 1) * 100).to_numpy()
        zsd = float(np.nanstd(z_all[idx_tr]))
        zt = np.nan_to_num(z_all / zsd)
        C, S = rl.step_channels(df, True, True, rb.TRAIN_END), rl.static_features(df, h, b, True)
        trD, evD = rl.Data(y_all, a24v, C, S, zt, idx_tr), rl.Data(y_all, a24v, C, S, zt, idx_ev)
        preds = []
        for sd in rt.SEEDS if not args.check else [0]:
            ep = c["best_epoch"][str(sd)] if not args.check else 2
            net = rt.lstm_fit_fixed(trD, C.shape[1] + 1, S.shape[1], c["params"], sd, ep)
            preds.append((1 + rl.predict(net, evD, len(idx_ev)) * zsd / 100.0) * a_ev)
        p = np.mean(preds, axis=0)
        mae = float(np.mean(np.abs(p - y_ev)))
        seed_mae = ", ".join(f"{np.mean(np.abs(q - y_ev)):,.0f}" for q in preds)
        if args.check:
            md.append(f"| {h} | {mae:,.0f} (check, 1 seed, 2 epochs) | | | | | | {seed_mae} |")
            continue
        z = np.load(PRED / f"h{h}.npz")
        assert np.allclose(z["y_te"], y_ev), "sample sets differ from the frozen test run"
        o, x, r = z["te__lstm_L4_full_A"], z["te__xgb_S4_full_A"], z["te__ridge_best"]
        d_o = np.abs(p - y_ev) - np.abs(o - y_ev)
        d_x = np.abs(p - y_ev) - np.abs(x - y_ev)
        lo1, hi1 = rb.block_ci(d_o, rng)
        lo2, hi2 = rb.block_ci(d_x, rng)
        np.savez_compressed(PRED / f"lstm_stage3_h{h}.npz", te=p, y_te=y_ev)
        f = lambda v: f"{np.mean(np.abs(v - y_ev)):,.0f}"
        md.append(f"| {h} | {mae:,.0f} | {f(o)} | {f(x)} | {f(r)} | {d_o.mean():+,.0f} ({lo1:+,.0f} to {hi1:+,.0f}) | {d_x.mean():+,.0f} ({lo2:+,.0f} to {hi2:+,.0f}) | {seed_mae} |")
        print(f"h={h}: equal-budget LSTM {mae:.0f} MW; original LSTM {f(o)}; XGBoost {f(x)}", flush=True)
    out = ROOT / "reports" / ("lstm_stage3_test_check.md" if args.check else "lstm_stage3_test.md")
    out.write_text(chr(10).join(md) + chr(10), encoding="utf-8")
    if not args.check:
        LOCK.write_text(f"stage-3 LSTM test run completed at commit {commit}" + chr(10), encoding="utf-8")
    print("wrote", out)


if __name__ == "__main__":
    main()
