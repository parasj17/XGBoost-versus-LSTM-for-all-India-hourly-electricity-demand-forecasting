"""Exploratory analysis on the TRAINING period only (task 4.2).

Only rows with timestamp <= 2023-12-31 23:00 are used. Validation (2024-H1)
and test (2024-07 onward) data are never loaded into any statistic here, so
the findings can legitimately guide design choices (protocol section 6).

Writes  reports/eda_training_period.md   (all numbers quoted in the report)
        reports/figures/eda_training_period.png
Usage:  py scripts/eda_training_period.py
"""
from pathlib import Path

import matplotlib

matplotlib.use("Agg")
import matplotlib.dates as mdates
import matplotlib.pyplot as plt
import numpy as np
import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
SRC = ROOT / "data" / "processed" / "india_hourly_canonical.csv"
HOL = ROOT / "data" / "raw" / "calendar" / "dopt_central_gazetted_holidays.csv"
FIG = ROOT / "reports" / "figures" / "eda_training_period.png"
REP = ROOT / "reports" / "eda_training_period.md"
TRAIN_END = pd.Timestamp("2023-12-31 23:00")

BLUE, ORANGE, AQUA, MAGENTA = "#2a78d6", "#eb6834", "#1baf7a", "#e87ba4"
INK, INK2, SURFACE, GRID = "#0b0b0b", "#52514e", "#fcfcfb", "#e4e3df"
SEASON_ORDER = ["winter", "pre_monsoon_summer", "monsoon", "post_monsoon"]
SEASON_STYLE = {"winter": (BLUE, "-"), "pre_monsoon_summer": (ORANGE, "--"),
                "monsoon": (AQUA, "-."), "post_monsoon": (MAGENTA, ":")}


def style(ax):
    ax.set_facecolor(SURFACE)
    for s in ("top", "right"):
        ax.spines[s].set_visible(False)
    for s in ("left", "bottom"):
        ax.spines[s].set_color(GRID)
    ax.tick_params(colors=INK2, labelsize=8)
    ax.grid(axis="y", color=GRID, linewidth=0.6)
    ax.set_axisbelow(True)


def main():
    df = pd.read_csv(SRC, parse_dates=["timestamp"]).set_index("timestamp")
    df = df.loc[:TRAIN_END].copy()
    y = df["electricity_demand_mw"]
    gw = y / 1000
    out = [f"# Exploratory analysis - training period only",
           "", f"Generated by `scripts/eda_training_period.py`. Rows used: {len(df):,} "
           f"({df.index.min()} to {df.index.max()}); demand observed in {int(y.notna().sum()):,} of them. "
           "No validation/test data is used. Correlations are descriptive, not evidence of causation.", ""]

    # ---- A/B: profiles
    prof = df.assign(gw=gw).groupby(["season", "hour"])["gw"].mean().unstack(0)[SEASON_ORDER]
    wk = df.assign(gw=gw, kind=np.where(df["is_holiday"] == 1, "holiday",
                    np.where(df["is_weekend"] == 1, "weekend", "weekday")))
    kind = wk.groupby(["kind", "hour"])["gw"].mean().unstack(0)
    out += ["## Daily profile",
            "Mean demand (GW) by season: " + "; ".join(f"{s}: {gw[df.season == s].mean():.1f}" for s in SEASON_ORDER),
            "Peak hour of the mean profile by season: " + "; ".join(
                f"{s}: {int(prof[s].idxmax()):02d}:00 ({prof[s].max():.0f} GW), trough {int(prof[s].idxmin()):02d}:00 ({prof[s].min():.0f} GW)"
                for s in SEASON_ORDER),
            "Weekday vs weekend vs holiday mean (GW): " + "; ".join(f"{k}: {kind[k].mean():.1f}" for k in kind.columns),
            f"Weekend mean is {100 * (1 - kind['weekend'].mean() / kind['weekday'].mean()):.1f}% below weekdays; "
            f"holidays {100 * (1 - kind['holiday'].mean() / kind['weekday'].mean()):.1f}% below weekdays (includes weekend holidays).", ""]

    # ---- trend
    weekly = gw.resample("W").mean()
    monthly = gw.groupby([gw.index.year, gw.index.month]).mean()
    pairs = []
    for (yy, mm), v in monthly.items():
        if (yy + 1, mm) in monthly.index:
            pairs.append((yy, yy + 1, mm, 100 * (monthly[(yy + 1, mm)] / v - 1)))
    pr = pd.DataFrame(pairs, columns=["from", "to", "month", "growth_pct"])
    out += ["## Level and growth",
            "Annual mean demand (GW), partial years marked: " + "; ".join(
                f"{yr}: {gw[gw.index.year == yr].mean():.1f}" for yr in (2021, 2022, 2023)) +
            " (2021 covers Sep-Dec only, so it is not comparable with full years).",
            "Year-over-year growth of monthly mean demand (matching months): " +
            "; ".join(f"{int(r['from'])}->{int(r['to'])} m{int(r['month'])}: {r['growth_pct']:+.1f}%" for _, r in pr.iterrows()),
            f"Average matched-month growth: {pr['growth_pct'].mean():+.1f}% (min {pr['growth_pct'].min():+.1f}%, max {pr['growth_pct'].max():+.1f}%). "
            "Weather differences between years are included in these numbers (e.g. a hot or cool October moves a single month by more than 20%). "
            f"Growth of the full-year mean 2022 -> 2023: {100 * (gw[gw.index.year == 2023].mean() / gw[gw.index.year == 2022].mean() - 1):+.1f}%.", ""]

    # ---- temperature response (de-seasonalised level)
    level = gw.rolling(24 * 28, center=True, min_periods=24 * 14).mean()
    ratio = (gw / level)
    sel = df["hour"].between(12, 16)
    t = df.loc[sel, "temp_c"]
    r = ratio[sel]
    bins = np.arange(np.floor(t.min()), np.ceil(t.max()) + 2, 2)
    grp = r.groupby(pd.cut(t, bins))
    stats = pd.DataFrame({"mid": [b.mid for b in grp.mean().index], "mean": grp.mean().values,
                          "q25": grp.quantile(.25).values, "q75": grp.quantile(.75).values,
                          "n": grp.size().values}).dropna()
    stats = stats[stats["n"] >= 30]
    out += ["## Temperature response (afternoon 12-16 h, demand relative to its centred 28-day mean)",
            "National mean temperature bins (deg C, width 2): " + "; ".join(
                f"{r_.mid:.0f}: {r_['mean']:.3f} (n={int(r_['n'])})" for _, r_ in stats.iterrows()),
            f"Pearson r between hourly national temperature and demand over the training period: {y.corr(df['temp_c']):.3f}; "
            f"between temperature and the de-levelled ratio (afternoon): {r.corr(t):.3f}.",
            "Caution: these numbers are confounded by season. Cool afternoons occur in winter, when the afternoon-to-daily-mean ratio is "
            "structurally larger, so the left side of the curve is not a pure heating effect. The curve is clearly non-linear (lowest around 30 deg C, "
            "rising on both sides), so a single linear temperature term would be a poor representation; the model should receive temperature "
            "together with hour and season and be allowed to learn the shape.", ""]

    # ---- holidays
    hol = pd.read_csv(HOL, parse_dates=["date"])
    hol = hol[hol["date"] <= TRAIN_END.normalize()]
    daily = gw.groupby(gw.index.normalize()).agg(["mean", "count"])
    dmean = daily["mean"].where(daily["count"] >= 22)
    hol_dates = set(hol["date"])
    rows = []
    for _, h in hol.iterrows():
        d0 = h["date"]
        if d0.dayofweek >= 5 or pd.isna(dmean.get(d0, np.nan)):
            continue
        ctrl = [d0 + pd.Timedelta(days=k) for k in (-14, -7, 7, 14)]
        ctrl = [c for c in ctrl if c not in hol_dates and not pd.isna(dmean.get(c, np.nan))]
        if len(ctrl) < 2:
            continue
        rows.append({"date": d0, "name": h["holiday_name"], "ratio": dmean[d0] / np.mean([dmean[c] for c in ctrl])})
    he = pd.DataFrame(rows)
    by = he.groupby("name")["ratio"].agg(["mean", "count"]).sort_values("mean")
    major = he[he["name"].isin(["Holi", "Diwali (Deepavali)", "Dussehra", "Id-ul-Fitr", "Christmas Day"])]
    out += ["## Holiday effect (weekday holidays only)",
            "Ratio = daily mean demand on the holiday / mean of the same weekday +-1 and +-2 weeks (non-holiday controls, >= 2 needed). "
            f"Holidays in the training period: {len(hol)}; usable weekday cases: {len(he)}.",
            f"Overall mean ratio: {he['ratio'].mean():.3f} (i.e. {100 * (he['ratio'].mean() - 1):+.1f}%). "
            f"Analyst-defined major festivals: {major['ratio'].mean():.3f} (n={len(major)}); others: "
            f"{he[~he.index.isin(major.index)]['ratio'].mean():.3f} (n={len(he) - len(major)}).",
            "By holiday (mean ratio, n): " + "; ".join(f"{n}: {m:.3f} (n={int(c)})" for n, (m, c) in by.iterrows()), ""]

    # ---- autocorrelation
    lags = list(range(1, 200))
    acf = pd.Series({k: y.autocorr(k) for k in lags})
    out += ["## Autocorrelation of demand (hourly lags)",
            "; ".join(f"lag {k} h: {acf[k]:.3f}" for k in (1, 2, 3, 6, 12, 24, 48, 168) if k in acf.index), ""]

    # ---- generation
    out += ["## Solar and wind (past values only are allowed as inputs)",
            f"Correlation with demand (all hours): solar {y.corr(df['solar_generation_mw']):.3f}, wind {y.corr(df['wind_generation_mw']):.3f}.",
            f"Mean solar by year (GW): " + "; ".join(f"{yr}: {df.loc[df.index.year == yr, 'solar_generation_mw'].mean() / 1000:.2f}" for yr in (2021, 2022, 2023)) +
            "; mean wind (GW): " + "; ".join(f"{yr}: {df.loc[df.index.year == yr, 'wind_generation_mw'].mean() / 1000:.2f}" for yr in (2021, 2022, 2023)) + ".",
            "These correlations mix season, time of day and capacity growth; they do not show a causal relation.", ""]

    # ---- D-07 evidence: how large is the drift a model must cope with
    anchor168 = y.shift(168)
    d_abs = (y - anchor168).abs()
    rel = (y / anchor168 - 1).abs()
    ratio_sd = (y / anchor168).std()
    drift = (gw.rolling(24 * 7).mean() / gw.rolling(24 * 7).mean().shift(24 * 7) - 1)
    out += ["## Evidence for the trend decision (D-07)",
            f"Seasonal-naive-168 (same hour last week) in the training period: MAE {d_abs.mean() / 1000:.2f} GW; MAPE {100 * rel.mean():.2f}%.",
            f"Week-over-week change of the weekly mean: median {100 * drift.median():+.2f}%, std {100 * drift.std():.2f}% - "
            "this shows how much the level moves from week to week (mostly seasonal), on top of the year-to-year growth reported above.",
            f"Std of the ratio y(t)/y(t-168): {ratio_sd:.3f}.",
            "Interpretation: demand is non-stationary in level. A tree model fitted on absolute MW cannot predict levels above the "
            "training maximum. This analysis does not examine later years; the earlier all-years data audit (not part of this analysis) "
            "indicated that demand keeps rising, so the issue is expected to matter and must be confirmed on validation. A target expressed relative to a lagged "
            "anchor removes most of the level drift. Recommendation (not yet frozen): primary candidate = ratio to the seasonal anchor; "
            "keep absolute MW as the comparison variant. The final choice must be made on VALIDATION results in Phase 5.", ""]
    REP.write_text("\n".join(out), encoding="utf-8")

    # ---- figure
    fig, axes = plt.subplots(2, 3, figsize=(15, 8.2), facecolor=SURFACE)
    ax = axes[0, 0]; style(ax)
    for s in SEASON_ORDER:
        c, ls = SEASON_STYLE[s]
        ax.plot(prof.index, prof[s], color=c, linestyle=ls, linewidth=1.8, label=s.replace("_", " "))
    ax.set_title("A  Mean daily profile by season", loc="left", fontsize=10, color=INK)
    ax.set_xlabel("Hour of day (IST)", color=INK2, fontsize=8); ax.set_ylabel("Demand (GW)", color=INK2, fontsize=9)
    ax.legend(frameon=False, fontsize=8, labelcolor=INK2, loc="upper center",
              bbox_to_anchor=(0.5, -0.17), ncol=2)
    ax = axes[0, 1]; style(ax)
    for k, (c, ls) in {"weekday": (BLUE, "-"), "weekend": (ORANGE, "--"), "holiday": (AQUA, "-.")}.items():
        ax.plot(kind.index, kind[k], color=c, linestyle=ls, linewidth=1.8, label=k)
    ax.set_title("B  Weekday vs weekend vs holiday", loc="left", fontsize=10, color=INK)
    ax.set_xlabel("Hour of day (IST)", color=INK2, fontsize=8); ax.legend(frameon=False, fontsize=8, labelcolor=INK2)
    ax = axes[0, 2]; style(ax)
    ax.plot(weekly.index, weekly.values, color=BLUE, linewidth=1.4)
    ax.set_title("C  Weekly mean demand (growth + season)", loc="left", fontsize=10, color=INK)
    ax.set_ylabel("Demand (GW)", color=INK2, fontsize=9)
    loc = mdates.MonthLocator(bymonth=[1, 7])
    ax.xaxis.set_major_locator(loc)
    ax.xaxis.set_major_formatter(mdates.DateFormatter("%b %Y"))
    ax = axes[1, 0]; style(ax)
    ax.fill_between(stats["mid"], stats["q25"], stats["q75"], color=BLUE, alpha=0.18, linewidth=0)
    ax.plot(stats["mid"], stats["mean"], color=BLUE, linewidth=1.8, marker="o", markersize=5)
    ax.set_title("D  Afternoon demand vs national temperature", loc="left", fontsize=10, color=INK)
    ax.set_xlabel("National mean temperature (deg C)", color=INK2, fontsize=8)
    ax.set_ylabel("Demand / 28-day level (mean, IQR band)", color=INK2, fontsize=8)
    ax = axes[1, 1]; style(ax)
    bn = by.copy(); bn["lab"] = [f"{n} (n={int(c)})" for n, c in zip(bn.index, bn["count"])]
    ax.barh(bn["lab"], bn["mean"] - 1, color=BLUE, height=0.6)
    ax.axvline(0, color=INK2, linewidth=0.8)
    ax.set_title("E  Weekday holiday effect (ratio to control days - 1)", loc="left", fontsize=10, color=INK)
    ax.tick_params(axis="y", labelsize=7); ax.grid(axis="x", color=GRID, linewidth=0.6); ax.grid(axis="y", visible=False)
    ax = axes[1, 2]; style(ax)
    ax.plot(acf.index, acf.values, color=BLUE, linewidth=1.4)
    for k in (24, 48, 168):
        ax.axvline(k, color=GRID, linewidth=1)
        ax.annotate(f"{k} h\n{acf[k]:.2f}", (k, acf[k]), textcoords="offset points", xytext=(4, 6), fontsize=8, color=INK2)
    ax.set_title("F  Autocorrelation of demand", loc="left", fontsize=10, color=INK)
    ax.set_xlabel("Lag (hours)", color=INK2, fontsize=8)
    fig.suptitle("Training period only (2021-09-01 to 2023-12-31): structure of all-India demand",
                 x=0.01, ha="left", fontsize=12, color=INK)
    fig.tight_layout(rect=(0, 0, 1, 0.96))
    FIG.parent.mkdir(parents=True, exist_ok=True)
    fig.savefig(FIG, dpi=140, facecolor=SURFACE)
    print(f"wrote {REP}\nwrote {FIG}")


if __name__ == "__main__":
    main()
