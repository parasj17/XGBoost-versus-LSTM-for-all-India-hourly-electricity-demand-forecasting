"""Exploratory XGBoost extensions: scenario C (archived forecast weather) and regional festivals (protocol deviation log, 2026-10-15).

Feature sets (features_tabular.EXTENSION_SETS): S2_ref = history + calendar + central holidays (reference), S6_forecastC = S2 + archived GFS forecast for the
target hour, S7_regionalFest = S2 + state-level holiday features, S8_both. Same recipe for every set: ratio target, stage-2 hyper-parameters of the
horizon, early stopping on validation (40 rounds, at most 3,000 trees), seeds 0-2, mean prediction. These are secondary results: the declared headline models
and all earlier numbers are unchanged.

  py scripts/run_extensions_xgb.py               validation only (the test period is not loaded)
  py scripts/run_extensions_xgb.py --with-test   adds the test period; runs ONCE (lock file reports/tables/EXTENSIONS_TEST_DONE.lock)
Outputs: reports/extensions_xgb.md (validation) or reports/extensions_xgb_test.md (validation + test).
"""
import argparse
import importlib
import sys
from pathlib import Path

import numpy as np
import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "scripts"))
rb = importlib.import_module("run_baselines")
ft = importlib.import_module("features_tabular")
rx = importlib.import_module("run_xgboost")
rt = importlib.import_module("run_test_evaluation")
LOCK = ROOT / "reports" / "tables" / "EXTENSIONS_TEST_DONE.lock"


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--with-test", action="store_true")
    args = ap.parse_args()
    if args.with_test and LOCK.exists():
        sys.exit("The extension test evaluation was already run; re-running would repeat a single-use evaluation.")
    commit, dirty = rb.git_state()
    if args.with_test and dirty:
        sys.exit("Working tree is not clean: commit first.")
    rx.MAX_TREES = 3000
    xgb_params, _, _ = rt.frozen_configs()
    df = pd.read_csv(rb.SRC, parse_dates=["timestamp"]).set_index("timestamp")
    df = df.loc[:(rt.TEST_END if args.with_test else rb.VAL_END)]
    md = ["# " + ("Extensions on validation and test" if args.with_test else "Extensions on validation") + " (generated by `scripts/run_extensions_xgb.py`)", "",
          f"Git commit `{(commit or 'n/a')[:10]}`. Secondary, exploratory results; recipe identical for all sets (ratio target, stage-2 hyper-parameters of the horizon, early stopping on validation, 3 seeds, "
          "mean prediction). Differences are MAE(set) minus MAE(S2_ref) in MW with 95% block-bootstrap intervals (negative = the extra features help). "
          "Forecast-weather caveat: the archive's 'previous_dayN' values are treated as available at the forecast origin; their exact issue time was not verified, so they may be slightly optimistic.", ""]
    for h in rb.HORIZONS:
        b = rb.build(df, h)
        Xs = {n: rb.design(b, rel, full) for n, (rel, full) in
              {"g01_abs": (False, False), "g01_rel": (True, False), "full_abs": (False, True), "full_rel": (True, True)}.items()}
        need = pd.concat(Xs.values(), axis=1).notna().all(axis=1) & b["y"].notna() & b["anchors"]["a24"].notna()
        if h <= 168:
            need &= b["anchors"]["a168"].notna()
        valid = need & b["target_obs"]
        Tt = b["T"]
        in_tr = valid & (Tt <= rb.TRAIN_END)
        in_va = valid & (Tt >= rb.VAL_START) & (Tt <= rb.VAL_END)
        in_te = valid & (Tt >= rt.TEST_START) & (Tt <= rt.TEST_END) if args.with_test else None
        a24 = b["anchors"]["a24"]
        a24v = a24.fillna(1.0).to_numpy()
        pos = np.arange(len(df))
        idx_va = pos[in_va.to_numpy()]
        y_va, a_va = b["target"].to_numpy()[idx_va], a24v[idx_va]
        if args.with_test:
            idx_te = pos[in_te.to_numpy()]
            y_te, a_te = b["target"].to_numpy()[idx_te], a24v[idx_te]
        zx = b["target"] / a24
        preds_va, preds_te, fc_missing = {}, {}, {}
        for sname, groups in ft.EXTENSION_SETS.items():
            X = ft.build_features(df, h, groups, True)
            if "g3f" in groups:
                fc_missing[sname] = (float(X["fc_temperature_2m_T"][in_tr].isna().mean()), float(X["fc_temperature_2m_T"][in_va].isna().mean()))
            pv, pt = [], []
            for sd in rt.SEEDS:
                p, m, *_ = rx.fit_predict(X[in_tr], zx[in_tr], X[in_va], zx[in_va], xgb_params[h], sd, a_va, True)
                pv.append(p)
                if args.with_test:
                    pt.append((1.0 + m.predict(X[in_te]) / 100.0) * a_te)
            preds_va[sname] = np.mean(pv, axis=0)
            if args.with_test:
                preds_te[sname] = np.mean(pt, axis=0)
        md += [f"## Horizon {h} h", ""]
        if fc_missing:
            md += ["Share of training / validation target hours with no archived forecast: " + "; ".join(f"{k}: {100 * a:.1f}% / {100 * c:.1f}%" for k, (a, c) in fc_missing.items()) + " (XGBoost handles the gaps as missing values).", ""]
        md += ["| set | validation MAE | vs S2_ref (95% CI)" + (" | test MAE | vs S2_ref (95% CI)" if args.with_test else "") + " |", "|---|---:|---|" + ("---:|---|" if args.with_test else "")]
        rng = np.random.default_rng(0)
        for sname in ft.EXTENSION_SETS:
            e = np.abs(preds_va[sname] - y_va)
            row = f"| {sname} | {e.mean():,.0f} | "
            if sname == "S2_ref":
                row += "-"
            else:
                d = e - np.abs(preds_va["S2_ref"] - y_va)
                lo, hi = rb.block_ci(d, rng)
                row += f"{d.mean():+,.0f} ({lo:+,.0f} to {hi:+,.0f})"
            if args.with_test:
                et = np.abs(preds_te[sname] - y_te)
                row += f" | {et.mean():,.0f} | "
                if sname == "S2_ref":
                    row += "-"
                else:
                    d = et - np.abs(preds_te["S2_ref"] - y_te)
                    lo, hi = rb.block_ci(d, rng)
                    row += f"{d.mean():+,.0f} ({lo:+,.0f} to {hi:+,.0f})"
            md.append(row + " |")
        md.append("")
        print(f"h={h} done", flush=True)
    out = ROOT / "reports" / ("extensions_xgb_test.md" if args.with_test else "extensions_xgb.md")
    out.write_text(chr(10).join(md) + chr(10), encoding="utf-8")
    if args.with_test:
        LOCK.write_text(f"extension test run completed at commit {commit}" + chr(10), encoding="utf-8")
    print("wrote", out)


if __name__ == "__main__":
    main()
