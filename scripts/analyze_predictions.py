"""Post-test analyses from the saved predictions (protocol deviation log, 2026-10-15).

Needs data/interim/predictions/h{1,6,24,48}.npz from `run_test_evaluation.py --export`.
Does NOT fit or select anything; every number is a function of the saved predictions and the validation residuals.

  1. hour-of-day breakdown (test)               -> reports/hour_of_day.md, reports/figures/test_hour_of_day.png
  2. robustness (test): samples whose 168 h input window contains imputed/rejected or stuck demand values excluded
                                                -> reports/robustness.md
  3. 90% prediction intervals (test), calibrated on VALIDATION residuals only:
       split conformal (absolute residuals), split conformal on residuals scaled by the 24 h anchor,
       rolling conformal (errors of forecasts whose target time <= origin, last 720 h; absolute),
       and, if present, XGBoost quantile regression raw and conformalised (CQR)
                                                -> reports/uncertainty.md
Usage: py scripts/analyze_predictions.py
"""
import math
from pathlib import Path

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt
import numpy as np
import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
PD = ROOT / "data" / "interim" / "predictions"
HORIZONS = [1, 6, 24, 48]
ALPHA = 0.10
WINDOW_H = 720
MODELS = {"xgb_S4_full_A": "XGBoost S4", "lstm_L4_full_A": "LSTM L4", "ridge_best": "ridge"}
SEASONS = ["winter", "pre_monsoon_summer", "monsoon", "post_monsoon"]
BLUE, ORANGE, AQUA, MAGENTA = "#2a78d6", "#eb6834", "#1baf7a", "#e87ba4"
INK, INK2, SURFACE, GRID = "#0b0b0b", "#52514e", "#fcfcfb", "#e4e3df"


def load(h):
    z = np.load(PD / f"h{h}.npz", allow_pickle=False)
    return {k: z[k] for k in z.files}


def best_naive(d):
    c = {k: np.mean(np.abs(d[f"te__{k}"] - d["y_te"])) for k in ("persistence", "snaive24", "snaive168")}
    return min(c, key=c.get)


def conf_q(scores, alpha=ALPHA):
    n = len(scores)
    k = min(math.ceil((n + 1) * (1 - alpha)), n)
    return float(np.sort(scores)[k - 1])


def interval_stats(y, lo, hi, alpha=ALPHA):
    cover = (y >= lo) & (y <= hi)
    width = hi - lo
    score = width + (2 / alpha) * np.maximum(lo - y, 0) + (2 / alpha) * np.maximum(y - hi, 0)
    return cover, width, score


def main():
    D = {h: load(h) for h in HORIZONS}
    # ---------------- 1. hour of day
    hod = ["# Hour-of-day breakdown on the test period (generated by `scripts/analyze_predictions.py`)", "",
           "MAE in MW by hour of the TARGET time (IST). Same predictions as `reports/test_results.md`; descriptive.", ""]
    fig, axes = plt.subplots(2, 2, figsize=(12, 7.2), facecolor=SURFACE)
    sty = {"xgb_S4_full_A": (BLUE, "-", "XGBoost S4"), "lstm_L4_full_A": (ORANGE, "--", "LSTM L4"), "ridge_best": (AQUA, "-.", "ridge"), "naive": (MAGENTA, ":", "best naive")}
    for ax, h in zip(axes.ravel(), HORIZONS):
        d = D[h]
        hours = pd.to_datetime(d["target_time_te"]).hour.to_numpy()
        bn = best_naive(d)
        preds = {"xgb_S4_full_A": d["te__xgb_S4_full_A"], "lstm_L4_full_A": d["te__lstm_L4_full_A"], "ridge_best": d["te__ridge_best"], "naive": d[f"te__{bn}"]}
        tab = pd.DataFrame({k: [np.mean(np.abs(v[hours == hr] - d["y_te"][hours == hr])) for hr in range(24)] for k, v in preds.items()})
        hod += [f"## Horizon {h} h (best naive: {bn})", "", "| hour | " + " | ".join(sty[k][2] for k in tab) + " |", "|---:|" + "---:|" * tab.shape[1]]
        for hr in range(24):
            hod.append(f"| {hr:02d} | " + " | ".join(f"{tab.loc[hr, k]:,.0f}" for k in tab) + " |")
        worst = tab["xgb_S4_full_A"].sort_values(ascending=False).head(3)
        hod += ["", "XGBoost S4 worst hours: " + "; ".join(f"{int(i):02d}:00 ({v:,.0f} MW)" for i, v in worst.items()) + ".", ""]
        ax.set_facecolor(SURFACE)
        for sp in ("top", "right"):
            ax.spines[sp].set_visible(False)
        for sp in ("left", "bottom"):
            ax.spines[sp].set_color(GRID)
        ax.grid(axis="y", color=GRID, linewidth=0.6)
        ax.tick_params(colors=INK2, labelsize=8)
        for k in tab:
            c, ls, lab = sty[k]
            ax.plot(range(24), tab[k] / 1000, color=c, linestyle=ls, linewidth=1.8, label=lab)
        ax.set_title(f"{h} h ahead", loc="left", fontsize=10, color=INK)
        ax.set_xlabel("Hour of target time (IST)", color=INK2, fontsize=8)
        ax.set_ylabel("MAE (GW)", color=INK2, fontsize=8)
        if h == 1:
            ax.legend(frameon=False, fontsize=8, labelcolor=INK2)
    fig.suptitle("Test period: error by hour of day", x=0.01, ha="left", fontsize=12, color=INK)
    fig.tight_layout(rect=(0, 0, 1, 0.95))
    (ROOT / "reports" / "figures").mkdir(exist_ok=True)
    fig.savefig(ROOT / "reports" / "figures" / "test_hour_of_day.png", dpi=140, facecolor=SURFACE)
    (ROOT / "reports" / "hour_of_day.md").write_text(chr(10).join(hod) + chr(10), encoding="utf-8")
    # ---------------- 2. robustness
    rb_ = ["# Robustness on the test period (generated by `scripts/analyze_predictions.py`)", "",
           "MAE in MW on all test samples versus samples whose 168-hour input window contains no imputed or rejected demand values (and, separately, no stuck-value hours). "
           "A model that is much better on the clean subset would be sensitive to the data-quality fixes.", "",
           "| horizon | subset | n | share | XGBoost S4 | LSTM L4 | ridge | best naive |", "|---:|---|---:|---:|---:|---:|---:|---:|"]
    for h in HORIZONS:
        d = D[h]
        bn = best_naive(d)
        for name, mask in (("all samples", np.ones(len(d["y_te"]), bool)), ("no imputed/rejected value in input window", d["window_has_imputed_te"] == 0),
                           ("no stuck-value hour in input window", d["window_has_stuck_te"] == 0)):
            f = lambda k: np.mean(np.abs(d[f"te__{k}"][mask] - d["y_te"][mask]))
            rb_.append(f"| {h} | {name} | {int(mask.sum()):,} | {100 * mask.mean():.1f}% | {f('xgb_S4_full_A'):,.0f} | {f('lstm_L4_full_A'):,.0f} | {f('ridge_best'):,.0f} | {f(bn):,.0f} |")
    rb_ += ["", "Seed spread of the headline models (MAE of each seed's prediction; the headline uses the mean prediction of the three seeds):", "",
            "| horizon | XGBoost S4 per seed | LSTM L4 per seed | LSTM L1 per seed |", "|---:|---|---|---|"]
    for h in HORIZONS:
        d = D[h]
        s = lambda k: ", ".join(f"{np.mean(np.abs(q - d['y_te'])):,.0f}" for q in d[f"te__{k}__perseed"])
        rb_.append(f"| {h} | {s('xgb_S4_full_A')} | {s('lstm_L4_full_A')} | {s('lstm_L1_history_calendar')} |")
    rb_ += ["", "Other robustness checks already on record: weather aggregation weights (`reports/sensitivity_summary.md`: at most 41 MW on validation for ridge), "
            "training on hourly-mean targets (same file), rolling-origin folds (`reports/rolling_origin.md`)."]
    (ROOT / "reports" / "robustness.md").write_text(chr(10).join(rb_) + chr(10), encoding="utf-8")
    # ---------------- 3. intervals
    un = ["# 90% prediction intervals on the test period (generated by `scripts/analyze_predictions.py`)", "",
          "Calibration uses validation residuals only (or, for the rolling variant, errors of forecasts whose target time is not later than the forecast origin). "
          "Nominal coverage 90%. PICP = share of test hours inside the interval; width in MW; interval score = width + (2/alpha) x penalty for misses (lower is better). "
          "Demand grew between validation and test and the test year was harder to forecast, so intervals calibrated on validation are expected to under-cover; "
          "split conformal guarantees coverage only for exchangeable data.", ""]
    rows = []
    cov_detail = []
    for h in HORIZONS:
        d = D[h]
        y, a_te, a_va = d["y_te"], d["a24_te"], d["a24_va"]
        origin_te = d["origin_te"]
        T_all = np.concatenate([d["target_time_va"], d["target_time_te"]])
        order = np.argsort(T_all, kind="stable")
        season = d["season_te"]
        hours = pd.to_datetime(d["target_time_te"]).hour.to_numpy()
        for m, lab in MODELS.items():
            p_te, p_va = d[f"te__{m}"], d[f"va__{m}"]
            e_va = np.abs(d["y_va"] - p_va)
            e_all = np.concatenate([e_va, np.abs(y - p_te)])[order]
            Ts = T_all[order]
            variants = {}
            q = conf_q(e_va)
            variants["split conformal (absolute)"] = (p_te - q, p_te + q)
            qs = conf_q(e_va / a_va)
            variants["split conformal (scaled by anchor)"] = (p_te - qs * a_te, p_te + qs * a_te)
            lo_r, hi_r = np.empty_like(p_te), np.empty_like(p_te)
            for j in range(len(p_te)):
                hi_i = np.searchsorted(Ts, origin_te[j], side="right")
                lo_i = np.searchsorted(Ts, origin_te[j] - WINDOW_H * 3600 * 10 ** 9, side="right")
                sc = e_all[lo_i:hi_i]
                qq = conf_q(sc) if len(sc) >= 100 else q
                lo_r[j], hi_r[j] = p_te[j] - qq, p_te[j] + qq
            variants["rolling conformal (last 720 h of known errors)"] = (lo_r, hi_r)
            qname = {"xgb_S4_full_A": ("xgb_quantile", "XGBoost quantile regression"), "lstm_L4_full_A": ("lstm_quantile", "LSTM quantile head")}.get(m)
            qf = ROOT / "data" / "interim" / "predictions" / f"{qname[0]}_h{h}.npz" if qname else None
            if qf is not None and qf.exists():
                z = np.load(qf)
                l_te, u_te, l_va, u_va = z["q05_te"], z["q95_te"], z["q05_va"], z["q95_va"]
                variants[f"{qname[1]}, raw 5%-95%"] = (l_te, u_te)
                E = np.maximum(l_va - d["y_va"], d["y_va"] - u_va)
                qc = conf_q(E)
                variants[f"{qname[1]} + CQR"] = (l_te - qc, u_te + qc)
            for vname, (lo, hi) in variants.items():
                cover, width, score = interval_stats(y, lo, hi)
                rows.append((h, lab, vname, cover.mean(), width.mean(), score.mean()))
                if lab == "XGBoost S4" and vname in ("split conformal (absolute)", "rolling conformal (last 720 h of known errors)"):
                    cov_detail.append((h, vname, {s: cover[season == s].mean() for s in SEASONS}, {f"{a:02d}-{a + 5:02d}h": cover[(hours >= a) & (hours <= a + 5)].mean() for a in (0, 6, 12, 18)}))
    un += ["| horizon | point forecast | interval method | PICP | mean width (MW) | interval score (MW) |", "|---:|---|---|---:|---:|---:|"]
    for h, lab, v, pc, w, sc in rows:
        un.append(f"| {h} | {lab} | {v} | {100 * pc:.1f}% | {w:,.0f} | {sc:,.0f} |")
    un += ["", "Coverage of the XGBoost S4 intervals by season and by hour of the target time:", "", "| horizon | method | " + " | ".join(SEASONS) + " | 00-05h | 06-11h | 12-17h | 18-23h |", "|---:|---|" + "---:|" * 8]
    for h, v, sd, hd in cov_detail:
        un.append(f"| {h} | {v} | " + " | ".join(f"{100 * sd[s]:.0f}%" for s in SEASONS) + " | " + " | ".join(f"{100 * hd[k]:.0f}%" for k in hd) + " |")
    (ROOT / "reports" / "uncertainty.md").write_text(chr(10).join(un) + chr(10), encoding="utf-8")
    print("wrote reports/hour_of_day.md, reports/robustness.md, reports/uncertainty.md")


if __name__ == "__main__":
    main()
