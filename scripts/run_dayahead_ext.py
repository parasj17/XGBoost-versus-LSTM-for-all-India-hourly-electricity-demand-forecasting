"""Part P2 (a), (b), (d), (e) of the completion batch: day-ahead completions (docs/experiment_protocol.md, entry of 2026-10-19). Same task, samples and rules as scripts/run_dayahead.py.
  (a) XGBoost S4 with ONE MODEL PER TARGET HOUR (one parameter set for all hours, 30 random trials of the stage-1 space chosen by the pooled validation MAE; trees per hour by early stopping on
      that hour's validation days; 3 seeds)
  (b) LSTM L1 (history + calendar inputs), pooled over the target hours (30 random trials of the stage-3 space, 3 seeds)
  (d) feature ablation of the pooled XGBoost (hyper-parameters of the day-ahead S4 model): S0, S1, S2, S3, S5 (oracle weather, upper bound) and S6 (S2 + archived temperature forecasts)
  (e) XGBoost quantile regression (5% / 95%, pooled S4 features, hyper-parameters of the day-ahead S4 model, one seed, trees by early stopping on validation)
  py scripts/run_dayahead_ext.py               PHASE 1 (validation only; test not loaded): writes reports/tables/dayahead_ext_config.json, reports/dayahead_ext_validation.md, data/interim/predictions/dayahead_ext_val.npz
  py scripts/run_dayahead_ext.py --with-test   PHASE 2: single test evaluation with the frozen configuration (lock reports/tables/DAYAHEAD_EXT_TEST_DONE.lock) -> reports/dayahead_ext_test.md, dayahead_ext.npz
"""
import argparse
import importlib
import json
import sys
import time
from pathlib import Path

import numpy as np
import pandas as pd
import xgboost as xgb

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "scripts"))
rb = importlib.import_module("run_baselines")
ft = importlib.import_module("features_tabular")
rx = importlib.import_module("run_xgboost")
rl = importlib.import_module("run_lstm")
rt = importlib.import_module("run_test_evaluation")
r3 = importlib.import_module("run_lstm_stage3")
rda = importlib.import_module("run_dayahead")
T = ROOT / "reports" / "tables"
CONFIG, LOCK = T / "dayahead_ext_config.json", T / "DAYAHEAD_EXT_TEST_DONE.lock"
PRED = ROOT / "data" / "interim" / "predictions"
LEADS, SEEDS, N_XGB, N_LSTM = rda.LEADS, rda.SEEDS, 30, 30
ABL = {"S0_history": ft.FEATURE_SETS["S0_history"], "S1_calendar": ft.FEATURE_SETS["S1_calendar"], "S2_holidays": ft.FEATURE_SETS["S2_holidays"], "S3_weatherA": ft.FEATURE_SETS["S3_weatherA"],
       "S5_oracle_B": ft.FEATURE_SETS["S5_oracle_B"], "S6_forecastC": ft.EXTENSION_SETS["S6_forecastC"]}


def feat(df, h, groups):
    X = ft.build_features(df, h, groups, True)
    X["lead"] = float(h)
    return X


def main():
    global LEADS_USED, N_XGB, N_LSTM
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--with-test", action="store_true")
    ap.add_argument("--smoke", action="store_true")
    args = ap.parse_args()
    rx.MAX_TREES = 3000
    commit, dirty = rb.git_state()
    LEADS_USED = LEADS
    if args.smoke:
        LEADS_USED, N_XGB, N_LSTM = [14, 26, 37], 1, 1
    if args.with_test:
        if LOCK.exists():
            sys.exit("The day-ahead completion test evaluation was already run.")
        if dirty:
            sys.exit("Working tree is not clean: commit first.")
        cfg = json.loads(CONFIG.read_text(encoding="utf-8"))
    base = json.loads(rda.CONFIG.read_text(encoding="utf-8"))
    xp_base = base["xgb"]["params"]
    df = pd.read_csv(rb.SRC, parse_dates=["timestamp"]).set_index("timestamp").loc[:(rt.TEST_END if args.with_test else rb.VAL_END)]
    y_all = df["electricity_demand_mw"].ffill().to_numpy(dtype=float)
    D = rda.collect(df, LEADS_USED, args.with_test)
    ev = "te" if args.with_test else "va"
    splits = ["tr", "va"] + (["te"] if args.with_test else [])

    def cat(f, split):
        return np.concatenate([f(D[h], D[h]["pos"][split]) for h in LEADS_USED])

    def meta(split):
        return {"lead": np.concatenate([np.full(len(D[h]["pos"][split]), h) for h in LEADS_USED]), "pos": np.concatenate([D[h]["pos"][split] for h in LEADS_USED]),
                "a24": cat(lambda d, p: d["a24v"][p], split), "y": cat(lambda d, p: d["target"][p], split), "zx": cat(lambda d, p: d["zx"].to_numpy()[p], split),
                "T": cat(lambda d, p: d["T"].to_numpy()[p].astype("datetime64[ns]").astype("int64"), split), "season": cat(lambda d, p: d["b"]["season_T"].to_numpy()[p], split).astype(str)}

    M = {s: meta(s) for s in splits}
    zv = np.load(PRED / ("dayahead.npz" if args.with_test else "dayahead_val.npz"), allow_pickle=True)
    if not args.smoke:
        assert np.allclose(zv["y"], M[ev]["y"]) and np.array_equal(zv["T"], M[ev]["T"]), "row order differs from the day-ahead run"
    E = M[ev]
    mae = lambda p: float(np.mean(np.abs(p - E["y"])))
    t0 = time.perf_counter()
    md = ["# " + ("Day-ahead completions: single test evaluation" if args.with_test else "Day-ahead completions: validation") + " (generated by `scripts/run_dayahead_ext.py`; part P2 of the completion batch)", "",
          f"Git commit `{(commit or 'n/a')[:10]}`. Same task, samples and rules as the day-ahead model; scenario A unless labelled. MAE in MW over all (day, hour) samples ({len(E['y']):,}). "
          + ("Models fitted on the training period only with the validation-chosen configuration." if args.with_test else "Hyper-parameters chosen on validation; early stopping on validation (mildly optimistic)."), ""]
    out_cfg, preds, rows = {}, {}, []

    # ---------------- (a) XGBoost S4, one model per target hour
    def perhour(params, seed, pred_split, trees=None):
        out, tr_out = [], {}
        for h in LEADS_USED:
            d = D[h]
            Xf = d["Xf"]
            ptr, pp = d["pos"]["tr"], d["pos"][pred_split]
            ztr = d["zx"].to_numpy()[ptr]
            a_p = d["a24v"][pp]
            if trees is None:
                pv = d["pos"]["va"]
                p, m, *_ = rx.fit_predict(Xf.iloc[ptr], ztr, Xf.iloc[pv], d["zx"].to_numpy()[pv], params, seed, d["a24v"][pv], True)
                tr_out[h] = int(m.best_iteration) + 1
                out.append(p)
            else:
                mdl = xgb.XGBRegressor(n_estimators=trees[str(h)][str(seed)], objective="reg:squarederror", tree_method="hist", device="cpu", n_jobs=rx.NJOBS, random_state=seed, eval_metric="mae", **params)
                mdl.fit(Xf.iloc[ptr], (ztr - 1.0) * 100.0, verbose=False)
                out.append((1.0 + mdl.predict(Xf.iloc[pp]) / 100.0) * a_p)
        return np.concatenate(out), tr_out

    if not args.with_test:
        r_, best = np.random.default_rng(8600), None
        for _ in range(N_XGB):
            prm = rx.sample_params(r_)
            p, _t = perhour(prm, 0, "va")
            m_ = mae(p)
            if best is None or m_ < best[0]:
                best = (m_, prm)
        ps, trees = [], {str(h): {} for h in LEADS_USED}
        for sd in SEEDS:
            p, tr_o = perhour(best[1], sd, "va")
            ps.append(p)
            for h, v in tr_o.items():
                trees[str(h)][str(sd)] = v
        out_cfg["xgb_perhour"] = {"params": best[1], "trees": trees}
        print("per-hour xgb", mae(np.mean(ps, axis=0)), flush=True)
    else:
        c = cfg["xgb_perhour"]
        ps = [perhour(c["params"], sd, "te", c["trees"])[0] for sd in SEEDS]
    preds["xgb_perhour"] = np.mean(ps, axis=0)

    # ---------------- (b) LSTM L1 (history + calendar), pooled
    S1 = {h: rl.static_features(df, h, D[h]["b"], False) for h in LEADS_USED}
    C1 = rl.step_channels(df, False, False, rb.TRAIN_END)
    n_in1, n_st1 = C1.shape[1] + 1, S1[LEADS_USED[0]].shape[1]
    ztr = (M["tr"]["zx"] - 1.0) * 100
    zsd = float(np.nanstd(ztr))

    def pooled(split):
        S = np.concatenate([S1[h][D[h]["pos"][split]] for h in LEADS_USED])
        return rda.Pooled(y_all, C1, M[split]["pos"], M[split]["a24"], S, np.nan_to_num(((M[split]["zx"] - 1.0) * 100) / zsd))

    trD, eD = pooled("tr"), pooled(ev)
    if not args.with_test:
        r2, cands = np.random.default_rng(9600), []
        for k in range(N_LSTM):
            hp = r3.sample_hp(r2)
            m_, *_ = r3.trial_fit(trD, eD, n_in1, n_st1, hp, zsd, E["a24"], E["y"], None)
            cands.append((m_, hp))
        sel = min(cands, key=lambda x: x[0])
        epochs, lp = {}, []
        for sd in SEEDS:
            net, m_, hist, *_ = rl.train(trD, eD, n_in1, n_st1, sel[1], sd, 30, 5, zsd, E["a24"], E["y"])
            epochs[sd] = int(np.argmin(hist)) + 1
            lp.append((1 + rl.predict(net, eD, len(E["y"])) * zsd / 100.0) * E["a24"])
        out_cfg["lstm_l1"] = {"params": sel[1], "epochs": {str(k): v for k, v in epochs.items()}, "zsd": zsd}
        print("lstm L1", mae(np.mean(lp, axis=0)), epochs, flush=True)
    else:
        c = cfg["lstm_l1"]
        lp = [(1 + rl.predict(rt.lstm_fit_fixed(trD, n_in1, n_st1, c["params"], sd, c["epochs"][str(sd)]), eD, len(E["y"])) * zsd / 100.0) * E["a24"] for sd in SEEDS]
    preds["lstm_l1"] = np.mean(lp, axis=0)

    # ---------------- (d) feature ablation of the pooled XGBoost
    def pooled_x(Xs_by_lead, split):
        return pd.concat([Xs_by_lead[h].iloc[D[h]["pos"][split]] for h in LEADS_USED])

    out_cfg["ablation"] = {}
    for name, groups in ABL.items():
        XL = {h: feat(df, h, groups) for h in LEADS_USED}
        Xtr, Xe = pooled_x(XL, "tr"), pooled_x(XL, ev)
        if not args.with_test:
            tr_o, ps = {}, []
            for sd in SEEDS:
                p, m, *_ = rx.fit_predict(Xtr, M["tr"]["zx"], Xe, E["zx"], xp_base, sd, E["a24"], True)
                tr_o[str(sd)] = int(m.best_iteration) + 1
                ps.append(p)
            out_cfg["ablation"][name] = tr_o
        else:
            ps = []
            for sd in SEEDS:
                mdl = xgb.XGBRegressor(n_estimators=cfg["ablation"][name][str(sd)], objective="reg:squarederror", tree_method="hist", device="cpu", n_jobs=rx.NJOBS, random_state=sd, eval_metric="mae", **xp_base)
                mdl.fit(Xtr, (M["tr"]["zx"] - 1.0) * 100.0, verbose=False)
                ps.append((1.0 + mdl.predict(Xe) / 100.0) * E["a24"])
        preds["xgb_" + name] = np.mean(ps, axis=0)
        print("ablation", name, mae(preds["xgb_" + name]), flush=True)

    # ---------------- (e) quantile regression (5% / 95%), pooled S4 features
    QS = np.array([0.05, 0.95])
    XL = {h: D[h]["Xf"] for h in LEADS_USED}
    Xtr, Xe = pooled_x(XL, "tr"), pooled_x(XL, ev)
    ztr_pct = (M["tr"]["zx"] - 1.0) * 100.0
    if not args.with_test:
        mq = xgb.XGBRegressor(n_estimators=3000, objective="reg:quantileerror", quantile_alpha=QS, tree_method="hist", device="cpu", n_jobs=rx.NJOBS, random_state=0, early_stopping_rounds=40, **xp_base)
        mq.fit(Xtr, ztr_pct, eval_set=[(Xe, (E["zx"] - 1.0) * 100.0)], verbose=False)
        out_cfg["quantile"] = {"trees": int(mq.best_iteration) + 1}
    else:
        mq = xgb.XGBRegressor(n_estimators=cfg["quantile"]["trees"], objective="reg:quantileerror", quantile_alpha=QS, tree_method="hist", device="cpu", n_jobs=rx.NJOBS, random_state=0, **xp_base)
        mq.fit(Xtr, ztr_pct, verbose=False)
    Pq = np.sort(mq.predict(Xe), axis=1)
    preds["q05"], preds["q95"] = (1.0 + Pq[:, 0] / 100.0) * E["a24"], (1.0 + Pq[:, 1] / 100.0) * E["a24"]
    print("quantile raw coverage", float(np.mean((E["y"] >= preds["q05"]) & (E["y"] <= preds["q95"]))), flush=True)

    # ---------------- report
    base_mae = {"XGBoost S4, pooled (day-ahead model)": mae(zv["xgb"]), "ridge (day-ahead model)": mae(zv["ridge"]), "LSTM L4, pooled (day-ahead model)": mae(zv["lstm"])} if not args.smoke else {"XGBoost S4, pooled (day-ahead model)": 0.0, "ridge (day-ahead model)": 0.0, "LSTM L4, pooled (day-ahead model)": 0.0}
    md += ["| model | " + ("test" if args.with_test else "validation") + " MAE (MW) |", "|---|---:|"] + [f"| {k} | {v:,.0f} |" for k, v in base_mae.items()]
    md += [f"| XGBoost S4, one model per target hour | {mae(preds['xgb_perhour']):,.0f} |", f"| LSTM L1 (history + calendar), pooled | {mae(preds['lstm_l1']):,.0f} |", ""]
    md += ["## Feature ablation of the pooled XGBoost (hyper-parameters of the day-ahead S4 model)", "", "| feature set | MAE (MW) |", "|---|---:|"]
    for name in ABL:
        md.append(f"| {name}{' (oracle weather, upper bound)' if name == 'S5_oracle_B' else (' (archived temperature forecasts; issue times unverified)' if name == 'S6_forecastC' else '')} | {mae(preds['xgb_' + name]):,.0f} |")
    md.append(f"| S4_full_A (the day-ahead model) | {base_mae['XGBoost S4, pooled (day-ahead model)']:,.0f} |")
    cov = float(np.mean((E["y"] >= preds["q05"]) & (E["y"] <= preds["q95"])))
    md += ["", f"## XGBoost quantile regression (raw 5%-95% interval)", "", f"Raw coverage {100 * cov:.1f}% (nominal 90%), mean width {np.mean(preds['q95'] - preds['q05']):,.0f} MW; conformal calibration and comparison with the other interval methods are in the analysis report.", "",
           f"Run time {time.perf_counter() - t0:,.0f} s.", ""]
    if args.smoke:
        print(chr(10).join(md))
        print("smoke finished (nothing written)")
        return
    np.savez_compressed(PRED / ("dayahead_ext.npz" if args.with_test else "dayahead_ext_val.npz"), y=E["y"], lead=E["lead"], T=E["T"], season=E["season"], **preds)
    if args.with_test:
        (ROOT / "reports" / "dayahead_ext_test.md").write_text(chr(10).join(md) + chr(10), encoding="utf-8")
        LOCK.write_text(f"day-ahead completion test run completed at commit {commit}" + chr(10), encoding="utf-8")
    else:
        CONFIG.write_text(json.dumps(out_cfg, indent=1), encoding="utf-8")
        (ROOT / "reports" / "dayahead_ext_validation.md").write_text(chr(10).join(md) + chr(10), encoding="utf-8")
    print("done")


if __name__ == "__main__":
    main()
