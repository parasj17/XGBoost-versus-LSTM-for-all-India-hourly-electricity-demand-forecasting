"""Diagnostic learning curve (protocol deviation log, 2026-10-15): does the LSTM gain more from extra data than XGBoost?

Models keep their frozen stage-2 hyper-parameters:
  XGBoost S1_calendar and S4_full_A (ratio target), parameters from reports/tables/xgboost_validation_wide.jsonl
  LSTM L1_history_calendar, parameters = best stage-2 tuning trial of reports/tables/lstm_validation_stage2_L1.jsonl
Training subsets: most recent 12 months and 18 months of the training period (targets 2023-01..2023-12 and
2022-07..2023-12). The full-period numbers come from the existing logs (mean of 3 seeds of the per-seed validation MAE).
Validation samples are identical to all earlier runs. The test period is never loaded.

Outputs: reports/learning_curve.md, reports/tables/learning_curve.jsonl.   Usage: py scripts/run_learning_curve.py [--smoke]
"""
import argparse
import importlib
import json
import sys
import time
from pathlib import Path

import numpy as np
import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "scripts"))
rb = importlib.import_module("run_baselines")
ft = importlib.import_module("features_tabular")
rx = importlib.import_module("run_xgboost")
rl = importlib.import_module("run_lstm")

T = ROOT / "reports" / "tables"
SIZES = {"12 months": pd.Timestamp("2023-01-01"), "18 months": pd.Timestamp("2022-07-01")}


def best_lstm_params(h):
    best = None
    for line in open(T / "lstm_validation_stage2_L1.jsonl", encoding="utf-8"):
        r = json.loads(line)
        if r["stage"] == "tuning_trial" and r["horizon"] == h and (best is None or r["val_MAE_MW"] < best["val_MAE_MW"]):
            best = r
    return best["params"]


def xgb_params(h):
    for line in open(T / "xgboost_validation_wide.jsonl", encoding="utf-8"):
        r = json.loads(line)
        if r["stage"] == "ablation_fit" and r["horizon"] == h and r["feature_set"] == "S4_full_A" and r["relative_target"] and r["seed"] == 0:
            return r["params"]


def full_means(h):
    """Mean over seeds of the per-seed validation MAE from the existing full-data runs."""
    out = {"XGB S1_calendar": [], "XGB S4_full_A": [], "LSTM L1": []}
    for line in open(T / "xgboost_validation_wide.jsonl", encoding="utf-8"):
        r = json.loads(line)
        if r["stage"] == "ablation_fit" and r["horizon"] == h and r["relative_target"]:
            if r["feature_set"] == "S1_calendar":
                out["XGB S1_calendar"].append(r["val_MAE_MW"])
            if r["feature_set"] == "S4_full_A":
                out["XGB S4_full_A"].append(r["val_MAE_MW"])
    for line in open(T / "lstm_validation_stage2_L1.jsonl", encoding="utf-8"):
        r = json.loads(line)
        if r["stage"] == "final_fit" and r["horizon"] == h:
            out["LSTM L1"].append(r["val_MAE_MW"])
    return {k: float(np.mean(v)) for k, v in out.items()}


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--smoke", action="store_true")
    args = ap.parse_args()
    horizons, seeds = rb.HORIZONS, [0, 1, 2]
    out_md, out_jsonl = ROOT / "reports" / "learning_curve.md", T / "learning_curve.jsonl"
    if args.smoke:
        horizons, seeds = [24], [0]
        rl.FINAL_EPOCHS = 2
        out_md, out_jsonl = out_md.with_name("learning_curve_smoke.md"), out_jsonl.with_name("learning_curve_smoke.jsonl")
    rx.MAX_TREES = 3000
    df = pd.read_csv(rb.SRC, parse_dates=["timestamp"]).set_index("timestamp").loc[:rb.VAL_END]
    commit, dirty = rb.git_state()
    log = open(out_jsonl, "a", encoding="utf-8")
    y = df["electricity_demand_mw"].ffill().to_numpy(dtype=float)
    md = ["# Diagnostic learning curve (generated by `scripts/run_learning_curve.py`)", "",
          f"Git commit `{(commit or 'n/a')[:10]}` (dirty: {dirty}). Validation period only; the test period was not loaded. Frozen stage-2 hyper-parameters; "
          "3 seeds; MAE in MW is the mean over seeds of the per-seed validation MAE (not the MAE of an averaged prediction). "
          "Only three training sizes and one hyper-parameter set per model: the pattern is descriptive, not a proof of why a model wins. "
          "'LSTM / XGB S1' compares models that receive the same information (history + calendar).", ""]
    for h in horizons:
        b = rb.build(df, h)
        Xs = {n: rb.design(b, rel, full) for n, (rel, full) in
              {"g01_abs": (False, False), "g01_rel": (True, False), "full_abs": (False, True), "full_rel": (True, True)}.items()}
        need = pd.concat(Xs.values(), axis=1).notna().all(axis=1) & b["y"].notna() & b["anchors"]["a24"].notna()
        if h <= 168:
            need &= b["anchors"]["a168"].notna()
        valid = need & b["target_obs"]
        in_va = valid & (b["T"] >= rb.VAL_START) & (b["T"] <= rb.VAL_END)
        in_tr_full = valid & (b["T"] <= rb.TRAIN_END)
        a24 = b["anchors"]["a24"]
        a24v = a24.fillna(1.0).to_numpy()
        pos = np.arange(len(df))
        idx_va = pos[in_va.to_numpy()]
        y_va, a_va = b["target"].to_numpy()[idx_va], a24v[idx_va]
        z_all = ((b["target"] / a24 - 1) * 100).to_numpy()
        zsd = float(np.nanstd(z_all[pos[in_tr_full.to_numpy()]]))     # full-training statistics, as in the main run
        zt = np.nan_to_num(z_all / zsd)
        C = rl.step_channels(df, False, False, rb.TRAIN_END)
        S = rl.static_features(df, h, b, False)
        va = rl.Data(y, a24v, C, S, zt, idx_va)
        feats = {s: ft.build_features(df, h, ft.FEATURE_SETS[s], True) for s in ("S1_calendar", "S4_full_A")}
        zx = b["target"] / a24
        hp_l, prm = best_lstm_params(h), xgb_params(h)
        full = full_means(h)
        results = {"full (2.3 yr)": {"n": int(in_tr_full.sum()), **full}}
        for size, start in SIZES.items():
            in_tr = in_tr_full & (b["T"] >= start)
            res = {"n": int(in_tr.sum())}
            for sname in ("S1_calendar", "S4_full_A"):
                Xf = feats[sname]
                maes = [float(np.mean(np.abs(rx.fit_predict(Xf[in_tr], zx[in_tr], Xf[in_va], zx[in_va], prm, sd, a_va, True)[0] - y_va)))
                        for sd in seeds]
                res[f"XGB {sname}"] = float(np.mean(maes))
            tr = rl.Data(y, a24v, C, S, zt, pos[in_tr.to_numpy()])
            maes = []
            for sd in seeds:
                t0 = time.perf_counter()
                net, mae, hist, wall, cpu, peak = rl.train(tr, va, C.shape[1] + 1, S.shape[1], hp_l, sd, rl.FINAL_EPOCHS, rl.FINAL_PATIENCE, zsd, a_va, y_va)
                maes.append(mae)
            res["LSTM L1"] = float(np.mean(maes))
            results[size] = res
            log.write(json.dumps({"horizon": h, "size": size, "git_commit": commit, **res}) + chr(10)); log.flush()
            print(f"h={h} {size}: n={res['n']} XGB S1 {res['XGB S1_calendar']:.0f} S4 {res['XGB S4_full_A']:.0f} LSTM L1 {res['LSTM L1']:.0f}", flush=True)
        md += [f"## Horizon {h} h", "", "| training data | samples | XGB S1_calendar | XGB S4_full_A | LSTM L1 | LSTM / XGB S1 |", "|---|---:|---:|---:|---:|---:|"]
        for size in ("12 months", "18 months", "full (2.3 yr)"):
            r = results[size]
            md.append(f"| {size} | {r['n']:,} | {r['XGB S1_calendar']:,.0f} | {r['XGB S4_full_A']:,.0f} | {r['LSTM L1']:,.0f} | {r['LSTM L1'] / r['XGB S1_calendar']:.2f} |")
        md.append("")
    out_md.write_text(chr(10).join(md) + chr(10), encoding="utf-8")
    log.close()
    print("wrote", out_md)


if __name__ == "__main__":
    main()
