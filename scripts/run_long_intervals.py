"""90% prediction intervals at the long horizons 72 h and 168 h (extension (2) of the deviation-log entry of 2026-10-16).

Point models: the long-horizon configurations of reports/tables/long_horizon_config.json (ridge variant/penalty, XGBoost S4 trees/parameters, LSTM L4 parameters/epochs), fitted on the
training period, 3 seeds, mean prediction. Intervals (nominal 90%): split conformal on absolute residuals, split conformal on residuals scaled by the 24-hour-style anchor,
rolling conformal (errors of forecasts whose target time <= the origin, last 720 h), XGBoost quantile regression (5%/95%, early stopping on validation) raw and conformalised (CQR),
LSTM quantile head (pinball loss, early stopping on validation, 3 seeds averaged) raw and conformalised. Calibration uses validation only.
  py scripts/run_long_intervals.py --check   dry run: the 'test' window is the VALIDATION period (the test period is not loaded; calibration = evaluation, so numbers are meaningless)
  py scripts/run_long_intervals.py           single test evaluation (lock reports/tables/LONG_INTERVALS_TEST_DONE.lock); writes reports/long_uncertainty.md
"""
import argparse
import copy
import importlib
import json
import sys
from pathlib import Path

import numpy as np
import pandas as pd
import torch
import xgboost as xgb

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "scripts"))
rb = importlib.import_module("run_baselines")
ft = importlib.import_module("features_tabular")
rx = importlib.import_module("run_xgboost")
rl = importlib.import_module("run_lstm")
rt = importlib.import_module("run_test_evaluation")
rql = importlib.import_module("run_quantile_lstm")
ap_ = importlib.import_module("analyze_predictions")
T = ROOT / "reports" / "tables"
LOCK = T / "LONG_INTERVALS_TEST_DONE.lock"
WINDOW_H = 720


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()
    rx.MAX_TREES = 3000
    commit, dirty = rb.git_state()
    if not args.check:
        if LOCK.exists():
            sys.exit("The long-horizon interval test evaluation was already run.")
        if dirty:
            sys.exit("Working tree is not clean: commit first.")
    cfg = json.loads((T / "long_horizon_config.json").read_text(encoding="utf-8"))
    ev0, ev1 = (rb.VAL_START, rb.VAL_END) if args.check else (rt.TEST_START, rt.TEST_END)
    df = pd.read_csv(rb.SRC, parse_dates=["timestamp"]).set_index("timestamp").loc[:ev1]
    y_all = df["electricity_demand_mw"].ffill().to_numpy(dtype=float)
    md = ["# " + ("CHECK (validation as the evaluation window; not a result)" if args.check else "90% prediction intervals at 72 h and 168 h: single test evaluation") + " (generated by `scripts/run_long_intervals.py`)", "",
          f"Git commit `{(commit or 'n/a')[:10]}`. Calibration on validation only (and, for the rolling variant, known past errors). PICP = share of hours inside the interval (nominal 90%); width in MW; "
          "interval score (lower is better). Demand growth and distribution shift make validation-calibrated intervals under-cover.", ""]
    rows = []
    for h in rb.HORIZONS if False else [72, 168]:
        c = cfg[str(h)]
        b = rb.build(df, h)
        Xs = {n: rb.design(b, rel, full) for n, (rel, full) in
              {"g01_abs": (False, False), "g01_rel": (True, False), "full_abs": (False, True), "full_rel": (True, True)}.items()}
        need = pd.concat(Xs.values(), axis=1).notna().all(axis=1) & b["y"].notna() & b["anchors"]["a24"].notna() & b["anchors"]["a168"].notna()
        valid = need & b["target_obs"]
        Tt = b["T"]
        in_tr = valid & (Tt <= rb.TRAIN_END)
        in_va = valid & (Tt >= rb.VAL_START) & (Tt <= rb.VAL_END)
        in_ev = valid & (Tt >= ev0) & (Tt <= ev1)
        a24 = b["anchors"]["a24"]
        a24v = a24.fillna(1.0).to_numpy()
        pos = np.arange(len(df))
        idx_tr, idx_va, idx_ev = pos[in_tr.to_numpy()], pos[in_va.to_numpy()], pos[in_ev.to_numpy()]
        y_va, a_va, y_ev, a_ev = b["target"].to_numpy()[idx_va], a24v[idx_va], b["target"].to_numpy()[idx_ev], a24v[idx_ev]
        zx = b["target"] / a24
        Xf = ft.build_features(df, h, ft.FEATURE_SETS["S4_full_A"], True)
        z_all = ((b["target"] / a24 - 1) * 100).to_numpy()
        zsd = float(np.nanstd(z_all[idx_tr]))
        zt = np.nan_to_num(z_all / zsd)
        C, S = rl.step_channels(df, True, True, rb.TRAIN_END), rl.static_features(df, h, b, True)
        trD, vaD, evD = (rl.Data(y_all, a24v, C, S, zt, ix) for ix in (idx_tr, idx_va, idx_ev))
        n_in, n_st = C.shape[1] + 1, S.shape[1]
        # ---- point models on validation and evaluation windows
        rname, al = c["ridge"]
        rel = rname.endswith("rel")
        Xd = Xs[rname.replace("ridge_", "")]
        tgt = (b["target"] / a24) if rel else b["target"]
        m = rb.ridge_fit(Xd[in_tr], tgt[in_tr], al)
        pr_va, pr_ev = rb.ridge_pred(m, Xd[in_va]), rb.ridge_pred(m, Xd[in_ev])
        pr_va, pr_ev = (pr_va * a_va, pr_ev * a_ev) if rel else (pr_va, pr_ev)
        xv, xe, lv, le = [], [], [], []
        for sd in rt.SEEDS:
            mdl = xgb.XGBRegressor(n_estimators=c["xgb_trees"][str(sd)], objective="reg:squarederror", tree_method="hist", device="cpu", n_jobs=rx.NJOBS, random_state=sd, eval_metric="mae", **c["xgb_params"])
            mdl.fit(Xf[in_tr], (zx[in_tr] - 1.0) * 100.0, verbose=False)
            xv.append((1.0 + mdl.predict(Xf[in_va]) / 100.0) * a_va)
            xe.append((1.0 + mdl.predict(Xf[in_ev]) / 100.0) * a_ev)
            net = rt.lstm_fit_fixed(trD, n_in, n_st, c["lstm_params"], sd, 2 if args.check else c["lstm_epochs"][str(sd)])
            lv.append((1 + rl.predict(net, vaD, len(idx_va)) * zsd / 100.0) * a_va)
            le.append((1 + rl.predict(net, evD, len(idx_ev)) * zsd / 100.0) * a_ev)
        pts = {"ridge": (pr_va, pr_ev), "XGBoost S4": (np.mean(xv, axis=0), np.mean(xe, axis=0)), "LSTM L4": (np.mean(lv, axis=0), np.mean(le, axis=0))}
        # ---- XGBoost quantile regression (early stopping on validation)
        qx = xgb.XGBRegressor(n_estimators=3000, objective="reg:quantileerror", quantile_alpha=np.array([0.05, 0.95]), tree_method="hist", device="cpu", n_jobs=rx.NJOBS, random_state=0,
                              early_stopping_rounds=40, **c["xgb_params"])
        zz = (zx - 1.0) * 100.0
        qx.fit(Xf[in_tr], zz[in_tr], eval_set=[(Xf[in_va], zz[in_va])], verbose=False)
        conv = lambda P, a: ((1.0 + np.sort(P, axis=1)[:, 0] / 100.0) * a, (1.0 + np.sort(P, axis=1)[:, 1] / 100.0) * a)
        qxv, qxe = conv(qx.predict(Xf[in_va]), a_va), conv(qx.predict(Xf[in_ev]), a_ev)
        # ---- LSTM quantile head (3 seeds, early stopping on validation)
        zva = torch.from_numpy(zt[idx_va].astype(np.float32))
        qlv, qle = [], []
        for sd in rt.SEEDS:
            torch.manual_seed(sd)
            rng_ = np.random.default_rng(sd)
            net = rql.NetQ(n_in, n_st, c["lstm_params"]["hidden"], c["lstm_params"]["dropout"])
            opt = torch.optim.Adam(net.parameters(), lr=c["lstm_params"]["lr"], weight_decay=c["lstm_params"]["weight_decay"])
            best, state, bad = np.inf, None, 0
            for ep in range(2 if args.check else 30):
                net.train()
                perm = rng_.permutation(len(idx_tr))
                for i in range(0, len(perm), rl.BATCH):
                    xb, sb, zb = trD.batch(perm[i:i + rl.BATCH])
                    loss = rql.pinball(net(xb, sb), zb)
                    opt.zero_grad(); loss.backward(); opt.step()
                with torch.no_grad():
                    vl = float(rql.pinball(torch.from_numpy(rql.predict_q(net, vaD, len(idx_va))), zva))
                if vl < best - 1e-6:
                    best, state, bad = vl, copy.deepcopy(net.state_dict()), 0
                else:
                    bad += 1
                    if bad >= 5:
                        break
            net.load_state_dict(state)
            cv = lambda q, a: (1 + np.sort(q, axis=1) * zsd / 100.0) * a[:, None]
            qlv.append(cv(rql.predict_q(net, vaD, len(idx_va)), a_va)); qle.append(cv(rql.predict_q(net, evD, len(idx_ev)), a_ev))
        qlv, qle = np.mean(qlv, axis=0), np.mean(qle, axis=0)
        # ---- intervals
        origin_ev = df.index.to_numpy()[idx_ev].astype("datetime64[ns]").astype("int64")
        T_all = np.concatenate([Tt.to_numpy()[idx_va].astype("datetime64[ns]").astype("int64"), Tt.to_numpy()[idx_ev].astype("datetime64[ns]").astype("int64")])
        order = np.argsort(T_all, kind="stable")
        Ts = T_all[order]
        season = b["season_T"].to_numpy()[idx_ev]
        for mname, (p_va, p_ev) in pts.items():
            e_va = np.abs(y_va - p_va)
            e_all = np.concatenate([e_va, np.abs(y_ev - p_ev)])[order]
            var = {}
            q = ap_.conf_q(e_va)
            var["split conformal (absolute)"] = (p_ev - q, p_ev + q)
            qs = ap_.conf_q(e_va / a_va)
            var["split conformal (scaled by anchor)"] = (p_ev - qs * a_ev, p_ev + qs * a_ev)
            lo_r, hi_r = np.empty_like(p_ev), np.empty_like(p_ev)
            for j in range(len(p_ev)):
                hi_i = np.searchsorted(Ts, origin_ev[j], side="right")
                lo_i = np.searchsorted(Ts, origin_ev[j] - WINDOW_H * 3600 * 10 ** 9, side="right")
                sc = e_all[lo_i:hi_i]
                qq = ap_.conf_q(sc) if len(sc) >= 100 else q
                lo_r[j], hi_r[j] = p_ev[j] - qq, p_ev[j] + qq
            var["rolling conformal (last 720 h of known errors)"] = (lo_r, hi_r)
            if mname == "XGBoost S4":
                var["XGBoost quantile regression, raw 5%-95%"] = qxe
                qc = ap_.conf_q(np.maximum(qxv[0] - y_va, y_va - qxv[1]))
                var["XGBoost quantile regression + CQR"] = (qxe[0] - qc, qxe[1] + qc)
            if mname == "LSTM L4":
                var["LSTM quantile head, raw 5%-95%"] = (qle[:, 0], qle[:, 1])
                qc = ap_.conf_q(np.maximum(qlv[:, 0] - y_va, y_va - qlv[:, 1]))
                var["LSTM quantile head + CQR"] = (qle[:, 0] - qc, qle[:, 1] + qc)
            for vname, (lo, hi) in var.items():
                cover, width, score = ap_.interval_stats(y_ev, lo, hi)
                rows.append((h, mname, vname, cover.mean(), width.mean(), score.mean(), {s: float(cover[season == s].mean()) for s in ap_.SEASONS if (season == s).any()}))
        print(f"h={h} done", flush=True)
    md += ["| horizon | point forecast | interval method | PICP | mean width (MW) | interval score (MW) |", "|---:|---|---|---:|---:|---:|"]
    for h, mname, vname, pc, w, sc, _ in rows:
        md.append(f"| {h} | {mname} | {vname} | {100 * pc:.1f}% | {w:,.0f} | {sc:,.0f} |")
    md += ["", "Coverage by season (XGBoost S4 intervals):", "", "| horizon | method | " + " | ".join(ap_.SEASONS) + " |", "|---:|---|" + "---:|" * len(ap_.SEASONS)]
    for h, mname, vname, pc, w, sc, cs in rows:
        if mname == "XGBoost S4" and vname in ("split conformal (absolute)", "rolling conformal (last 720 h of known errors)"):
            md.append(f"| {h} | {vname} | " + " | ".join(f"{100 * cs.get(s, float('nan')):.0f}%" for s in ap_.SEASONS) + " |")
    out = ROOT / "reports" / ("long_uncertainty_check.md" if args.check else "long_uncertainty.md")
    out.write_text(chr(10).join(md) + chr(10), encoding="utf-8")
    if not args.check:
        LOCK.write_text(f"long-horizon interval test run completed at commit {commit}" + chr(10), encoding="utf-8")
    print("wrote", out)


if __name__ == "__main__":
    main()
