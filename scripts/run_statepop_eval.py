"""Task 9.4 (extension D): does population-weighted state-capital weather change the forecasts compared with the 12-city equal-weight series?

Models: ridge_full_rel and XGBoost S3_weatherA / S4_full_A, each with the national weather (and regional temperatures) from the two sources
  (a) data/processed/india_hourly_canonical.csv       12 cities, equal weight over the five grid regions (the frozen choice, D-03)
  (b) data/interim/sensitivity/canonical_statepop.csv state/UT capitals, Census-2011 population weights (build_state_weather_dataset.py)
XGBoost: stage-2 hyper-parameters of the horizon, early stopping on validation, 3 seeds, mean prediction; ridge penalty on validation. Same samples for every model.
  py scripts/run_statepop_eval.py               validation only
  py scripts/run_statepop_eval.py --with-test   adds the test period, ONCE (lock reports/tables/STATEPOP_TEST_DONE.lock)
Output: reports/statepop_weather.md or reports/statepop_weather_test.md
"""
import argparse
import importlib
import sys
from pathlib import Path

import numpy as np
import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "scripts"))
rb = importlib.import_module("run_baselines")
ft = importlib.import_module("features_tabular")
rx = importlib.import_module("run_xgboost")
rt = importlib.import_module("run_test_evaluation")
LOCK = ROOT / "reports" / "tables" / "STATEPOP_TEST_DONE.lock"
SOURCES = {"12 cities, equal weights": ROOT / "data" / "processed" / "india_hourly_canonical.csv",
           "state capitals, population weights": ROOT / "data" / "interim" / "sensitivity" / "canonical_statepop.csv"}


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--with-test", action="store_true")
    args = ap.parse_args()
    if args.with_test and LOCK.exists():
        sys.exit("The state-weather test evaluation was already run.")
    commit, dirty = rb.git_state()
    if args.with_test and dirty:
        sys.exit("Working tree is not clean: commit first.")
    rx.MAX_TREES = 3000
    xgb_params, _, _ = rt.frozen_configs()
    last = rt.TEST_END if args.with_test else rb.VAL_END
    dfs = {k: pd.read_csv(p, parse_dates=["timestamp"]).set_index("timestamp").loc[:last] for k, p in SOURCES.items()}
    base_df = dfs["12 cities, equal weights"]
    md = ["# " + ("State-level weather: validation and test" if args.with_test else "State-level weather: validation") + " (generated by `scripts/run_statepop_eval.py`)", "",
          f"Git commit `{(commit or 'n/a')[:10]}`. MAE in MW. Differences are state-capital population-weighted minus 12-city equal-weight (negative = the state-level series is better), 95% block bootstrap.", ""]
    rng = np.random.default_rng(0)
    for h in rb.HORIZONS:
        b = rb.build(base_df, h)
        Xs = {n: rb.design(b, rel, full) for n, (rel, full) in
              {"g01_abs": (False, False), "g01_rel": (True, False), "full_abs": (False, True), "full_rel": (True, True)}.items()}
        need = pd.concat(Xs.values(), axis=1).notna().all(axis=1) & b["y"].notna() & b["anchors"]["a24"].notna()
        if h <= 168:
            need &= b["anchors"]["a168"].notna()
        valid = need & b["target_obs"]
        Tt = b["T"]
        in_tr = valid & (Tt <= rb.TRAIN_END)
        in_va = valid & (Tt >= rb.VAL_START) & (Tt <= rb.VAL_END)
        in_te = valid & (Tt >= rt.TEST_START) & (Tt <= rt.TEST_END) if args.with_test else None
        a24 = b["anchors"]["a24"]
        a24v = a24.fillna(1.0).to_numpy()
        pos = np.arange(len(base_df))
        idx_va = pos[in_va.to_numpy()]
        y_va, a_va = b["target"].to_numpy()[idx_va], a24v[idx_va]
        if args.with_test:
            idx_te = pos[in_te.to_numpy()]
            y_te, a_te = b["target"].to_numpy()[idx_te], a24v[idx_te]
        zx = b["target"] / a24
        pv, pt = {}, {}
        for sname, df in dfs.items():
            bb = rb.build(df, h)
            X_r = rb.design(bb, True, True)
            assert bool(X_r.notna().all(axis=1)[valid].all()), "weather missing for valid samples in " + sname
            tgt = bb["target"] / bb["anchors"]["a24"]
            best = None
            for al in rb.ALPHAS:
                m = rb.ridge_fit(X_r[in_tr], tgt[in_tr], al)
                p = rb.ridge_pred(m, X_r[in_va]) * a_va
                mae = float(np.mean(np.abs(p - y_va)))
                if best is None or mae < best[0]:
                    best = (mae, al, m)
            pv[(sname, "ridge_full_rel")] = rb.ridge_pred(best[2], X_r[in_va]) * a_va
            if args.with_test:
                pt[(sname, "ridge_full_rel")] = rb.ridge_pred(best[2], X_r[in_te]) * a_te
            for fs in ("S3_weatherA", "S4_full_A"):
                X = ft.build_features(df, h, ft.FEATURE_SETS[fs], True)
                vv, tt = [], []
                for sd in rt.SEEDS:
                    p, m, *_ = rx.fit_predict(X[in_tr], zx[in_tr], X[in_va], zx[in_va], xgb_params[h], sd, a_va, True)
                    vv.append(p)
                    if args.with_test:
                        tt.append((1.0 + m.predict(X[in_te]) / 100.0) * a_te)
                pv[(sname, "XGBoost " + fs)] = np.mean(vv, axis=0)
                if args.with_test:
                    pt[(sname, "XGBoost " + fs)] = np.mean(tt, axis=0)
        models = ["ridge_full_rel", "XGBoost S3_weatherA", "XGBoost S4_full_A"]
        md += [f"## Horizon {h} h", "", "| model | 12 cities, validation | state capitals, validation | difference (95% CI)" + (" | 12 cities, test | state capitals, test | difference (95% CI) |" if args.with_test else " |"),
               "|---|---:|---:|---|" + ("---:|---:|---|" if args.with_test else "")]
        for mname in models:
            row = f"| {mname} | "
            for P, y in ((pv, y_va),) + (((pt, y_te),) if args.with_test else ()):
                a_, b_ = np.abs(P[("12 cities, equal weights", mname)] - y), np.abs(P[("state capitals, population weights", mname)] - y)
                d = b_ - a_
                lo, hi = rb.block_ci(d, rng)
                row += f"{a_.mean():,.0f} | {b_.mean():,.0f} | {d.mean():+,.0f} ({lo:+,.0f} to {hi:+,.0f}) | "
            md.append(row.rstrip())
        md.append("")
        print(f"h={h} done", flush=True)
    out = ROOT / "reports" / ("statepop_weather_test.md" if args.with_test else "statepop_weather.md")
    out.write_text(chr(10).join(md) + chr(10), encoding="utf-8")
    if args.with_test:
        LOCK.write_text(f"state-weather test run completed at commit {commit}" + chr(10), encoding="utf-8")
    print("wrote", out)


if __name__ == "__main__":
    main()
