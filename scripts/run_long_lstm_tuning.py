"""Equal-budget LSTM tuning at the long horizons 72 h and 168 h (extension (4) of the deviation-log entry of 2026-10-16).

XGBoost's tuning budget at these horizons was 30 trials; the LSTM L4 gets 30 random trials per horizon in the widened space of the stage-3 tuning (hidden in {16, 32, 48, 64, 96},
lr log-uniform 3e-4..2e-2, dropout 0..0.4, weight decay log-uniform 1e-6..1e-2; seed 0, at most 10 epochs, patience 3, no pruning) plus the originally selected configuration re-evaluated
under the same trial procedure. Selection by validation MAE only. Then 3 seeds with the selected configuration (at most 30 epochs, patience 5, early stopping on validation).
  py scripts/run_long_lstm_tuning.py               phase 1 (test not loaded): tuning + final fits on validation; writes reports/tables/long_lstm_eq_config.json and reports/long_lstm_tuning.md
  py scripts/run_long_lstm_tuning.py --with-test   phase 2: single test evaluation with the selected configuration and the validation-chosen epochs (lock reports/tables/LONG_LSTM_TEST_DONE.lock)
"""
import argparse
import importlib
import json
import sys
from pathlib import Path

import numpy as np
import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "scripts"))
rb = importlib.import_module("run_baselines")
rl = importlib.import_module("run_lstm")
rt = importlib.import_module("run_test_evaluation")
r3 = importlib.import_module("run_lstm_stage3")
T = ROOT / "reports" / "tables"
CFG, LOCK = T / "long_lstm_eq_config.json", T / "LONG_LSTM_TEST_DONE.lock"
N_TRIALS = 30


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--with-test", action="store_true")
    ap.add_argument("--smoke", action="store_true")
    args = ap.parse_args()
    global N_TRIALS
    if args.smoke:
        N_TRIALS = 1
    commit, dirty = rb.git_state()
    if args.with_test:
        if LOCK.exists():
            sys.exit("The long-horizon LSTM test evaluation was already run.")
        if dirty:
            sys.exit("Working tree is not clean: commit first.")
        cfg_eq = json.loads(CFG.read_text(encoding="utf-8"))
    orig = json.loads((T / "long_horizon_config.json").read_text(encoding="utf-8"))
    df = pd.read_csv(rb.SRC, parse_dates=["timestamp"]).set_index("timestamp").loc[:(rt.TEST_END if args.with_test else rb.VAL_END)]
    y_all = df["electricity_demand_mw"].ffill().to_numpy(dtype=float)
    md = ["# " + ("Equal-budget LSTM at 72 h and 168 h: single test evaluation" if args.with_test else "Equal-budget LSTM at 72 h and 168 h: tuning on validation") + " (generated by `scripts/run_long_lstm_tuning.py`)", "",
          f"Git commit `{(commit or 'n/a')[:10]}`. LSTM L4, {N_TRIALS} random trials per horizon in the widened space plus the original configuration re-evaluated; selection on validation only. MAE in MW.", ""]
    rng = np.random.default_rng(0)
    out_cfg = {}
    for h in ((72,) if args.smoke else (72, 168)):
        b = rb.build(df, h)
        Xs = {n: rb.design(b, rel, full) for n, (rel, full) in
              {"g01_abs": (False, False), "g01_rel": (True, False), "full_abs": (False, True), "full_rel": (True, True)}.items()}
        need = pd.concat(Xs.values(), axis=1).notna().all(axis=1) & b["y"].notna() & b["anchors"]["a24"].notna() & b["anchors"]["a168"].notna()
        valid = need & b["target_obs"]
        Tt = b["T"]
        in_tr = valid & (Tt <= rb.TRAIN_END)
        in_va = valid & (Tt >= rb.VAL_START) & (Tt <= rb.VAL_END)
        a24 = b["anchors"]["a24"]
        a24v = a24.fillna(1.0).to_numpy()
        pos = np.arange(len(df))
        idx_tr, idx_va = pos[in_tr.to_numpy()], pos[in_va.to_numpy()]
        y_va, a_va = b["target"].to_numpy()[idx_va], a24v[idx_va]
        z_all = ((b["target"] / a24 - 1) * 100).to_numpy()
        zsd = float(np.nanstd(z_all[idx_tr]))
        zt = np.nan_to_num(z_all / zsd)
        C, S = rl.step_channels(df, True, True, rb.TRAIN_END), rl.static_features(df, h, b, True)
        trD, vaD = rl.Data(y_all, a24v, C, S, zt, idx_tr), rl.Data(y_all, a24v, C, S, zt, idx_va)
        n_in, n_st = C.shape[1] + 1, S.shape[1]
        if not args.with_test:
            r_ = np.random.default_rng(13000 + h)
            cands = []
            mae0, *_ = r3.trial_fit(trD, vaD, n_in, n_st, orig[str(h)]["lstm_params"], zsd, a_va, y_va, None)
            cands.append((mae0, orig[str(h)]["lstm_params"], "original"))
            for k in range(N_TRIALS):
                hp = r3.sample_hp(r_)
                mae, *_ = r3.trial_fit(trD, vaD, n_in, n_st, hp, zsd, a_va, y_va, None)
                cands.append((mae, hp, f"new#{k}"))
            sel = min(cands, key=lambda x: x[0])
            per, preds, eps = [], [], {}
            for sd in rt.SEEDS:
                net, mae, hist, *_ = rl.train(trD, vaD, n_in, n_st, sel[1], sd, 30, 5, zsd, a_va, y_va)
                per.append(float(mae)); eps[sd] = int(np.argmin(hist)) + 1
            out_cfg[str(h)] = {"params": sel[1], "best_epoch": {str(k): v for k, v in eps.items()}, "selected_from": sel[2], "val_per_seed_mean": float(np.mean(per))}
            md += [f"## Horizon {h} h", "", f"- Original configuration re-evaluated under the trial procedure: {mae0:,.0f} MW; best of the {N_TRIALS} new trials: {min(x[0] for x in cands[1:]):,.0f} MW; selected {sel[2]} (hidden {sel[1]['hidden']}, lr {sel[1]['lr']:.4g}, dropout {sel[1]['dropout']:.2f}, weight decay {sel[1]['weight_decay']:.2g}).",
                   f"- Final validation MAE (3 seeds, early stopping on validation): per-seed mean {np.mean(per):,.0f} MW (range {min(per):,.0f}-{max(per):,.0f}); best epochs {list(eps.values())}.", ""]
            print(f"h={h} selected {sel[2]}; validation per-seed mean {np.mean(per):.0f}", flush=True)
        else:
            c = cfg_eq[str(h)]
            in_te = valid & (Tt >= rt.TEST_START) & (Tt <= rt.TEST_END)
            idx_te = pos[in_te.to_numpy()]
            y_te, a_te = b["target"].to_numpy()[idx_te], a24v[idx_te]
            teD = rl.Data(y_all, a24v, C, S, zt, idx_te)
            lp = []
            for sd in rt.SEEDS:
                net = rt.lstm_fit_fixed(trD, n_in, n_st, c["params"], sd, c["best_epoch"][str(sd)])
                lp.append((1 + rl.predict(net, teD, len(idx_te)) * zsd / 100.0) * a_te)
            p = np.mean(lp, axis=0)
            z = np.load(ROOT / "data" / "interim" / "predictions" / f"long_h{h}.npz")
            assert np.allclose(z["y_te"], y_te)
            o, x, r = z["LSTM_L4"], z["XGBoost_S4"], z["ridge"]
            f = lambda v: f"{np.mean(np.abs(v - y_te)):,.0f}"
            d1, d2 = np.abs(p - y_te) - np.abs(o - y_te), np.abs(p - y_te) - np.abs(x - y_te)
            (l1, h1), (l2, h2) = rb.block_ci(d1, rng), rb.block_ci(d2, rng)
            md += [f"## Horizon {h} h", "", "| model | test MAE (MW) |", "|---|---:|", f"| LSTM L4, equal budget | {f(p)} |", f"| LSTM L4, original | {f(o)} |", f"| XGBoost S4 | {f(x)} |", f"| ridge | {f(r)} |", "",
                   f"Equal-budget minus original: {d1.mean():+,.0f} MW (95% CI {l1:+,.0f} to {h1:+,.0f}); equal-budget minus XGBoost: {d2.mean():+,.0f} MW (CI {l2:+,.0f} to {h2:+,.0f}).", ""]
            print(f"h={h} test: equal-budget LSTM {f(p)}; original {f(o)}; XGBoost {f(x)}", flush=True)
    if args.smoke:
        print("smoke finished (nothing written)")
        return
    if args.with_test:
        (ROOT / "reports" / "long_lstm_tuning_test.md").write_text(chr(10).join(md) + chr(10), encoding="utf-8")
        LOCK.write_text(f"long-horizon LSTM test run completed at commit {commit}" + chr(10), encoding="utf-8")
    else:
        CFG.write_text(json.dumps(out_cfg, indent=1), encoding="utf-8")
        (ROOT / "reports" / "long_lstm_tuning.md").write_text(chr(10).join(md) + chr(10), encoding="utf-8")
    print("done")


if __name__ == "__main__":
    main()
