"""Task 9.5 (extension C): forecast horizons 72 h and 168 h (design in docs/experiment_protocol.md, deviation log 2026-10-16).

Same task definition, samples and feature groups as the main study (section 4), with h = 72 and 168 (anchors: the same hour 3 and 7 days earlier).
  py scripts/run_long_horizons.py               PHASE 1, validation only (test not loaded): ridge variant/penalty, XGBoost S4 (30 random trials, stage-1 ranges),
                                                LSTM L4 (12 random trials, stage-1 space), 3 seeds each; saves the chosen configuration
                                                (reports/tables/long_horizon_config.json) and reports/long_horizons.md
  py scripts/run_long_horizons.py --with-test   PHASE 2, single test evaluation with the saved configuration: models fitted on the training period only,
                                                trees/epochs fixed from validation, 3 seeds; paired comparisons; lock reports/tables/LONG_HORIZON_TEST_DONE.lock
Output of phase 2: reports/long_horizons_test.md and data/interim/predictions/long_h{h}.npz.
"""
import argparse
import importlib
import json
import sys
import time
from pathlib import Path

import numpy as np
import pandas as pd
import xgboost as xgb

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "scripts"))
rb = importlib.import_module("run_baselines")
ft = importlib.import_module("features_tabular")
rx = importlib.import_module("run_xgboost")
rl = importlib.import_module("run_lstm")
rt = importlib.import_module("run_test_evaluation")
T = ROOT / "reports" / "tables"
CONFIG = T / "long_horizon_config.json"
LOCK = T / "LONG_HORIZON_TEST_DONE.lock"
HORIZONS, SEEDS, N_XGB, N_LSTM = [72, 168], [0, 1, 2], 30, 12


def main():
    global N_XGB, N_LSTM, HORIZONS
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--with-test", action="store_true")
    ap.add_argument("--smoke", action="store_true")
    args = ap.parse_args()
    rx.MAX_TREES = 3000
    commit, dirty = rb.git_state()
    if args.smoke:
        N_XGB, N_LSTM, HORIZONS = 2, 1, [72]
    if args.with_test:
        if LOCK.exists():
            sys.exit("The long-horizon test evaluation was already run.")
        if dirty:
            sys.exit("Working tree is not clean: commit first.")
        cfg_all = json.loads(CONFIG.read_text(encoding="utf-8"))
    df = pd.read_csv(rb.SRC, parse_dates=["timestamp"]).set_index("timestamp").loc[:(rt.TEST_END if args.with_test else rb.VAL_END)]
    y_all = df["electricity_demand_mw"].ffill().to_numpy(dtype=float)
    cfg_out, md = {}, ["# " + ("Long horizons (72 h, 168 h): single test evaluation" if args.with_test else "Long horizons (72 h, 168 h): validation") + " (generated by `scripts/run_long_horizons.py`)", "",
                       f"Git commit `{(commit or 'n/a')[:10]}`. Scenario A, same samples for all models, 3 seeds, mean prediction. MAE in MW. "
                       + ("Models fitted on the training period only with the validation-chosen configuration." if args.with_test else "Hyper-parameters chosen on validation; early stopping on validation (mildly optimistic)."), ""]
    rng = np.random.default_rng(0)
    for h in HORIZONS:
        b = rb.build(df, h)
        Xs = {n: rb.design(b, rel, full) for n, (rel, full) in
              {"g01_abs": (False, False), "g01_rel": (True, False), "full_abs": (False, True), "full_rel": (True, True)}.items()}
        need = pd.concat(Xs.values(), axis=1).notna().all(axis=1) & b["y"].notna() & b["anchors"]["a24"].notna() & b["anchors"]["a168"].notna()
        valid = need & b["target_obs"]
        Tt = b["T"]
        in_tr = valid & (Tt <= rb.TRAIN_END)
        in_va = valid & (Tt >= rb.VAL_START) & (Tt <= rb.VAL_END)
        in_te = valid & (Tt >= rt.TEST_START) & (Tt <= rt.TEST_END) if args.with_test else None
        a24 = b["anchors"]["a24"]
        a24v = a24.fillna(1.0).to_numpy()
        pos = np.arange(len(df))
        idx_tr, idx_va = pos[in_tr.to_numpy()], pos[in_va.to_numpy()]
        y_va, a_va = b["target"].to_numpy()[idx_va], a24v[idx_va]
        zx = b["target"] / a24
        Xf = ft.build_features(df, h, ft.FEATURE_SETS["S4_full_A"], True)
        z_all = ((b["target"] / a24 - 1) * 100).to_numpy()
        zsd = float(np.nanstd(z_all[idx_tr]))
        zt = np.nan_to_num(z_all / zsd)
        C, S = rl.step_channels(df, True, True, rb.TRAIN_END), rl.static_features(df, h, b, True)
        trD, vaD = rl.Data(y_all, a24v, C, S, zt, idx_tr), rl.Data(y_all, a24v, C, S, zt, idx_va)
        n_in, n_st = C.shape[1] + 1, S.shape[1]
        if not args.with_test:
            # ---- ridge
            best = None
            for rname, Xd in {"ridge_full_rel": Xs["full_rel"], "ridge_g01_rel": Xs["g01_rel"], "ridge_full_abs": Xs["full_abs"], "ridge_g01_abs": Xs["g01_abs"]}.items():
                rel = rname.endswith("rel")
                tgt = (b["target"] / a24) if rel else b["target"]
                for al in rb.ALPHAS:
                    m = rb.ridge_fit(Xd[in_tr], tgt[in_tr], al)
                    p = rb.ridge_pred(m, Xd[in_va]); p = p * a_va if rel else p
                    mae = float(np.mean(np.abs(p - y_va)))
                    if best is None or mae < best[0]:
                        best = (mae, rname, al)
            # ---- XGBoost
            r_ = np.random.default_rng(8000 + h)
            xb = None
            for _ in range(N_XGB):
                prm = rx.sample_params(r_)
                p, *_ = rx.fit_predict(Xf[in_tr], zx[in_tr], Xf[in_va], zx[in_va], prm, 0, a_va, True)
                mae = float(np.mean(np.abs(p - y_va)))
                if xb is None or mae < xb[0]:
                    xb = (mae, prm)
            trees, xp = {}, []
            for sd in SEEDS:
                p, m, *_ = rx.fit_predict(Xf[in_tr], zx[in_tr], Xf[in_va], zx[in_va], xb[1], sd, a_va, True)
                trees[sd] = int(m.best_iteration) + 1
                xp.append(p)
            # ---- LSTM
            r2 = np.random.default_rng(9000 + h)
            lb = None
            for _ in range(N_LSTM):
                hp = {"hidden": int(r2.choice([16, 32, 48, 64])), "lr": float(np.exp(r2.uniform(np.log(5e-4), np.log(1e-2)))),
                      "dropout": float(r2.uniform(0, 0.3)), "weight_decay": float(np.exp(r2.uniform(np.log(1e-6), np.log(1e-3))))}
                net, mae, hist, *_ = rl.train(trD, vaD, n_in, n_st, hp, 0, 10, 3, zsd, a_va, y_va)
                if lb is None or mae < lb[0]:
                    lb = (mae, hp)
            epochs, lp = {}, []
            for sd in SEEDS:
                net, mae, hist, *_ = rl.train(trD, vaD, n_in, n_st, lb[1], sd, 30, 5, zsd, a_va, y_va)
                epochs[sd] = int(np.argmin(hist)) + 1
                lp.append((1 + rl.predict(net, vaD, len(idx_va)) * zsd / 100.0) * a_va)
            naive = {"persistence": b["y"].to_numpy()[idx_va], "snaive_same_hour_3_or_7_days": a24.to_numpy()[idx_va], "snaive168": b["anchors"]["a168"].to_numpy()[idx_va]}
            vals = {k: float(np.mean(np.abs(v - y_va))) for k, v in naive.items()}
            vals.update({"ridge": best[0], "xgboost S4": float(np.mean(np.abs(np.mean(xp, axis=0) - y_va))), "LSTM L4": float(np.mean(np.abs(np.mean(lp, axis=0) - y_va)))})
            cfg_out[str(h)] = {"ridge": [best[1], best[2]], "xgb_params": xb[1], "xgb_trees": {str(k): v for k, v in trees.items()}, "lstm_params": lb[1], "lstm_epochs": {str(k): v for k, v in epochs.items()}}
            md += [f"## Horizon {h} h (train samples {int(in_tr.sum()):,}; validation samples {int(in_va.sum()):,})", "", "| model | validation MAE (MW) |", "|---|---:|"] + [f"| {k} | {v:,.0f} |" for k, v in vals.items()] + \
                  ["", f"Selected: ridge {best[1]} alpha {best[2]}; XGBoost best of {N_XGB} trials, trees {list(trees.values())}; LSTM best of {N_LSTM} trials (hidden {lb[1]['hidden']}, lr {lb[1]['lr']:.4g}, dropout {lb[1]['dropout']:.2f}), epochs {list(epochs.values())}.", ""]
            print(f"h={h} validation: " + "; ".join(f"{k} {v:.0f}" for k, v in vals.items()), flush=True)
        else:
            c = cfg_all[str(h)]
            idx_te = pos[in_te.to_numpy()]
            y_te, a_te = b["target"].to_numpy()[idx_te], a24v[idx_te]
            rname, al = c["ridge"]
            Xd = Xs[rname.replace("ridge_", "")]
            rel = rname.endswith("rel")
            tgt = (b["target"] / a24) if rel else b["target"]
            m = rb.ridge_fit(Xd[in_tr], tgt[in_tr], al)
            p_r = rb.ridge_pred(m, Xd[in_te]); p_r = p_r * a_te if rel else p_r
            xp = []
            for sd in SEEDS:
                mdl = xgb.XGBRegressor(n_estimators=c["xgb_trees"][str(sd)], objective="reg:squarederror", tree_method="hist", device="cpu", n_jobs=rx.NJOBS, random_state=sd, eval_metric="mae", **c["xgb_params"])
                mdl.fit(Xf[in_tr], (zx[in_tr] - 1.0) * 100.0, verbose=False)
                xp.append((1.0 + mdl.predict(Xf[in_te]) / 100.0) * a_te)
            teD = rl.Data(y_all, a24v, C, S, zt, idx_te)
            lp = []
            for sd in SEEDS:
                net = rt.lstm_fit_fixed(trD, n_in, n_st, c["lstm_params"], sd, c["lstm_epochs"][str(sd)])
                lp.append((1 + rl.predict(net, teD, len(idx_te)) * zsd / 100.0) * a_te)
            P = {"persistence": b["y"].to_numpy()[idx_te], "same hour 3 or 7 days earlier": a24.to_numpy()[idx_te], "snaive168": b["anchors"]["a168"].to_numpy()[idx_te],
                 "ridge": p_r, "XGBoost S4": np.mean(xp, axis=0), "LSTM L4": np.mean(lp, axis=0)}
            np.savez_compressed(ROOT / "data" / "interim" / "predictions" / f"long_h{h}.npz", y_te=y_te, **{k.replace(" ", "_"): v for k, v in P.items()})
            md += [f"## Horizon {h} h (train samples {int(in_tr.sum()):,}; test samples {int(in_te.sum()):,})", "", "| model | test MAE (MW) | MAPE % | skill vs best naive |", "|---|---:|---:|---:|"]
            nv = min(float(np.mean(np.abs(P[k] - y_te))) for k in ("persistence", "same hour 3 or 7 days earlier", "snaive168"))
            for k, v in P.items():
                e = np.abs(v - y_te)
                md.append(f"| {k} | {e.mean():,.0f} | {100 * np.mean(e / y_te):.2f} | " + ("" if k in ("persistence", "same hour 3 or 7 days earlier", "snaive168") else f"{100 * (1 - e.mean() / nv):+.1f}%") + " |")
            md += ["", "Paired differences (MAE of first minus second; negative = first better; 95% block bootstrap):", "", "| first | second | difference (MW) | 95% CI |", "|---|---|---:|---|"]
            for a_, b_ in (("XGBoost S4", "ridge"), ("LSTM L4", "XGBoost S4"), ("LSTM L4", "ridge")):
                d = np.abs(P[a_] - y_te) - np.abs(P[b_] - y_te)
                lo, hi = rb.block_ci(d, rng)
                md.append(f"| {a_} | {b_} | {d.mean():+,.0f} | {lo:+,.0f} to {hi:+,.0f} |")
            md.append("")
            print(f"h={h} test: " + "; ".join(f"{k} {np.mean(np.abs(v - y_te)):.0f}" for k, v in P.items()), flush=True)
    if args.smoke:
        print("smoke finished (nothing written)")
        return
    if args.with_test:
        (ROOT / "reports" / "long_horizons_test.md").write_text(chr(10).join(md) + chr(10), encoding="utf-8")
        LOCK.write_text(f"long-horizon test run completed at commit {commit}" + chr(10), encoding="utf-8")
    else:
        CONFIG.write_text(json.dumps(cfg_out, indent=1), encoding="utf-8")
        (ROOT / "reports" / "long_horizons.md").write_text(chr(10).join(md) + chr(10), encoding="utf-8")
    print("done")


if __name__ == "__main__":
    main()
