"""Cross-validated tuning at the long horizons 72 h and 168 h (extension (1) of the deviation-log entry of 2026-10-16).

Remedy tested: instead of early stopping and selection on the single validation half-year (which chose 2 trees / 1 epoch at 168 h), the configuration of ridge, XGBoost S4 and
LSTM L4 is chosen by expanding-window time-series cross-validation INSIDE the training period:
  fold 1: train targets <= 2022-06-30, validate 2022-07-01..2022-12-31;  fold 2: <= 2022-12-31, validate 2023-01..2023-06;  fold 3: <= 2023-06-30, validate 2023-07..2023-12.
XGBoost: 30 random trials (stage-1 ranges), early stopping inside each fold, score = mean fold MAE, trees = median of the folds' best iterations.
LSTM: 12 random trials (stage-1 space, at most 10 epochs, patience 3 inside each fold), score = mean fold MAE, epochs = median best epoch.
Ridge: variant and penalty by mean fold MAE.
Final models: fitted on the whole training period (targets <= 2023-12-31), 3 seeds, fixed trees/epochs. The validation period is then a true hold-out (never used for stopping or selection).
  py scripts/run_long_cv_tuning.py               phase 1 (test not loaded): CV tuning + validation hold-out evaluation; writes reports/tables/long_cv_config.json and reports/long_cv_tuning.md
  py scripts/run_long_cv_tuning.py --with-test   phase 2: single test evaluation (lock reports/tables/LONG_CV_TEST_DONE.lock) with paired comparisons against the original long-horizon models
"""
import argparse
import importlib
import json
import sys
from pathlib import Path

import numpy as np
import pandas as pd
import xgboost as xgb

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "scripts"))
rb = importlib.import_module("run_baselines")
ft = importlib.import_module("features_tabular")
rx = importlib.import_module("run_xgboost")
rl = importlib.import_module("run_lstm")
rt = importlib.import_module("run_test_evaluation")
T = ROOT / "reports" / "tables"
CFG, LOCK = T / "long_cv_config.json", T / "LONG_CV_TEST_DONE.lock"
FOLDS = [(pd.Timestamp("2022-06-30 23:00"), pd.Timestamp("2022-07-01"), pd.Timestamp("2022-12-31 23:00")),
         (pd.Timestamp("2022-12-31 23:00"), pd.Timestamp("2023-01-01"), pd.Timestamp("2023-06-30 23:00")),
         (pd.Timestamp("2023-06-30 23:00"), pd.Timestamp("2023-07-01"), pd.Timestamp("2023-12-31 23:00"))]
N_XGB, N_LSTM = 30, 12


def main():
    global N_XGB, N_LSTM
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--with-test", action="store_true")
    ap.add_argument("--smoke", action="store_true")
    args = ap.parse_args()
    rx.MAX_TREES = 3000
    commit, dirty = rb.git_state()
    if args.smoke:
        N_XGB, N_LSTM = 2, 1
    if args.with_test:
        if LOCK.exists():
            sys.exit("The CV-tuned long-horizon test evaluation was already run.")
        if dirty:
            sys.exit("Working tree is not clean: commit first.")
        cfg_all = json.loads(CFG.read_text(encoding="utf-8"))
    orig = json.loads((T / "long_horizon_config.json").read_text(encoding="utf-8"))
    df = pd.read_csv(rb.SRC, parse_dates=["timestamp"]).set_index("timestamp").loc[:(rt.TEST_END if args.with_test else rb.VAL_END)]
    y_all = df["electricity_demand_mw"].ffill().to_numpy(dtype=float)
    md = ["# " + ("CV-tuned long-horizon models: single test evaluation" if args.with_test else "CV-tuned long-horizon models: tuning and validation hold-out") + " (generated by `scripts/run_long_cv_tuning.py`)", "",
          f"Git commit `{(commit or 'n/a')[:10]}`. Configuration chosen by expanding-window cross-validation inside the training period (three half-year folds of 2022-H2, 2023-H1, 2023-H2); "
          "the validation half-year (2024-H1) is NOT used for stopping or selection here. MAE in MW, mean prediction of 3 seeds.", ""]
    rng = np.random.default_rng(0)
    out_cfg = {}
    for h in ([72] if args.smoke else [72, 168]):
        b = rb.build(df, h)
        Xs = {n: rb.design(b, rel, full) for n, (rel, full) in
              {"g01_abs": (False, False), "g01_rel": (True, False), "full_abs": (False, True), "full_rel": (True, True)}.items()}
        need = pd.concat(Xs.values(), axis=1).notna().all(axis=1) & b["y"].notna() & b["anchors"]["a24"].notna() & b["anchors"]["a168"].notna()
        valid = need & b["target_obs"]
        Tt = b["T"]
        a24 = b["anchors"]["a24"]
        a24v = a24.fillna(1.0).to_numpy()
        pos = np.arange(len(df))
        zx = b["target"] / a24
        Xf = ft.build_features(df, h, ft.FEATURE_SETS["S4_full_A"], True)
        z_all = ((b["target"] / a24 - 1) * 100).to_numpy()
        in_train = valid & (Tt <= rb.TRAIN_END)
        in_va = valid & (Tt >= rb.VAL_START) & (Tt <= rb.VAL_END)
        fold = []
        for tr_end, v0, v1 in FOLDS:
            fold.append((valid & (Tt <= tr_end), valid & (Tt >= v0) & (Tt <= v1), tr_end))

        def lstm_data(in_tr, in_ev, tr_end):
            idx_tr, idx_ev = pos[in_tr.to_numpy()], pos[in_ev.to_numpy()]
            zsd = float(np.nanstd(z_all[idx_tr]))
            zt = np.nan_to_num(z_all / zsd)
            C, S = rl.step_channels(df, True, True, tr_end), rl.static_features(df, h, b, True)
            return rl.Data(y_all, a24v, C, S, zt, idx_tr), rl.Data(y_all, a24v, C, S, zt, idx_ev), C.shape[1] + 1, S.shape[1], zsd, a24v[idx_ev], b["target"].to_numpy()[idx_ev]

        if not args.with_test:
            # ---- ridge by CV
            best_r = None
            for rname, Xd in {"ridge_full_rel": Xs["full_rel"], "ridge_g01_rel": Xs["g01_rel"], "ridge_full_abs": Xs["full_abs"], "ridge_g01_abs": Xs["g01_abs"]}.items():
                rel = rname.endswith("rel")
                tgt = (b["target"] / a24) if rel else b["target"]
                for al in rb.ALPHAS:
                    maes = []
                    for in_tr, in_ev, _ in fold:
                        m = rb.ridge_fit(Xd[in_tr], tgt[in_tr], al)
                        p = rb.ridge_pred(m, Xd[in_ev]); a_ = a24v[pos[in_ev.to_numpy()]]
                        maes.append(float(np.mean(np.abs((p * a_ if rel else p) - b["target"].to_numpy()[pos[in_ev.to_numpy()]]))))
                    if best_r is None or np.mean(maes) < best_r[0]:
                        best_r = (float(np.mean(maes)), rname, al)
            # ---- XGBoost by CV
            r_ = np.random.default_rng(11000 + h)
            best_x = None
            for _ in range(N_XGB):
                prm = rx.sample_params(r_)
                maes, its = [], []
                for in_tr, in_ev, _ in fold:
                    ie = pos[in_ev.to_numpy()]
                    p, m, *_ = rx.fit_predict(Xf[in_tr], zx[in_tr], Xf[in_ev], zx[in_ev], prm, 0, a24v[ie], True)
                    maes.append(float(np.mean(np.abs(p - b["target"].to_numpy()[ie]))))
                    its.append(int(m.best_iteration) + 1)
                if best_x is None or np.mean(maes) < best_x[0]:
                    best_x = (float(np.mean(maes)), prm, int(np.median(its)), its)
            # ---- LSTM by CV
            r2 = np.random.default_rng(12000 + h)
            fd = [lstm_data(in_tr, in_ev, tr_end) for in_tr, in_ev, tr_end in fold]
            best_l = None
            for _ in range(N_LSTM):
                hp = {"hidden": int(r2.choice([16, 32, 48, 64])), "lr": float(np.exp(r2.uniform(np.log(5e-4), np.log(1e-2)))),
                      "dropout": float(r2.uniform(0, 0.3)), "weight_decay": float(np.exp(r2.uniform(np.log(1e-6), np.log(1e-3))))}
                maes, eps = [], []
                for trD, evD, n_in, n_st, zsd, a_ev, y_ev in fd:
                    net, mae, hist, *_ = rl.train(trD, evD, n_in, n_st, hp, 0, 10, 3, zsd, a_ev, y_ev)
                    maes.append(float(mae)); eps.append(int(np.argmin(hist)) + 1)
                if best_l is None or np.mean(maes) < best_l[0]:
                    best_l = (float(np.mean(maes)), hp, int(np.median(eps)), eps)
            cfg_h = {"ridge": [best_r[1], best_r[2]], "ridge_cv_mae": best_r[0], "xgb_params": best_x[1], "xgb_trees": best_x[2], "xgb_trees_per_fold": best_x[3], "xgb_cv_mae": best_x[0],
                     "lstm_params": best_l[1], "lstm_epochs": best_l[2], "lstm_epochs_per_fold": best_l[3], "lstm_cv_mae": best_l[0]}
            out_cfg[str(h)] = cfg_h
            c = cfg_h
        else:
            c = cfg_all[str(h)]
        # ---- final models on the whole training period; evaluate on validation (phase 1) or test (phase 2)
        ev_mask = in_va if not args.with_test else (valid & (Tt >= rt.TEST_START) & (Tt <= rt.TEST_END))
        idx_tr, idx_ev = pos[in_train.to_numpy()], pos[ev_mask.to_numpy()]
        y_ev, a_ev = b["target"].to_numpy()[idx_ev], a24v[idx_ev]
        rname, al = c["ridge"]
        rel = rname.endswith("rel")
        Xd = Xs[rname.replace("ridge_", "")]
        tgt = (b["target"] / a24) if rel else b["target"]
        m = rb.ridge_fit(Xd[in_train], tgt[in_train], al)
        p_r = rb.ridge_pred(m, Xd[ev_mask]); p_r = p_r * a_ev if rel else p_r
        xp = []
        for sd in rt.SEEDS:
            mdl = xgb.XGBRegressor(n_estimators=c["xgb_trees"], objective="reg:squarederror", tree_method="hist", device="cpu", n_jobs=rx.NJOBS, random_state=sd, eval_metric="mae", **c["xgb_params"])
            mdl.fit(Xf[in_train], (zx[in_train] - 1.0) * 100.0, verbose=False)
            xp.append((1.0 + mdl.predict(Xf[ev_mask]) / 100.0) * a_ev)
        zsd = float(np.nanstd(z_all[idx_tr]))
        zt = np.nan_to_num(z_all / zsd)
        C, S = rl.step_channels(df, True, True, rb.TRAIN_END), rl.static_features(df, h, b, True)
        trD, evD = rl.Data(y_all, a24v, C, S, zt, idx_tr), rl.Data(y_all, a24v, C, S, zt, idx_ev)
        lp = []
        for sd in rt.SEEDS:
            net = rt.lstm_fit_fixed(trD, C.shape[1] + 1, S.shape[1], c["lstm_params"], sd, c["lstm_epochs"])
            lp.append((1 + rl.predict(net, evD, len(idx_ev)) * zsd / 100.0) * a_ev)
        P = {"ridge": p_r, "XGBoost S4": np.mean(xp, axis=0), "LSTM L4": np.mean(lp, axis=0)}
        label = "test" if args.with_test else "validation hold-out"
        md += [f"## Horizon {h} h", "",
               f"CV choice: ridge {rname} alpha {al}; XGBoost {c['xgb_trees']} trees (per fold {c.get('xgb_trees_per_fold')}, CV MAE {c.get('xgb_cv_mae', float('nan')):,.0f}); LSTM hidden {c['lstm_params']['hidden']}, "
               f"epochs {c['lstm_epochs']} (per fold {c.get('lstm_epochs_per_fold')}, CV MAE {c.get('lstm_cv_mae', float('nan')):,.0f}). Original (validation-tuned) choice: XGBoost trees {list(orig[str(h)]['xgb_trees'].values())}, LSTM epochs {list(orig[str(h)]['lstm_epochs'].values())}.", "",
               f"| model | {label} MAE (MW) |", "|---|---:|"] + [f"| {k} | {np.mean(np.abs(v - y_ev)):,.0f} |" for k, v in P.items()]
        if args.with_test:
            z = np.load(ROOT / "data" / "interim" / "predictions" / f"long_h{h}.npz")
            assert np.allclose(z["y_te"], y_ev)
            O = {"ridge": z["ridge"], "XGBoost S4": z["XGBoost_S4"], "LSTM L4": z["LSTM_L4"]}
            md += ["", "Against the original validation-tuned models of the same horizon (test MAE, difference CV-tuned minus original, 95% block bootstrap):", "", "| model | original | CV-tuned | difference (95% CI) |", "|---|---:|---:|---|"]
            for k in P:
                d = np.abs(P[k] - y_ev) - np.abs(O[k] - y_ev)
                lo, hi = rb.block_ci(d, rng)
                md.append(f"| {k} | {np.mean(np.abs(O[k] - y_ev)):,.0f} | {np.mean(np.abs(P[k] - y_ev)):,.0f} | {d.mean():+,.0f} ({lo:+,.0f} to {hi:+,.0f}) |")
            md += ["", "CV-tuned models against each other (MAE difference, first minus second):", "", "| first | second | difference (95% CI) |", "|---|---|---|"]
            for a_, b_ in (("XGBoost S4", "ridge"), ("LSTM L4", "XGBoost S4"), ("LSTM L4", "ridge")):
                d = np.abs(P[a_] - y_ev) - np.abs(P[b_] - y_ev)
                lo, hi = rb.block_ci(d, rng)
                md.append(f"| {a_} | {b_} | {d.mean():+,.0f} ({lo:+,.0f} to {hi:+,.0f}) |")
        md.append("")
        print(f"h={h} {label}: " + "; ".join(f"{k} {np.mean(np.abs(v - y_ev)):.0f}" for k, v in P.items()), flush=True)
    if args.smoke:
        print("smoke finished (nothing written)")
        return
    if args.with_test:
        (ROOT / "reports" / "long_cv_tuning_test.md").write_text(chr(10).join(md) + chr(10), encoding="utf-8")
        LOCK.write_text(f"CV-tuned long-horizon test run completed at commit {commit}" + chr(10), encoding="utf-8")
    else:
        CFG.write_text(json.dumps(out_cfg, indent=1), encoding="utf-8")
        (ROOT / "reports" / "long_cv_tuning.md").write_text(chr(10).join(md) + chr(10), encoding="utf-8")
    print("done")


if __name__ == "__main__":
    main()
