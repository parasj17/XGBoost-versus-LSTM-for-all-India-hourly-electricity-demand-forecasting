"""Sensitivity target: robust hourly MEAN of demand for 2021-09 .. 2023-12 (task 2.6).

The primary target is the HH:00 snapshot (decision D-01). The 2024-25 workbook
only provides one value per hour, so a mean-based target exists only for the
5-minute and 10-second period. This script averages, for every clock hour, all
raw samples that pass the same plausibility bounds as the cleaning rules
(80,000-260,000 MW), and keeps the hour only if at least half of the expected
samples are valid.

Input : data/interim/parsed/*.csv.gz  (made by inspect_electricity_data.py)
Output: data/interim/demand_hourmean_2021_2023.csv, reports/hourmean_sensitivity.md
Usage : py scripts/build_hourmean_sensitivity.py
"""
from pathlib import Path

import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
PARSED = ROOT / "data" / "interim" / "parsed"
CLEAN = ROOT / "data" / "processed" / "india_hourly_demand_clean.csv"
OUT = ROOT / "data" / "interim" / "demand_hourmean_2021_2023.csv"
REPORT = ROOT / "reports" / "hourmean_sensitivity.md"
LO, HI, MIN_SHARE = 80_000, 260_000, 0.5


def main():
    parts = []
    for f in sorted(PARSED.glob("*.csv.gz")):
        head = pd.read_csv(f, nrows=0).columns
        if "NLDC_DEMAND|P" not in head:       # skip the 2024-25 hourly workbook
            continue
        d = pd.read_csv(f, usecols=["Time", "NLDC_DEMAND|P"], parse_dates=["Time"])
        d = d.rename(columns={"Time": "t", "NLDC_DEMAND|P": "mw"})
        d["hour"] = d["t"].dt.floor("h")
        step = d["t"].diff().dt.total_seconds().median()
        expected = int(3600 / step)
        ok = d["mw"].between(LO, HI)
        g = d[ok].groupby("hour")["mw"].agg(["mean", "size"])
        g["expected"] = expected
        parts.append(g)
    hm = pd.concat(parts).sort_index()
    hm.loc[hm["size"] < MIN_SHARE * hm["expected"], "mean"] = float("nan")
    hm = hm.rename(columns={"mean": "demand_hourmean_mw", "size": "n_valid_samples"})
    full = pd.date_range("2021-09-01", "2023-12-31 23:00", freq="h")
    hm = hm.reindex(full)
    hm.index.name = "timestamp"
    OUT.parent.mkdir(parents=True, exist_ok=True)
    hm[["demand_hourmean_mw", "n_valid_samples"]].to_csv(OUT, float_format="%.3f")

    c = pd.read_csv(CLEAN, parse_dates=["timestamp"]).set_index("timestamp")["electricity_demand_mw"].reindex(full)
    both = pd.concat([c.rename("snap"), hm["demand_hourmean_mw"].rename("mean")], axis=1).dropna()
    diff = both["snap"] - both["mean"]
    by_regime = {"5-min (to 2022-09)": both.loc[:"2022-09-30"], "10-s (from 2022-10)": both.loc["2022-10-01":]}
    lines = ["# Hourly-mean sensitivity target (2021-09 to 2023-12)", "",
             "Generated by `scripts/build_hourmean_sensitivity.py`. Mean of all raw samples within the plausibility bounds "
             f"({LO:,}-{HI:,} MW) for each clock hour; hours with fewer than {MIN_SHARE:.0%} valid samples are missing.", "",
             f"Hours: {len(full):,}; with a valid hourly mean: {int(hm['demand_hourmean_mw'].notna().sum()):,}; "
             f"hours where both the cleaned snapshot and the mean exist: {len(both):,}.", "",
             "## Snapshot (HH:00) minus hourly mean, MW", "",
             f"- all: mean {diff.mean():+.0f}, MAE {diff.abs().mean():,.0f} ({100 * diff.abs().mean() / both['mean'].mean():.2f}% of mean demand), "
             f"99th percentile of |difference| {diff.abs().quantile(.99):,.0f}"]
    for k, v in by_regime.items():
        dd = v["snap"] - v["mean"]
        lines.append(f"- {k}: MAE {dd.abs().mean():,.0f} MW ({100 * dd.abs().mean() / v['mean'].mean():.2f}%)")
    lines += ["", "The difference reflects what the snapshot misses within the hour (mostly the morning and evening ramps). "
              "Use: `run_baselines.py --train-target hourmean` trains on the mean for 2021-2023 targets and still scores on the snapshot, "
              "which shows how much the primary-target definition matters for the validation error."]
    REPORT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
