"""LSTM stage 3: equal tuning budget with XGBoost (protocol deviation log, 2026-10-16). Validation period only; the test period is never loaded.

L4_full_A (the declared LSTM headline) is tuned up to 90 trials per horizon in total: the 12 trials of the first tuning plus N_NEW = 78 new ones (seed 0, at most
10 epochs per trial, patience 3). Search space widened as for XGBoost: hidden in {16, 32, 48, 64, 96}, lr log-uniform 3e-4..2e-2, dropout 0..0.4, weight decay
log-uniform 1e-6..1e-2. A new trial is abandoned after epoch 3 if its validation MAE exceeds 1.25 x the best epoch-3 MAE of the earlier stage-3 trials (the first 5
new trials are never pruned). Selection = lowest validation MAE over all 90 trials. The selected configuration is trained with 3 seeds (at most 30 epochs, patience 5),
exactly as the first LSTM run, and the epochs are stored for the single test evaluation (run_test_lstm_stage3.py).
Resumable: every trial is appended to reports/tables/lstm_stage3.jsonl. Outputs: reports/lstm_stage3.md, reports/tables/lstm_stage3_config.json.
Usage: py scripts/run_lstm_stage3.py [--smoke]
"""
import argparse
import json
import sys
import time
import importlib
from pathlib import Path

import numpy as np
import pandas as pd
import torch

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "scripts"))
rb = importlib.import_module("run_baselines")
rl = importlib.import_module("run_lstm")

T = ROOT / "reports" / "tables"
LOG = T / "lstm_stage3.jsonl"
CONFIG = T / "lstm_stage3_config.json"
N_NEW, PRUNE_FACTOR, N_UNPRUNED = 78, 1.25, 5
HIDDEN = [16, 32, 48, 64, 96]


def sample_hp(rng):
    return {"hidden": int(rng.choice(HIDDEN)), "lr": float(np.exp(rng.uniform(np.log(3e-4), np.log(2e-2)))),
            "dropout": float(rng.uniform(0, 0.4)), "weight_decay": float(np.exp(rng.uniform(np.log(1e-6), np.log(1e-2))))}


def read(path):
    return [json.loads(l) for l in open(path, encoding="utf-8")] if path.exists() else []


def trial_fit(tr, va, n_in, n_st, hp, zsd, a_va, y_va, ref3, max_epochs=10, patience=3):
    torch.manual_seed(0)
    rng = np.random.default_rng(0)
    net = rl.Net(n_in, n_st, hp["hidden"], hp["dropout"])
    opt = torch.optim.Adam(net.parameters(), lr=hp["lr"], weight_decay=hp["weight_decay"])
    best, bad, hist, pruned = np.inf, 0, [], False
    for ep in range(max_epochs):
        net.train()
        perm = rng.permutation(len(tr.idx))
        for i in range(0, len(perm), rl.BATCH):
            x, s, z = tr.batch(perm[i:i + rl.BATCH])
            loss = ((net(x, s) - z) ** 2).mean()
            opt.zero_grad(); loss.backward(); opt.step()
        zhat = rl.predict(net, va, len(va.idx))
        mae = float(np.mean(np.abs((1 + zhat * zsd / 100.0) * a_va - y_va)))
        hist.append(mae)
        if mae < best - 1e-6:
            best, bad = mae, 0
        else:
            bad += 1
            if bad >= patience:
                break
        if ep == 2 and ref3 is not None and mae > PRUNE_FACTOR * ref3:
            pruned = True
            break
    return best, hist, pruned


def main():
    global N_NEW
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--smoke", action="store_true")
    args = ap.parse_args()
    horizons, final_epochs, seeds = rb.HORIZONS, 30, [0, 1, 2]
    log_path = LOG
    if args.smoke:
        N_NEW, horizons, final_epochs, seeds = 3, [24], 2, [0]
        log_path = T / "lstm_stage3_smoke.jsonl"
    df = pd.read_csv(rb.SRC, parse_dates=["timestamp"]).set_index("timestamp").loc[:rb.VAL_END]
    y_all = df["electricity_demand_mw"].ffill().to_numpy(dtype=float)
    xg = {r["horizon"]: (r["n_train"], r["n_val"]) for r in read(T / "xgboost_validation_wide.jsonl") if r["stage"] == "ablation_fit"}
    old_trials = [r for r in read(T / "lstm_validation.jsonl") if r["stage"] == "tuning_trial"]
    prev_final = {}
    for r in read(T / "lstm_validation.jsonl"):
        if r["stage"] == "final_fit" and r["feature_set"] == "L4_full_A":
            prev_final.setdefault(r["horizon"], []).append(r["val_MAE_MW"])
    xgb_ref = {}
    for r in read(T / "xgboost_validation_wide.jsonl"):
        if r["stage"] == "ablation_fit" and r["feature_set"] == "S4_full_A" and r["relative_target"]:
            xgb_ref.setdefault(r["horizon"], []).append(r["val_MAE_MW"])
    done = read(log_path)
    config, md = {}, ["# LSTM stage 3: equal tuning budget (generated by `scripts/run_lstm_stage3.py`)", "",
                      "Validation period only. L4_full_A tuned with up to 90 trials per horizon in total (12 from the first tuning + 78 new, widened search space, pruning after epoch 3), "
                      "then 3 seeds with the selected configuration, as in the first LSTM run. Selection by validation MAE only; early stopping on validation, so the numbers are mildly optimistic.", ""]
    for h in horizons:
        b = rb.build(df, h)
        Xs = {n: rb.design(b, rel, full) for n, (rel, full) in
              {"g01_abs": (False, False), "g01_rel": (True, False), "full_abs": (False, True), "full_rel": (True, True)}.items()}
        need = pd.concat(Xs.values(), axis=1).notna().all(axis=1) & b["y"].notna() & b["anchors"]["a24"].notna()
        if h <= 168:
            need &= b["anchors"]["a168"].notna()
        valid = need & b["target_obs"]
        in_tr = valid & (b["T"] <= rb.TRAIN_END)
        in_va = valid & (b["T"] >= rb.VAL_START) & (b["T"] <= rb.VAL_END)
        assert (int(in_tr.sum()), int(in_va.sum())) == xg[h]
        a24 = b["anchors"]["a24"]
        a24v = a24.fillna(1.0).to_numpy()
        pos = np.arange(len(df))
        idx_tr, idx_va = pos[in_tr.to_numpy()], pos[in_va.to_numpy()]
        z_all = ((b["target"] / a24 - 1) * 100).to_numpy()
        zsd = float(np.nanstd(z_all[idx_tr]))
        zt = np.nan_to_num(z_all / zsd)
        y_va, a_va = b["target"].to_numpy()[idx_va], a24v[idx_va]
        C, S = rl.step_channels(df, True, True, rb.TRAIN_END), rl.static_features(df, h, b, True)
        tr, va = rl.Data(y_all, a24v, C, S, zt, idx_tr), rl.Data(y_all, a24v, C, S, zt, idx_va)
        n_in, n_st = C.shape[1] + 1, S.shape[1]
        mine = {r["trial"]: r for r in done if r.get("stage") == "tuning_trial" and r["horizon"] == h}
        rng = np.random.default_rng(6000 + h)
        t_h = time.perf_counter()
        for trial in range(N_NEW):
            hp = sample_hp(rng)                                 # always consume the generator so that resuming reproduces the sequence
            if trial in mine:
                continue
            ep3 = [r["epoch3_mae"] for r in mine.values() if r.get("epoch3_mae") is not None]
            ref3 = min(ep3) if len(mine) >= N_UNPRUNED and ep3 else None
            t0 = time.perf_counter()
            best, hist, pruned = trial_fit(tr, va, n_in, n_st, hp, zsd, a_va, y_va, ref3)
            rec = {"stage": "tuning_trial", "horizon": h, "trial": trial, "params": hp, "val_MAE_MW": best, "epochs_run": len(hist), "pruned": pruned,
                   "epoch3_mae": hist[2] if len(hist) >= 3 else None, "fit_s": round(time.perf_counter() - t0, 1)}
            mine[trial] = rec
            with open(log_path, "a", encoding="utf-8") as f:
                f.write(json.dumps(rec) + chr(10))
            print(f"h={h} trial {trial + 1}/{N_NEW}: hidden={hp['hidden']} lr={hp['lr']:.4f} -> MAE {best:.0f} ({len(hist)} ep{', pruned' if pruned else ''}, {rec['fit_s']:.0f}s)", flush=True)
        # ---- selection over all trials of this horizon (old 12 + new)
        cands = [(r["val_MAE_MW"], r["params"], f"old#{r['trial']}") for r in old_trials if r["horizon"] == h]
        old_best = min(c[0] for c in cands)
        cands += [(r["val_MAE_MW"], r["params"], f"new#{k}") for k, r in mine.items() if not r["pruned"]]
        sel = min(cands, key=lambda c: c[0])
        hp = sel[1]
        # ---- final fits with 3 seeds
        preds, per_seed, epochs = [], [], {}
        for sd in seeds:
            net, mae, hist, wall, cpu, peak = rl.train(tr, va, n_in, n_st, hp, sd, final_epochs, rl.FINAL_PATIENCE, zsd, a_va, y_va)
            zhat = rl.predict(net, va, len(idx_va))
            preds.append((1 + zhat * zsd / 100.0) * a_va)
            per_seed.append(float(mae))
            epochs[sd] = int(np.argmin(hist)) + 1
            with open(log_path, "a", encoding="utf-8") as f:
                f.write(json.dumps({"stage": "final_fit", "horizon": h, "seed": sd, "val_MAE_MW": float(mae), "best_epoch": epochs[sd], "epochs_run": len(hist),
                                    "train_wall_s": round(wall, 1), "params": hp}) + chr(10))
        ens = float(np.mean(np.abs(np.mean(preds, axis=0) - y_va)))
        config[str(h)] = {"params": hp, "best_epoch": {str(k): v for k, v in epochs.items()}, "selected_from": sel[2], "val_per_seed_mean": float(np.mean(per_seed)), "val_ensemble": ens}
        pk = prev_final.get(h)
        md += [f"## Horizon {h} h", "",
               f"- Trials: 12 old + {len(mine)} new ({sum(1 for r in mine.values() if r['pruned'])} pruned); tuning time of the new trials {sum(r['fit_s'] for r in mine.values()) / 60:.0f} min.",
               f"- Best trial MAE: first 12 trials {old_best:,.0f} MW; all {len(cands)} eligible trials {sel[0]:,.0f} MW (selected {sel[2]}: hidden {hp['hidden']}, lr {hp['lr']:.4g}, dropout {hp['dropout']:.2f}, weight decay {hp['weight_decay']:.2g}).",
               f"- Final validation MAE (3 seeds): per-seed mean {np.mean(per_seed):,.0f} MW (range {min(per_seed):,.0f}-{max(per_seed):,.0f}); mean prediction {ens:,.0f} MW; best epochs {list(epochs.values())}."]
        if pk:
            md.append(f"- First LSTM L4 run (12 trials): per-seed mean {np.mean(pk):,.0f} MW. XGBoost headline S4 (stage 2) per-seed mean {np.mean(xgb_ref[h]):,.0f} MW.")
        md.append("")
        print(f"h={h} done: selected {sel[2]}; validation per-seed mean {np.mean(per_seed):.0f} (first run {np.mean(pk):.0f}; XGBoost {np.mean(xgb_ref[h]):.0f}); {time.perf_counter() - t_h:.0f} s", flush=True)
    if not args.smoke:
        CONFIG.write_text(json.dumps(config, indent=1), encoding="utf-8")
        (ROOT / "reports" / "lstm_stage3.md").write_text(chr(10).join(md) + chr(10), encoding="utf-8")
    print("finished")


if __name__ == "__main__":
    main()
