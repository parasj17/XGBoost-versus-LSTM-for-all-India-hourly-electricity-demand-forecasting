"""Phase 3: merge cleaned demand, national weather and calendar into one table.

Inputs
  data/processed/india_hourly_demand_clean.csv   (build_hourly_dataset.py)
  data/raw/weather/era5_<city>_*.csv             (inspect_weather_data.py --fetch)
  data/processed/calendar_hourly.csv             (build_calendar_features.py)
Output
  data/processed/india_hourly_canonical.csv
  reports/canonical_dataset_log.md

National weather (decision D-03): for every variable, first the mean of the
cities inside each grid region, then the EQUAL-weight mean of the five regions.
Region-level temperature is also kept (5 columns) for sensitivity analysis.
No weights from population/consumption are used until a source is cited.

Time alignment (decision D-09): all series are on the same IST hourly label.
Precipitation and shortwave radiation are preceding-hour aggregates ending at
the label, i.e. they are fully known at that label, so no shift is applied.

Solar night correction: raw solar has a night-time offset that grew from 9 MW
(2021) to 886 MW (2025). In hours where ERA5 shortwave radiation is 0 at ALL 12
cities (national night) the solar value is set to 0 and flagged. Any daytime
offset cannot be identified and is left as is (documented limitation).

Not done here on purpose: degree-hours (CDD/HDD), lags, rolling features. Their
parameters must be chosen on training data only, so they belong to the modelling
feature pipeline.

Usage (project root):  py scripts/build_canonical_dataset.py
"""
import sys
from pathlib import Path

import numpy as np
import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
DEMAND = ROOT / "data" / "processed" / "india_hourly_demand_clean.csv"
CAL = ROOT / "data" / "processed" / "calendar_hourly.csv"
WEATHER_DIR = ROOT / "data" / "raw" / "weather"
OUT = ROOT / "data" / "processed" / "india_hourly_canonical.csv"
LOG = ROOT / "reports" / "canonical_dataset_log.md"

VARS = {  # API name -> canonical name
    "temperature_2m": "temp_c",
    "relative_humidity_2m": "rel_humidity_pct",
    "dew_point_2m": "dew_point_c",
    "precipitation": "precip_mm",
    "wind_speed_10m": "wind_speed_10m_kmh",
    "cloud_cover": "cloud_cover_pct",
    "shortwave_radiation": "ghi_wm2",
}
REGION_COL = {"Northern": "n", "Western": "w", "Southern": "s", "Eastern": "e", "North-Eastern": "ne"}


def load_weather() -> pd.DataFrame:
    files = sorted(WEATHER_DIR.glob("era5_*.csv"))
    if len(files) != 12:
        sys.exit(f"Expected 12 weather files in {WEATHER_DIR}, found {len(files)}.")
    return pd.concat([pd.read_csv(f, parse_dates=["timestamp"]) for f in files], ignore_index=True)


def main():
    for p in (DEMAND, CAL):
        if not p.exists():
            sys.exit(f"Missing {p}; run the earlier scripts first (see README).")
    d = pd.read_csv(DEMAND, parse_dates=["timestamp"]).set_index("timestamp")
    w = load_weather()

    # region mean, then equal-weight mean of regions
    reg = w.groupby(["timestamp", "grid_region"])[list(VARS)].mean()
    nat = reg.groupby("timestamp").mean().rename(columns=VARS)
    temp_reg = reg["temperature_2m"].unstack("grid_region").rename(
        columns={k: f"temp_c_{v}" for k, v in REGION_COL.items()})
    # national night = shortwave radiation is 0 at every city
    night = (w.groupby("timestamp")["shortwave_radiation"].max() == 0).rename("is_national_night")

    out = d.join(nat).join(temp_reg).join(night)
    assert out[list(VARS.values())].notna().all().all(), "weather has gaps against the demand grid"

    out["solar_night_zeroed"] = out["is_national_night"] & (out["solar_generation_mw"] > 0)
    solar_before = out["solar_generation_mw"].copy()
    out.loc[out["is_national_night"] & out["solar_generation_mw"].notna(), "solar_generation_mw"] = 0.0

    cal = pd.read_csv(CAL, parse_dates=["timestamp"]).set_index("timestamp")
    out = out.join(cal)
    assert out[cal.columns.difference(["holiday_name", "festival_name"])].notna().all().all()

    assert len(out) == 33432 and out.index.is_unique and out.index.is_monotonic_increasing
    out.to_csv(OUT, float_format="%.4f")

    yr = out.index.year
    nz = out.loc[out["is_national_night"]]
    lines = [
        "# Canonical dataset log (generated by `scripts/build_canonical_dataset.py`)", "",
        f"Rows: {len(out):,}; columns: {out.shape[1]}. Output: `data/processed/india_hourly_canonical.csv`.", "",
        "## Weather aggregate (equal weights over the 5 grid regions)",
        "National temperature (C), by year: " + ", ".join(
            f"{y}: {v:.1f}" for y, v in out.groupby(yr)["temp_c"].mean().items()),
        f"Hours with national night (radiation 0 at all 12 cities): {int(out['is_national_night'].sum()):,} "
        f"({out['is_national_night'].mean():.1%})", "",
        "## Solar night correction",
        f"Hours set to 0: {int(out['solar_night_zeroed'].sum()):,}",
        "Mean solar in national-night hours before correction (MW), by year: " + ", ".join(
            f"{y}: {v:.0f}" for y, v in solar_before[out['is_national_night']].groupby(
                out.index[out['is_national_night']].year).mean().items()),
        "After correction: 0 by construction. Daytime offsets are not corrected.", "",
        "## Missing values in key columns",
        f"electricity_demand_mw missing: {int(out['electricity_demand_mw'].isna().sum())} hours "
        f"(see cleaning_log.md); solar/wind missing: {int(out['solar_generation_mw'].isna().sum())} / "
        f"{int(out['wind_generation_mw'].isna().sum())}", "",
        f"Holiday hours: {int(out['is_holiday'].sum()):,}; major-festival hours: {int(out['is_major_festival'].sum()):,}",
        "",
        "## Correlations with demand (all years, FULL sample - descriptive only, do not use for model selection)",
        "| variable | Pearson r |", "|---|---:|",
    ]
    for c in ["temp_c", "rel_humidity_pct", "dew_point_c", "wind_speed_10m_kmh", "ghi_wm2", "cloud_cover_pct"]:
        lines.append(f"| {c} | {out['electricity_demand_mw'].corr(out[c]):.3f} |")
    LOG.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {OUT} ({out.shape[0]} x {out.shape[1]}) and {LOG}")


if __name__ == "__main__":
    main()
