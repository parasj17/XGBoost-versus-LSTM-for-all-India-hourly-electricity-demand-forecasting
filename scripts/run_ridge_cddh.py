"""Task 3.3 (extension B): cooling/heating degree-hour features and an apparent-temperature index for RIDGE (design in docs/experiment_protocol.md, deviation log 2026-10-16).

Reference: ridge_full_rel (the ridge variant with weather, anchor-relative target) as in run_baselines. Extension: the same model plus, at the forecast origin t,
cooling degree-hours max(T - base, 0), heating degree-hours max(base - T, 0), their 24 h rolling means, and the apparent temperature
AT = T + 0.33 e - 0.70 w - 4.00 (e = vapour pressure from relative humidity and temperature in hPa, w = wind speed in m/s; Australian BoM formula).
The base temperature is chosen on the TRAINING period only from {18, 20, 22, 24, 26, 28} C by the in-sample training MAE of the anchor-relative target (penalty fixed at 10);
the penalty is then chosen on validation as in the baselines.
  py scripts/run_ridge_cddh.py               validation only (test not loaded)
  py scripts/run_ridge_cddh.py --with-test   adds the test period, ONCE (lock reports/tables/RIDGE_CDDH_TEST_DONE.lock)
Output: reports/ridge_cddh.md (validation) or reports/ridge_cddh_test.md
"""
import argparse
import importlib
import sys
from pathlib import Path

import numpy as np
import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "scripts"))
rb = importlib.import_module("run_baselines")
rt = importlib.import_module("run_test_evaluation")
LOCK = ROOT / "reports" / "tables" / "RIDGE_CDDH_TEST_DONE.lock"
BASES = [18, 20, 22, 24, 26, 28]


def extra_features(df, base):
    T = df["temp_c"]
    X = pd.DataFrame(index=df.index)
    X["cdh"] = (T - base).clip(lower=0)
    X["hdh"] = (base - T).clip(lower=0)
    X["cdh_roll24"] = X["cdh"].rolling(24, min_periods=24).mean()
    X["hdh_roll24"] = X["hdh"].rolling(24, min_periods=24).mean()
    e = df["rel_humidity_pct"] / 100.0 * 6.105 * np.exp(17.27 * T / (237.7 + T))
    X["apparent_temp"] = T + 0.33 * e - 0.70 * (df["wind_speed_10m_kmh"] / 3.6) - 4.00
    return X


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--with-test", action="store_true")
    args = ap.parse_args()
    if args.with_test and LOCK.exists():
        sys.exit("The ridge degree-hour test evaluation was already run.")
    commit, dirty = rb.git_state()
    if args.with_test and dirty:
        sys.exit("Working tree is not clean: commit first.")
    df = pd.read_csv(rb.SRC, parse_dates=["timestamp"]).set_index("timestamp").loc[:(rt.TEST_END if args.with_test else rb.VAL_END)]
    md = ["# " + ("Ridge with degree-hour features: validation and test" if args.with_test else "Ridge with degree-hour features: validation") + " (generated by `scripts/run_ridge_cddh.py`)", "",
          f"Git commit `{(commit or 'n/a')[:10]}`. ridge_full_rel with and without cooling/heating degree-hours (base temperature chosen on the training period), their 24 h means and an apparent-temperature index. "
          "MAE in MW; differences are with-minus-without (negative = the extra features help), 95% block bootstrap.", ""]
    rng = np.random.default_rng(0)
    for h in rb.HORIZONS:
        b = rb.build(df, h)
        Xs = {n: rb.design(b, rel, full) for n, (rel, full) in
              {"g01_abs": (False, False), "g01_rel": (True, False), "full_abs": (False, True), "full_rel": (True, True)}.items()}
        need = pd.concat(Xs.values(), axis=1).notna().all(axis=1) & b["y"].notna() & b["anchors"]["a24"].notna()
        if h <= 168:
            need &= b["anchors"]["a168"].notna()
        valid = need & b["target_obs"]
        Tt = b["T"]
        in_tr = valid & (Tt <= rb.TRAIN_END)
        in_va = valid & (Tt >= rb.VAL_START) & (Tt <= rb.VAL_END)
        in_te = valid & (Tt >= rt.TEST_START) & (Tt <= rt.TEST_END) if args.with_test else None
        a24 = b["anchors"]["a24"]
        a24v = a24.fillna(1.0).to_numpy()
        pos = np.arange(len(df))
        idx_va = pos[in_va.to_numpy()]
        y_va, a_va = b["target"].to_numpy()[idx_va], a24v[idx_va]
        tgt = b["target"] / a24
        Xbase = Xs["full_rel"]

        def fit_eval(X, alpha, masks):
            m = rb.ridge_fit(X[in_tr], tgt[in_tr], alpha)
            return [rb.ridge_pred(m, X[mk]) for mk in masks]

        # reference ridge: penalty on validation
        ref = {al: fit_eval(Xbase, al, [in_va])[0] * a_va for al in rb.ALPHAS}
        a_ref = min(ref, key=lambda al: np.mean(np.abs(ref[al] - y_va)))
        # base temperature on TRAINING fit (penalty 10)
        train_mae = {}
        for base in BASES:
            X = pd.concat([Xbase, extra_features(df, base)], axis=1)
            ok = in_tr & X.notna().all(axis=1)
            m = rb.ridge_fit(X[ok], tgt[ok], 10)
            train_mae[base] = float(np.mean(np.abs(rb.ridge_pred(m, X[ok]) - tgt[ok].to_numpy())))
        base = min(train_mae, key=train_mae.get)
        Xc = pd.concat([Xbase, extra_features(df, base)], axis=1)
        valid2 = Xc.notna().all(axis=1)
        assert bool(valid2[valid].all()), "extra features missing for valid samples"
        cand = {al: fit_eval(Xc, al, [in_va])[0] * a_va for al in rb.ALPHAS}
        a_new = min(cand, key=lambda al: np.mean(np.abs(cand[al] - y_va)))
        e_ref, e_new = np.abs(ref[a_ref] - y_va), np.abs(cand[a_new] - y_va)
        d = e_new - e_ref
        lo, hi = rb.block_ci(d, rng)
        md += [f"## Horizon {h} h", "", f"Base temperature chosen on the training period: {base} C (training MAE by base in the ratio target: " +
               ", ".join(f"{k}: {v:.5f}" for k, v in train_mae.items()) + f"). Penalty: reference {a_ref}, with degree-hours {a_new}.", "",
               "| | validation MAE (MW) |", "|---|---:|", f"| ridge_full_rel (reference) | {e_ref.mean():,.0f} |", f"| + degree-hours and apparent temperature | {e_new.mean():,.0f} |",
               f"| difference (95% CI) | {d.mean():+,.0f} ({lo:+,.0f} to {hi:+,.0f}) |", ""]
        if args.with_test:
            idx_te = pos[in_te.to_numpy()]
            y_te, a_te = b["target"].to_numpy()[idx_te], a24v[idx_te]
            p_ref = fit_eval(Xbase, a_ref, [in_te])[0] * a_te
            p_new = fit_eval(Xc, a_new, [in_te])[0] * a_te
            z = np.load(ROOT / "data" / "interim" / "predictions" / f"h{h}.npz")
            assert np.allclose(z["y_te"], y_te)
            dt = np.abs(p_new - y_te) - np.abs(p_ref - y_te)
            lo, hi = rb.block_ci(dt, rng)
            md += ["Test period (single run):", "", "| model | test MAE (MW) |", "|---|---:|", f"| ridge_full_rel (reference) | {np.mean(np.abs(p_ref - y_te)):,.0f} |",
                   f"| + degree-hours and apparent temperature | {np.mean(np.abs(p_new - y_te)):,.0f} |", f"| difference (95% CI) | {dt.mean():+,.0f} ({lo:+,.0f} to {hi:+,.0f}) |",
                   f"| for context: selected ridge of the frozen run | {np.mean(np.abs(z['te__ridge_best'] - y_te)):,.0f} |", f"| for context: XGBoost S4 | {np.mean(np.abs(z['te__xgb_S4_full_A'] - y_te)):,.0f} |", ""]
        print(f"h={h} done: validation reference {e_ref.mean():.0f} -> with degree-hours {e_new.mean():.0f} (base {base})", flush=True)
    out = ROOT / "reports" / ("ridge_cddh_test.md" if args.with_test else "ridge_cddh.md")
    out.write_text(chr(10).join(md) + chr(10), encoding="utf-8")
    if args.with_test:
        LOCK.write_text(f"ridge degree-hour test run completed at commit {commit}" + chr(10), encoding="utf-8")
    print("wrote", out)


if __name__ == "__main__":
    main()
