"""Learning curve at the long horizons 72 h and 168 h (protocol deviation log, 2026-10-16). Validation period only; the test period is never loaded.

XGBoost S4_full_A (ratio target) and LSTM L4_full_A with the long-horizon hyper-parameters (reports/tables/long_horizon_config.json), trained on the most recent
12 months (targets 2023-01-01..2023-12-31), 18 months (2022-07-01..2023-12-31) and the full training period (2021-09..2023-12); 3 seeds; early stopping on the
validation period for every size (XGBoost up to 3,000 trees, patience 40; LSTM up to 30 epochs, patience 5), same procedure for all sizes, mean of the per-seed MAE.
Output: reports/long_learning_curve.md.   Usage: py scripts/run_long_learning_curve.py
"""
import importlib
import json
import sys
from pathlib import Path

import numpy as np
import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "scripts"))
rb = importlib.import_module("run_baselines")
ft = importlib.import_module("features_tabular")
rx = importlib.import_module("run_xgboost")
rl = importlib.import_module("run_lstm")
rt = importlib.import_module("run_test_evaluation")
SIZES = {"12 months": pd.Timestamp("2023-01-01"), "18 months": pd.Timestamp("2022-07-01"), "full (28 months)": pd.Timestamp("2000-01-01")}


def main():
    rx.MAX_TREES = 3000
    cfg = json.loads((ROOT / "reports" / "tables" / "long_horizon_config.json").read_text(encoding="utf-8"))
    df = pd.read_csv(rb.SRC, parse_dates=["timestamp"]).set_index("timestamp").loc[:rb.VAL_END]
    y_all = df["electricity_demand_mw"].ffill().to_numpy(dtype=float)
    md = ["# Learning curve at 72 h and 168 h (generated by `scripts/run_long_learning_curve.py`)", "",
          "Validation period only. XGBoost S4 and LSTM L4 with the long-horizon hyper-parameters, trained on the most recent 12 / 18 months and on the full training period; "
          "early stopping on validation for every size (mildly optimistic, identical procedure for all sizes); MAE in MW, mean of 3 per-seed MAEs. Descriptive, three sizes only.", ""]
    for h in (72, 168):
        c = cfg[str(h)]
        b = rb.build(df, h)
        Xs = {n: rb.design(b, rel, full) for n, (rel, full) in
              {"g01_abs": (False, False), "g01_rel": (True, False), "full_abs": (False, True), "full_rel": (True, True)}.items()}
        need = pd.concat(Xs.values(), axis=1).notna().all(axis=1) & b["y"].notna() & b["anchors"]["a24"].notna() & b["anchors"]["a168"].notna()
        valid = need & b["target_obs"]
        Tt = b["T"]
        in_full = valid & (Tt <= rb.TRAIN_END)
        in_va = valid & (Tt >= rb.VAL_START) & (Tt <= rb.VAL_END)
        a24 = b["anchors"]["a24"]
        a24v = a24.fillna(1.0).to_numpy()
        pos = np.arange(len(df))
        idx_va = pos[in_va.to_numpy()]
        y_va, a_va = b["target"].to_numpy()[idx_va], a24v[idx_va]
        zx = b["target"] / a24
        Xf = ft.build_features(df, h, ft.FEATURE_SETS["S4_full_A"], True)
        z_all = ((b["target"] / a24 - 1) * 100).to_numpy()
        C, S = rl.step_channels(df, True, True, rb.TRAIN_END), rl.static_features(df, h, b, True)
        zsd = float(np.nanstd(z_all[pos[in_full.to_numpy()]]))
        zt = np.nan_to_num(z_all / zsd)
        vaD = rl.Data(y_all, a24v, C, S, zt, idx_va)
        md += [f"## Horizon {h} h", "", "| training data | samples | XGBoost S4 | LSTM L4 | LSTM / XGBoost |", "|---|---:|---:|---:|---:|"]
        for name, start in SIZES.items():
            in_tr = in_full & (Tt >= start)
            idx_tr = pos[in_tr.to_numpy()]
            xm = [float(np.mean(np.abs(rx.fit_predict(Xf[in_tr], zx[in_tr], Xf[in_va], zx[in_va], c["xgb_params"], sd, a_va, True)[0] - y_va))) for sd in rt.SEEDS]
            trD = rl.Data(y_all, a24v, C, S, zt, idx_tr)
            lm = []
            for sd in rt.SEEDS:
                net, mae, *_ = rl.train(trD, vaD, C.shape[1] + 1, S.shape[1], c["lstm_params"], sd, 30, 5, zsd, a_va, y_va)
                lm.append(float(mae))
            md.append(f"| {name} | {int(in_tr.sum()):,} | {np.mean(xm):,.0f} | {np.mean(lm):,.0f} | {np.mean(lm) / np.mean(xm):.2f} |")
            print(f"h={h} {name}: XGBoost {np.mean(xm):.0f} LSTM {np.mean(lm):.0f}", flush=True)
        md.append("")
    (ROOT / "reports" / "long_learning_curve.md").write_text(chr(10).join(md) + chr(10), encoding="utf-8")
    print("wrote reports/long_learning_curve.md")


if __name__ == "__main__":
    main()
