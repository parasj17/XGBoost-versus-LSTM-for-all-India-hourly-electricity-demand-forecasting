"""Derived day-wise view of the 24 h-ahead forecasts (plan task 9.8; declared in docs/experiment_protocol.md, entry of 2026-10-19).

No model is fitted or re-run: the script reads the saved test-period predictions of the frozen 24 h horizon (data/interim/predictions/h24.npz) and turns the hourly forecasts into daily
energy (MU), daily peak (MW) and peak hour, for every day of the test period that has all 24 valid hours. Paired moving-block bootstrap over whole days (28-day blocks, 1,000 resamples,
fixed seed). Writes reports/daywise_test.md, reports/tables/daywise_results.json and reports/figures/fig13_daywise.png.
Usage: py -I scripts/run_daywise.py
"""
import json
import subprocess
from pathlib import Path

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt
import numpy as np
import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
BLOCK, B, SEED = 28, 1000, 0
MODELS = {"naive": ("te__snaive24", "Best naive (same hour yesterday)"), "ridge": ("te__ridge_best", "Ridge"), "xgb": ("te__xgb_S4_full_A", "XGBoost S4"), "lstm": ("te__lstm_L4_full_A", "LSTM L4")}
COL = {"ridge": "#0072B2", "xgb": "#D55E00", "lstm": "#009E73", "naive": "#7F7F7F"}
SEASONS = ["winter", "pre_monsoon_summer", "monsoon", "post_monsoon"]
rng = np.random.default_rng(SEED)


def boot_idx(n):
    nb = int(np.ceil(n / BLOCK))
    starts = rng.integers(0, n - BLOCK + 1, size=(B, nb))
    return (starts[:, :, None] + np.arange(BLOCK)).reshape(B, -1)[:, :n]


def ci(d, idx):
    return tuple(np.percentile(d[idx].mean(axis=1), [2.5, 97.5]))


z = np.load(ROOT / "data" / "interim" / "predictions" / "h24.npz", allow_pickle=True)
t = pd.to_datetime(np.array(z["target_time_te"], dtype="datetime64[ns]"))
order = np.argsort(t.values)
t = t[order]
y = z["y_te"].astype(float)[order]
season_h = np.array(z["season_te"]).astype(str)[order]
pred = {m: z[k].astype(float)[order] for m, (k, _) in MODELS.items()}
day = pd.Series(t.date)
cnt = day.groupby(day.values).transform("size").to_numpy()
keep = cnt == 24
n_days_any, n_days = day.nunique(), int(keep.sum() // 24)
assert np.all(t[keep].hour.values.reshape(-1, 24) == np.arange(24))
Y = y[keep].reshape(-1, 24)
P = {m: v[keep].reshape(-1, 24) for m, v in pred.items()}
dates = pd.to_datetime(pd.Series(t[keep].date).iloc[::24].values)
season_d = season_h[keep].reshape(-1, 24)[:, 0]
assert all((season_h[keep].reshape(-1, 24) == season_d[:, None]).all(axis=1))

act_E, act_pk, act_ph = Y.sum(axis=1) / 1000, Y.max(axis=1), Y.argmax(axis=1)
Q = {}
for m, A in P.items():
    pE, pk, ph = A.sum(axis=1) / 1000, A.max(axis=1), A.argmax(axis=1)
    Q[m] = {"eE": pE - act_E, "ePk": pk - act_pk, "hit0": (ph == act_ph).astype(float), "hit1": (np.abs(ph - act_ph) <= 1).astype(float), "pE": pE, "pk": pk}
idx = boot_idx(n_days)

res = {"n_days": n_days, "n_days_with_any_hour": int(n_days_any), "models": {}, "diffs": {}, "season": {}}
for m, q in Q.items():
    aE, aP = np.abs(q["eE"]), np.abs(q["ePk"])
    res["models"][m] = {"energy_MAE_MU": aE.mean(), "energy_MAE_ci": ci(aE, idx), "energy_MAPE_pct": float(np.mean(aE / act_E) * 100), "energy_bias_MU": q["eE"].mean(),
                        "peak_MAE_MW": aP.mean(), "peak_MAE_ci": ci(aP, idx), "peak_MAPE_pct": float(np.mean(aP / act_pk) * 100), "peak_bias_MW": q["ePk"].mean(),
                        "peak_hour_exact_pct": 100 * q["hit0"].mean(), "peak_hour_exact_ci": tuple(100 * np.array(ci(q["hit0"], idx))),
                        "peak_hour_within1_pct": 100 * q["hit1"].mean(), "peak_hour_within1_ci": tuple(100 * np.array(ci(q["hit1"], idx)))}
PAIRS = [("xgb", "ridge"), ("lstm", "xgb"), ("lstm", "ridge"), ("xgb", "naive")]
for a, b in PAIRS:
    dE = np.abs(Q[a]["eE"]) - np.abs(Q[b]["eE"])
    dP = np.abs(Q[a]["ePk"]) - np.abs(Q[b]["ePk"])
    d0, d1 = 100 * (Q[a]["hit0"] - Q[b]["hit0"]), 100 * (Q[a]["hit1"] - Q[b]["hit1"])
    res["diffs"][f"{a}-{b}"] = {k: (float(d.mean()), *map(float, ci(d, idx))) for k, d in (("energy_MU", dE), ("peak_MW", dP), ("hit_exact_pp", d0), ("hit_within1_pp", d1))}
for s in SEASONS:
    mk = season_d == s
    res["season"][s] = {"n_days": int(mk.sum()), **{m: {"energy_MAE_MU": float(np.abs(Q[m]["eE"][mk]).mean()), "peak_MAE_MW": float(np.abs(Q[m]["ePk"][mk]).mean())} for m in Q}}

zen = [json.loads(line) for line in open(ROOT / "reports" / "tables" / "daily_multiyear.jsonl", encoding="utf-8")]
z24 = next(r for r in zen if r["horizon"] == 1 and r["year"] == 2024)
zcl = [r for r in zen if r["horizon"] == 1 and r["year"] in (2017, 2018, 2019, 2023, 2024)]
commit = subprocess.run(["git", "rev-parse", "HEAD"], cwd=ROOT, capture_output=True, text=True).stdout.strip()[:10]
f0 = lambda v: f"{v:,.0f}"
f1 = lambda v: f"{v:,.1f}"
sg = lambda v, f=f1: ("+" if v >= 0 else "-") + f(abs(v))
md = ["# Day-wise view of the 24 h-ahead forecasts (generated by `scripts/run_daywise.py`; plan task 9.8)", "",
      f"Git commit `{commit}`. Declared in `docs/experiment_protocol.md` (entry of 2026-10-19) before any number was computed. No model was fitted or re-run: the hourly 24 h-ahead test predictions saved by the single test run were aggregated. "
      f"Test days {dates.min().date()} to {dates.max().date()}: {n_days} days with all 24 valid hours (of {n_days_any} days with any valid hour; days with a missing hour are excluded). "
      "Each hour of a day is the 24 h-ahead forecast issued exactly 24 h earlier, so a day's 24 forecasts come from 24 different issue times (a stitched rolling day-ahead, not one forecast issued once per day); this is optimistic compared with an operational day-ahead forecast. "
      "Daily energy = sum of the 24 hourly values / 1000 (MU; the hourly series is a snapshot at the start of each hour, so this approximates energy). Daily peak = maximum hourly value; peak hour = clock hour of the maximum. "
      f"Intervals: 95% paired moving-block bootstrap over whole days (block {BLOCK} days, {B:,} resamples, fixed seed).", "",
      "## Accuracy by model", "",
      "| model | energy MAE (MU) [95% CI] | energy MAPE % | energy bias (MU) | peak MAE (MW) [95% CI] | peak MAPE % | peak bias (MW) | peak hour exact % [CI] | peak hour within 1 h % [CI] |", "|---|---:|---:|---:|---:|---:|---:|---:|---:|"]
for m, (_, lab) in MODELS.items():
    r = res["models"][m]
    md.append(f"| {lab} | {f1(r['energy_MAE_MU'])} [{f1(r['energy_MAE_ci'][0])}, {f1(r['energy_MAE_ci'][1])}] | {r['energy_MAPE_pct']:.2f} | {sg(r['energy_bias_MU'])} | {f0(r['peak_MAE_MW'])} [{f0(r['peak_MAE_ci'][0])}, {f0(r['peak_MAE_ci'][1])}] | {r['peak_MAPE_pct']:.2f} | {sg(r['peak_bias_MW'], f0)} | "
              f"{r['peak_hour_exact_pct']:.1f} [{r['peak_hour_exact_ci'][0]:.1f}, {r['peak_hour_exact_ci'][1]:.1f}] | {r['peak_hour_within1_pct']:.1f} [{r['peak_hour_within1_ci'][0]:.1f}, {r['peak_hour_within1_ci'][1]:.1f}] |")
md += ["", "## Paired differences (first minus second; negative = first better for errors, positive = first better for hit rates)", "",
       "| first | second | energy MAE (MU) | peak MAE (MW) | peak hour exact (percentage points) | peak hour within 1 h (percentage points) |", "|---|---|---|---|---|---|"]
for a, b in PAIRS:
    d = res["diffs"][f"{a}-{b}"]
    c = lambda k, f: f"{sg(d[k][0], f)} ({sg(d[k][1], f)} to {sg(d[k][2], f)})"
    md.append(f"| {MODELS[a][1]} | {MODELS[b][1]} | {c('energy_MU', f1)} | {c('peak_MW', f0)} | {c('hit_exact_pp', f1)} | {c('hit_within1_pp', f1)} |")
md += ["", "Differences whose interval includes zero are not distinguishable.", "", "## By season of the target day (MAE)", "",
       "| season | days | " + " | ".join(f"{MODELS[m][1]} energy (MU)" for m in Q) + " | " + " | ".join(f"{MODELS[m][1]} peak (MW)" for m in Q) + " |", "|---|---:|" + "---:|" * (2 * len(Q))]
for s in SEASONS:
    r = res["season"][s]
    md.append(f"| {s} | {r['n_days']} | " + " | ".join(f1(r[m]["energy_MAE_MU"]) for m in Q) + " | " + " | ".join(f0(r[m]["peak_MAE_MW"]) for m in Q) + " |")
md += ["", "## Reference: the Zenodo daily study (units only)", "",
       f"`reports/daily_multiyear.md` forecasts the daily total directly from daily data (Zenodo series, a different dataset and different periods). Its 1-day-ahead MAE in MU: 2024 fold (1 January to 28 April 2024) naive {f1(z24['naive'])}, ridge {f1(z24['ridge'])}, XGBoost {f1(z24['xgb'])}, LSTM {f1(z24['lstm'])}; "
       f"mean of the five clean folds naive {f1(np.mean([r['naive'] for r in zcl]))}, ridge {f1(np.mean([r['ridge'] for r in zcl]))}, XGBoost {f1(np.mean([r['xgb'] for r in zcl]))}, LSTM {f1(np.mean([r['lstm'] for r in zcl]))}. "
       "The numbers above are not a like-for-like comparison with these (different period, different data, hourly-derived energy), only the same unit.", "",
       "## Caveats", "",
       "- One test year, so about 355 daily errors; the intervals reflect day-to-day sampling noise within that year, not year-to-year variation.",
       "- The 24 forecasts of a day are not issued at one time; a real day-ahead forecast issued once (for example at 10:00 on the previous day) must look 14-37 h ahead and would be less accurate. That is the parked task 9.7.",
       "- Daily energy from hourly snapshots is an approximation of the metered energy.",
       "- Peak hour is defined as the hour of the maximum; when the evening and the morning peaks are close in size the exact hour is unstable, so the within-1-hour share is the more informative number.",
       "- The test year has been used several times for declared analyses; this view only re-aggregates predictions already produced and tunes nothing.", ""]
(ROOT / "reports" / "daywise_test.md").write_text(chr(10).join(md), encoding="utf-8")
(ROOT / "reports" / "tables" / "daywise_results.json").write_text(json.dumps(res, indent=1, default=float), encoding="utf-8")
print(chr(10).join(md))

# ---- figure ----
plt.rcParams.update({"font.size": 10, "axes.spines.top": False, "axes.spines.right": False, "axes.grid": True, "grid.alpha": 0.25, "figure.dpi": 120, "savefig.bbox": "tight"})
fig, axes = plt.subplots(2, 2, figsize=(11, 7))
ax = axes[0, 0]
ax.plot(dates, act_E, color="k", lw=1.2, label="Actual")
ax.plot(dates, Q["xgb"]["pE"], color=COL["xgb"], lw=0.9, label="XGBoost S4")
ax.set_ylabel("Daily energy (MU)")
ax.set_title("Daily energy, actual and 24 h-ahead (XGBoost)")
ax.legend(frameon=False)
ax.tick_params(axis="x", rotation=30)
order_m = ["naive", "ridge", "xgb", "lstm"]
for ax, key, ttl, scale, unit in ((axes[0, 1], "energy_MAE", "Daily energy error", 1, "MAE (MU)"), (axes[1, 0], "peak_MAE", "Daily peak error", 1000, "MAE (GW)")):
    for i, m in enumerate(order_m):
        r = res["models"][m]
        v = r[key + ("_MU" if key == "energy_MAE" else "_MW")] / scale
        lo, hi = np.array(r[key + "_ci"]) / scale
        ax.errorbar(i, v, yerr=[[v - lo], [hi - v]], fmt="o", color=COL[m], capsize=3)
    ax.set_xticks(range(4), [MODELS[m][1].replace(" (same hour yesterday)", "") for m in order_m], rotation=15)
    ax.set_ylabel(unit)
    ax.set_title(ttl + " (95% block-bootstrap intervals)")
ax = axes[1, 1]
w = 0.38
for j, (k, lab, hatch) in enumerate((("peak_hour_exact", "exact hour", None), ("peak_hour_within1", "within 1 h", "//"))):
    for i, m in enumerate(order_m):
        r = res["models"][m]
        v = r[k + "_pct"]
        lo, hi = r[k + "_ci"]
        ax.bar(i + (j - 0.5) * w, v, w, color=COL[m], hatch=hatch, alpha=0.9 if j == 0 else 0.55, yerr=[[v - lo], [hi - v]], capsize=2)
ax.set_xticks(range(4), [MODELS[m][1].replace(" (same hour yesterday)", "") for m in order_m], rotation=15)
ax.set_ylabel("Days with the peak hour right (%)")
ax.set_title("Peak hour: solid = exact, hatched = within 1 h")
fig.suptitle(f"Day-wise view of the 24 h-ahead forecasts, test period ({n_days} complete days)", y=1.0)
fig.tight_layout()
fig.savefig(ROOT / "reports" / "figures" / "fig13_daywise.png", dpi=200)
plt.close(fig)
print("wrote fig13_daywise")
