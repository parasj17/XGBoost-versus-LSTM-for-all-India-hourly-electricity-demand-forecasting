"""Daily multi-year walk-forward on the Zenodo national daily energy (extension A; design in docs/experiment_protocol.md, deviation log 2026-10-16).

Target: all-India daily energy met (MU), horizons 1 and 7 days, ratio to the same-weekday anchor. Expanding-window folds: for each test year Y in 2017..2024 (2020 = COVID,
2024 = 1 Jan - 28 Apr) every model is trained on all valid samples whose target precedes 1 January of Y and scored on year Y.
Hyper-parameters are chosen ONCE on validation (train targets <= 2020-12-31, validation 2021-2022; ridge penalty grid, XGBoost 20 random trials as in the daily study, daily
LSTM 30 random trials) and frozen for every fold (XGBoost trees and LSTM epochs fixed from the validation fits). Folds 2021 and 2022 lie in the tuning period (flagged).
Samples are identical for all models (target, anchor and all lag/weather features present; at least 55 days of history for the LSTM window).
Output: reports/daily_multiyear.md, reports/tables/daily_multiyear.jsonl.   Usage: py scripts/run_daily_multiyear.py [--smoke]
"""
import argparse
import importlib
import json
import sys
import time
from pathlib import Path

import holidays
import numpy as np
import pandas as pd
import xgboost as xgb

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "scripts"))
rb = importlib.import_module("run_baselines")
rx = importlib.import_module("run_xgboost")
rl = importlib.import_module("run_lstm")
drs = importlib.import_module("run_daily_regional_study")

TRAIN_END, VAL_START, VAL_END = pd.Timestamp("2020-12-31"), pd.Timestamp("2021-01-01"), pd.Timestamp("2022-12-31")
YEARS = [2017, 2018, 2019, 2020, 2021, 2022, 2023, 2024]
TUNING_YEARS, SHOCK_YEARS = {2021, 2022}, {2020}
HORIZONS, SEEDS, N_XGB, N_LSTM, WIN = [1, 7], [0, 1, 2], 20, 30, 56
LAST = pd.Timestamp("2024-04-28")
torch_seed = None


def lstm_arrays(y, W, T, hol, train_end):
    yf = y.ffill().bfill().to_numpy(dtype=float)
    Wf = W.ffill().bfill()
    st = Wf[Wf.index <= train_end]
    Z = ((Wf - st.mean()) / st.std().replace(0, 1)).fillna(0).to_numpy(dtype=np.float32)
    idx = y.index
    cyc = np.stack([np.sin(2 * np.pi * idx.dayofweek / 7), np.cos(2 * np.pi * idx.dayofweek / 7),
                    np.sin(2 * np.pi * (idx.month - 1) / 12), np.cos(2 * np.pi * (idx.month - 1) / 12)], axis=1).astype(np.float32)
    C = np.concatenate([cyc, Z], axis=1)
    Td = pd.DatetimeIndex(T)
    S = np.stack([np.sin(2 * np.pi * Td.dayofweek / 7), np.cos(2 * np.pi * Td.dayofweek / 7), np.sin(2 * np.pi * (Td.month - 1) / 12),
                  np.cos(2 * np.pi * (Td.month - 1) / 12), np.array([1.0 if t in hol else 0.0 for t in Td]), (Td.dayofweek >= 5).astype(float)], axis=1).astype(np.float32)
    return yf, C, S


def make_data(yf, a, C, S, zt, idx):
    d = rl.Data(yf, a, C, S, zt, idx)
    d.off = np.arange(-(WIN - 1), 1)               # 56-day window instead of the 168-hour window
    return d


def main():
    global N_XGB, N_LSTM, YEARS
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--smoke", action="store_true")
    args = ap.parse_args()
    out_md, out_jl = ROOT / "reports" / "daily_multiyear.md", ROOT / "reports" / "tables" / "daily_multiyear.jsonl"
    if args.smoke:
        N_XGB, N_LSTM, YEARS = 2, 2, [2023]
        out_md, out_jl = out_md.with_name("daily_multiyear_smoke.md"), out_jl.with_name("daily_multiyear_smoke.jsonl")
    e = drs.load_energy(LAST)
    nat = e["Total"]
    _, nat_w = drs.weather_by_region(e.index)
    hol = holidays.India(years=range(2013, 2026))
    commit, dirty = rb.git_state()
    log = open(out_jl, "a", encoding="utf-8")
    pos_all = np.arange(len(nat))
    md = ["# Daily multi-year walk-forward on the Zenodo national daily energy (generated by `scripts/run_daily_multiyear.py`)", "",
          f"Git commit `{(commit or 'n/a')[:10]}`. All-India daily energy met (MU), test years 2017-2024 (expanding training window, trained on everything before 1 January of the test year); "
          "hyper-parameters chosen once on the validation years 2021-2022 and frozen. **Folds 2021 and 2022 are in the tuning period (marked *); 2020 is the COVID year (marked c).** "
          "2024 covers 1 January to 28 April only. National weather = the daily-study aggregate (population-weighted state means inside each grid region, equal weight over the five regions). "
          "Exploratory; not part of the frozen hourly protocol.", ""]
    for h in HORIZONS:
        Xn, a, T = drs.features(nat, nat_w, h, hol)
        target = nat.shift(-h)
        valid = target.notna() & a.notna() & Xn.notna().all(axis=1) & pd.Series(pos_all >= WIN - 1, index=nat.index)
        a_fill = a.fillna(1.0).to_numpy()
        z_all = ((target / a - 1) * 100).to_numpy()
        Tt = pd.Series(T, index=nat.index)
        in_tr = valid & (Tt <= TRAIN_END)
        in_va = valid & (Tt >= VAL_START) & (Tt <= VAL_END)
        idx_tr, idx_va = pos_all[in_tr.to_numpy()], pos_all[in_va.to_numpy()]
        y_va, a_va = target.to_numpy()[idx_va], a_fill[idx_va]
        # ---- ridge: penalty on validation
        outs = drs.ridge_fit_predict(Xn[in_tr], pd.Series(z_all, index=nat.index)[in_tr], [Xn[in_va]], [0.1, 1, 10, 100, 1000])
        alpha = min(outs, key=lambda al: np.mean(np.abs((1 + outs[al][0] / 100) * a_va - y_va)))
        # ---- XGBoost: random search on validation, then trees per seed
        r_ = np.random.default_rng(5000 + h)
        best = None
        for _ in range(N_XGB):
            prm = rx.sample_params(r_)
            p, *_ = rx.fit_predict(Xn[in_tr], (target / a)[in_tr], Xn[in_va], (target / a)[in_va], prm, 0, a_va, True)
            mae = float(np.mean(np.abs(p - y_va)))
            if best is None or mae < best[0]:
                best = (mae, prm)
        xprm = best[1]
        trees = {}
        for sd in SEEDS:
            _, m, *_ = rx.fit_predict(Xn[in_tr], (target / a)[in_tr], Xn[in_va], (target / a)[in_va], xprm, sd, a_va, True)
            trees[sd] = int(m.best_iteration) + 1
        # ---- LSTM: random search on validation, epochs per seed
        yf, C, S = lstm_arrays(nat, nat_w, T, hol, TRAIN_END)
        zsd = float(np.nanstd(z_all[idx_tr]))
        zt = np.nan_to_num(z_all / zsd)
        trD, vaD = make_data(yf, a_fill, C, S, zt, idx_tr), make_data(yf, a_fill, C, S, zt, idx_va)
        n_in, n_st = C.shape[1] + 1, S.shape[1]
        r2 = np.random.default_rng(7000 + h)
        lbest = None
        for _ in range(N_LSTM):
            hp = {"hidden": int(r2.choice([16, 32, 48, 64])), "lr": float(np.exp(r2.uniform(np.log(5e-4), np.log(1e-2)))),
                  "dropout": float(r2.uniform(0, 0.3)), "weight_decay": float(np.exp(r2.uniform(np.log(1e-6), np.log(1e-3))))}
            net, mae, hist, *_ = rl.train(trD, vaD, n_in, n_st, hp, 0, 30, 5, zsd, a_va, y_va)
            if lbest is None or mae < lbest[0]:
                lbest = (mae, hp)
        lhp = lbest[1]
        epochs = {}
        for sd in SEEDS:
            _, mae, hist, *_ = rl.train(trD, vaD, n_in, n_st, lhp, sd, 30, 5, zsd, a_va, y_va)
            epochs[sd] = int(np.argmin(hist)) + 1
        md += [f"## Horizon {h} day{'s' if h > 1 else ''}", "", f"Selected on validation (2021-2022): ridge alpha {alpha}; XGBoost validation MAE {best[0]:.1f} MU, trees {list(trees.values())}; "
               f"LSTM validation MAE {lbest[0]:.1f} MU (hidden {lhp['hidden']}, lr {lhp['lr']:.4g}, dropout {lhp['dropout']:.2f}), epochs {list(epochs.values())}.", "",
               "| test year | training days | eval days | naive | ridge | XGBoost | LSTM | XGBoost minus ridge | LSTM minus XGBoost |", "|---|---:|---:|---:|---:|---:|---:|---:|---:|"]
        rows = []
        for Y in YEARS:
            ys, ye = pd.Timestamp(f"{Y}-01-01"), (pd.Timestamp(f"{Y}-12-31") if Y < 2024 else LAST)
            tr_m = valid & (Tt < ys)
            ev_m = valid & (Tt >= ys) & (Tt <= ye)
            if tr_m.sum() < 300 or ev_m.sum() < 30:
                continue
            itr, iev = pos_all[tr_m.to_numpy()], pos_all[ev_m.to_numpy()]
            y_ev, a_ev = target.to_numpy()[iev], a_fill[iev]
            res = {"horizon": h, "year": Y, "n_train": int(tr_m.sum()), "n_eval": int(ev_m.sum()), "git_commit": commit}
            res["naive"] = float(np.mean(np.abs(a_ev - y_ev)))
            zr = pd.Series(z_all, index=nat.index)
            p = drs.ridge_fit_predict(Xn[tr_m], zr[tr_m], [Xn[ev_m]], [alpha])[alpha][0]
            res["ridge"] = float(np.mean(np.abs((1 + p / 100) * a_ev - y_ev)))
            xp = []
            for sd in SEEDS:
                mdl = xgb.XGBRegressor(n_estimators=trees[sd], objective="reg:squarederror", tree_method="hist", device="cpu", n_jobs=rx.NJOBS, random_state=sd, eval_metric="mae", **xprm)
                mdl.fit(Xn[tr_m], zr[tr_m] / 1.0, verbose=False)
                xp.append((1 + mdl.predict(Xn[ev_m]) / 100) * a_ev)
            res["xgb"] = float(np.mean(np.abs(np.mean(xp, axis=0) - y_ev)))
            yf, C, S = lstm_arrays(nat, nat_w, T, hol, ys - pd.Timedelta(days=1))
            zsd_f = float(np.nanstd(z_all[itr]))
            zt_f = np.nan_to_num(z_all / zsd_f)
            trF, evF = make_data(yf, a_fill, C, S, zt_f, itr), make_data(yf, a_fill, C, S, zt_f, iev)
            lp = []
            for sd in SEEDS:
                import torch
                torch.manual_seed(sd)
                rng = np.random.default_rng(sd)
                net = rl.Net(n_in, n_st, lhp["hidden"], lhp["dropout"])
                opt = torch.optim.Adam(net.parameters(), lr=lhp["lr"], weight_decay=lhp["weight_decay"])
                for _ in range(epochs[sd]):
                    net.train()
                    perm = rng.permutation(len(itr))
                    for i in range(0, len(perm), rl.BATCH):
                        xb, sb, zb = trF.batch(perm[i:i + rl.BATCH])
                        loss = ((net(xb, sb) - zb) ** 2).mean()
                        opt.zero_grad(); loss.backward(); opt.step()
                lp.append((1 + rl.predict(net, evF, len(iev)) * zsd_f / 100.0) * a_ev)
            res["lstm"] = float(np.mean(np.abs(np.mean(lp, axis=0) - y_ev)))
            rows.append(res)
            log.write(json.dumps(res) + chr(10)); log.flush()
            flag = "*" if Y in TUNING_YEARS else ("c" if Y in SHOCK_YEARS else "")
            md.append(f"| {Y}{flag} | {res['n_train']:,} | {res['n_eval']:,} | {res['naive']:.1f} | {res['ridge']:.1f} | {res['xgb']:.1f} | {res['lstm']:.1f} | {res['xgb'] - res['ridge']:+.1f} | {res['lstm'] - res['xgb']:+.1f} |")
            print(f"h={h} {Y}: naive {res['naive']:.1f} ridge {res['ridge']:.1f} xgb {res['xgb']:.1f} lstm {res['lstm']:.1f}", flush=True)
        clean = [r for r in rows if r["year"] not in TUNING_YEARS | SHOCK_YEARS]
        for name, rr in (("mean of all folds", rows), (f"mean of folds not in the tuning period or the COVID year ({', '.join(str(r['year']) for r in clean)})", clean)):
            if rr:
                m_ = {k: float(np.mean([r[k] for r in rr])) for k in ("naive", "ridge", "xgb", "lstm")}
                md.append(f"| {name} | | | {m_['naive']:.1f} | {m_['ridge']:.1f} | {m_['xgb']:.1f} | {m_['lstm']:.1f} | {m_['xgb'] - m_['ridge']:+.1f} | {m_['lstm'] - m_['xgb']:+.1f} |")
        md += ["", f"XGBoost better than ridge in {sum(r['xgb'] < r['ridge'] for r in rows)} of {len(rows)} folds; the LSTM better than XGBoost in {sum(r['lstm'] < r['xgb'] for r in rows)} of {len(rows)} folds; "
               f"LSTM better than ridge in {sum(r['lstm'] < r['ridge'] for r in rows)} of {len(rows)} folds.", ""]
    out_md.write_text(chr(10).join(md) + chr(10), encoding="utf-8")
    log.close()
    print("wrote", out_md)


if __name__ == "__main__":
    main()
