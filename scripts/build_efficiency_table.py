"""Consolidated computational-efficiency table (plan task 10.2), generated from the run logs in reports/tables. Writes reports/efficiency_table.md.
Usage: py -I scripts/build_efficiency_table.py
Sources: test_results.jsonl (frozen-configuration refits on the training period, 3 seeds each), xgboost_validation_wide.jsonl and lstm_validation.jsonl
(per-fit time, memory, model size, inference latency, measured during validation), and the tuning-trial logs.
"""
import json
from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parents[1]
T = ROOT / "reports" / "tables"
H = [1, 6, 24, 48]


def jl(name):
    return [json.loads(line) for line in open(T / name, encoding="utf-8")]


test = {r["horizon"]: r for r in jl("test_results.jsonl")}
xw, lv = jl("xgboost_validation_wide.jsonl"), jl("lstm_validation.jsonl")
x_fit = {h: [r for r in xw if r["stage"] == "ablation_fit" and r["feature_set"] == "S4_full_A" and r["horizon"] == h] for h in H}
l_fit = {h: [r for r in lv if r["stage"] == "final_fit" and r["feature_set"] == "L4_full_A" and r["horizon"] == h] for h in H}
m = lambda rows, k: float(np.mean([r[k] for r in rows]))
mi = lambda rows, k: float(np.mean([r["inference"][k] for r in rows if r.get("inference")]))
md = ["# Computational efficiency (generated by `scripts/build_efficiency_table.py` from the logs in `reports/tables`)", "",
      "Hardware: laptop CPU, 4 logical cores, 12.8 GB RAM, no GPU (`cpu` field of the logs). All times are wall-clock seconds measured by the scripts. Headline models only: XGBoost S4 (full features) and LSTM L4 (full features); ridge for reference. "
      "Direct forecasting: one model per horizon and seed.", "",
      "## 1. Final refit on the training period (frozen configuration of the test run)", "",
      "Time for the three seeds together, trees and epochs fixed, no early-stopping evaluation (`refit_seconds` of `test_results.jsonl`).", "",
      "| horizon | ridge (s) | XGBoost S4 (s) | LSTM L4 (s) | LSTM / XGBoost |", "|---:|---:|---:|---:|---:|"]
for h in H:
    s = test[h]["refit_seconds"]
    md.append(f"| {h} h | {s['ridge_best']:.2f} | {s['xgb_S4_full_A']:.0f} | {s['lstm_L4_full_A']:.0f} | {s['lstm_L4_full_A'] / s['xgb_S4_full_A']:.1f} |")
md += ["", "## 2. Per-fit cost during validation (mean over seeds; the early-stopping rounds or epochs actually run)", "",
       "| horizon | XGBoost fit (s) | XGBoost trees | XGBoost peak memory (MB) | XGBoost model (MB) | LSTM fit (s) | LSTM epochs run | LSTM peak memory (MB) | LSTM parameters | LSTM model (KB) |", "|---:|---:|---:|---:|---:|---:|---:|---:|---:|---:|"]
for h in H:
    xf, lf = x_fit[h], l_fit[h]
    md.append(f"| {h} h | {m(xf, 'train_wall_s'):.0f} | {m(xf, 'best_iteration'):.0f} | {m(xf, 'peak_working_set_mb'):.0f} | {m(xf, 'model_bytes') / 1e6:.2f} | {m(lf, 'train_wall_s'):.0f} | {m(lf, 'epochs_run'):.0f} | "
              f"{m(lf, 'peak_working_set_mb'):.0f} | {lf[0]['n_parameters']:,} | {m(lf, 'model_bytes') / 1e3:.0f} |")
md += ["", "## 3. Inference latency (validation, after warm-up; median)", "",
       "| horizon | XGBoost, 4,367 rows in one batch (ms) | LSTM, 1,024 windows in one batch (ms) | XGBoost per row (ms) | LSTM per row (ms) |", "|---:|---:|---:|---:|---:|"]
for h in H:
    xb, lb = mi(x_fit[h], "batch_ms_median"), mi(l_fit[h], "batch_ms_median")
    md.append(f"| {h} h | {xb:.0f} | {lb:.0f} | {xb / 4367:.3f} | {lb / 1024:.3f} |")
rat = [(mi(l_fit[h], "batch_ms_median") / 1024) / (mi(x_fit[h], "batch_ms_median") / 4367) for h in H]
md += ["", f"Batch latency per row is the comparable figure (LSTM {min(rat):.0f}-{max(rat):.0f} times higher per row than the stage-2 XGBoost models; against the stage-1 XGBoost models of `reports/validation_summary.md` (S4 inference 23-56 ms per batch) the ratio is 10-22 times; the LSTM figure includes the sliding-window construction). Single-row latencies were measured through different Python interfaces and are dominated by overhead, so they are not tabulated.", ""]
xt = [r for r in xw if r["stage"] == "tuning_trial"]
lt = [r for r in lv if r["stage"] == "tuning_trial"]
l3 = [r for r in jl("lstm_stage3.jsonl") if r["stage"] == "tuning_trial"]
md += ["## 4. Tuning budget", "", "| search | trials | total time (min) | mean per trial (s) |", "|---|---:|---:|---:|",
       f"| XGBoost, stage 2 (4 horizons) | {len(xt)} | {sum(r['fit_s'] for r in xt) / 60:.1f} | {np.mean([r['fit_s'] for r in xt]):.1f} |",
       f"| LSTM L1/L2/L4 stage 1 (4 horizons) | {len(lt)} | {sum(r['fit_s'] for r in lt) / 60:.1f} | {np.mean([r['fit_s'] for r in lt]):.1f} |",
       f"| LSTM L4 stage 3, widened space with pruning (equal-budget tuning) | {len(l3)} | {sum(r['fit_s'] for r in l3) / 60:.1f} | {np.mean([r['fit_s'] for r in l3]):.1f} |", ""]
md += ["The 72 h and 168 h extensions (`reports/long_*.md`) did not log per-fit time, memory and inference in a comparable form, so they are not part of this table. "
       "Timings depend on this machine and on the thread count (XGBoost 4 threads, PyTorch CPU); only the ratios are meant to transfer.", ""]
md += ["## 5. Wall-clock cost of the completion batch (2026-10-19/20; compiled by hand from the run logs and the 'Run time' lines of the reports)", "",
       "Same laptop (4 threads, CPU only). Times are for whole tasks (all seeds, all trials) and were not measured per fit; several runs overlapped with other jobs (marked), so they are upper bounds and only the order of magnitude should be compared. The first four rows are the validation phase (tuning plus final fits), the last four the single test run (fixed trees or epochs, 3 seeds).", "",
       "| model and task | phase | wall-clock | note |", "|---|---|---:|---|",
       "| LightGBM S4, six horizons and the day-ahead task (30 trials each) | validation | 5 min | all seven tasks together |",
       "| LightGBM S4, same seven tasks, 3 seeds | test | 1.5 min | |",
       "| GRU, 1 h / 24 h / day-ahead (12 trials each) | validation | 74 / 41 / 50 min | the first 15 minutes overlapped with other jobs |",
       "| GRU, 1 h / 24 h / day-ahead, 3 seeds | test | 16 / 5 / 9 min | |",
       "| 24-output LSTM, day-ahead (30 trials) | validation / test | 9 min / 1.5 min | one network per day, 828 training windows |",
       "| Day-ahead completions: per-hour XGBoost (24 models x 30 trials), LSTM L1 (30 trials), ablation (6 sets), quantile model | validation | 126 min | overlapped with code tests, inflated |",
       "| the same, frozen configuration | test | 8 min | |", "",
       "For orientation, the LSTM L4 tuning of the main study took 53 min for 48 trials (about 66 s per trial) and the XGBoost tuning 43.5 min for 244 trials (section 4). The new neural families TCN and Transformer were not run (cost: measured 0.6-4.2 and 2.7-5.6 minutes per epoch before the amendment of 2026-10-20, see the protocol log).", ""]
(ROOT / "reports" / "efficiency_table.md").write_text(chr(10).join(md), encoding="utf-8")
print(chr(10).join(md))
