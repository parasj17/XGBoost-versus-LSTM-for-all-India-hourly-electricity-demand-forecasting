"""Task 6.5: which features drive the headline XGBoost model (validation data only).

Refits the headline model (set S4_full_A, ratio target, seed 0) per horizon with the tuned
hyper-parameters from reports/tables/xgboost_validation.jsonl and reports the mean absolute
TreeSHAP contribution (XGBoost's built-in pred_contribs, in percentage points of the ratio
target) on the validation samples. Contributions describe the model, not causal effects.

Outputs: reports/xgboost_feature_importance.md
Usage:   py scripts/xgb_importance.py
"""
import importlib
import json
import sys
from pathlib import Path

import numpy as np
import pandas as pd
import xgboost as xgb

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "scripts"))
rb = importlib.import_module("run_baselines")
ft = importlib.import_module("features_tabular")
rx = importlib.import_module("run_xgboost")


def main():
    params = {}
    for line in open(ROOT / "reports" / "tables" / "xgboost_validation.jsonl", encoding="utf-8"):
        r = json.loads(line)
        if r["stage"] == "ablation_fit" and r["feature_set"] == rx.HEADLINE and r["relative_target"] and r["seed"] == 0:
            params[r["horizon"]] = r["params"]
    df = pd.read_csv(rb.SRC, parse_dates=["timestamp"]).set_index("timestamp").loc[:rb.VAL_END]
    out = ["# XGBoost feature importance (headline model, validation samples)", "",
           "Generated by `scripts/xgb_importance.py`. Mean |TreeSHAP contribution| in percentage points of the ratio target "
           "(1 point is about 1% of the anchor demand). Describes what the model uses, not causal effects; correlated features share credit.", ""]
    for h in rb.HORIZONS:
        b = rb.build(df, h)
        Xs = {n: rb.design(b, rel, full) for n, (rel, full) in {"g01_abs": (False, False), "g01_rel": (True, False), "full_abs": (False, True), "full_rel": (True, True)}.items()}
        need = pd.concat(Xs.values(), axis=1).notna().all(axis=1) & b["y"].notna() & b["anchors"]["a24"].notna()
        if h <= 168:
            need &= b["anchors"]["a168"].notna()
        valid = need & b["target_obs"]
        in_tr = valid & (b["T"] <= rb.TRAIN_END)
        in_va = valid & (b["T"] >= rb.VAL_START) & (b["T"] <= rb.VAL_END)
        a24 = b["anchors"]["a24"]
        X = ft.build_features(df, h, ft.FEATURE_SETS[rx.HEADLINE], True)
        z = (b["target"] / a24 - 1) * 100
        m = xgb.XGBRegressor(n_estimators=rx.MAX_TREES, objective="reg:squarederror", tree_method="hist", n_jobs=rx.NJOBS,
                             random_state=0, early_stopping_rounds=rx.ES_ROUNDS, eval_metric="mae", **params[h])
        m.fit(X[in_tr], z[in_tr], eval_set=[(X[in_va], z[in_va])], verbose=False)
        contrib = m.get_booster().predict(xgb.DMatrix(X[in_va]), pred_contribs=True)[:, :-1]
        imp = pd.Series(np.abs(contrib).mean(axis=0), index=X.columns).sort_values(ascending=False)
        grp = {"history (g0)": [c for c in X if c.startswith(("lag", "roll", "anchor"))],
               "calendar (g1)": [c for c in X if c.endswith(("_T", "_origin")) and not c.startswith(("is_", "d_"))],
               "holidays (g2)": [c for c in X if c.startswith(("is_holiday", "is_major", "d_"))],
               "weather (g3a)": [c for c in X if c.endswith("_t") and not c.startswith(("solar_", "wind_t"))] + [c for c in X if c.startswith(("temp_lag", "temp_roll", "precip_roll"))],
               "solar/wind (g4)": [c for c in X if c.startswith(("solar_", "wind_t", "wind_lag", "wind_roll"))]}
        out += [f"## Horizon {h} h", "", "Top 10 features: " + "; ".join(f"{k} ({v:.2f})" for k, v in imp.head(10).items()), "",
                "By group (sum of mean |contribution|): " + "; ".join(f"{g}: {imp[[c for c in cs if c in imp.index]].sum():.2f}" for g, cs in grp.items()), ""]
    (ROOT / "reports" / "xgboost_feature_importance.md").write_text("\n".join(out) + "\n", encoding="utf-8")
    print("\n".join(out))


if __name__ == "__main__":
    main()
