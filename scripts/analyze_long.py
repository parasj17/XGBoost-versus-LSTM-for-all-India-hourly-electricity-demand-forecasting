"""Breakdowns and feature importance at the long horizons 72 h and 168 h (protocol deviation log, 2026-10-16).

1. Breakdowns of the TEST predictions saved by run_long_horizons.py --with-test (data/interim/predictions/long_h{h}.npz): MAE by season, weekday/weekend/holiday,
   within one day of a major festival, peak hours (target >= training 95th percentile) and by hour of the target time -> reports/long_breakdowns.md
2. Feature importance: the S4_full_A XGBoost of each long horizon (parameters and number of trees of seed 0 from reports/tables/long_horizon_config.json) is refitted on the
   training period; the mean absolute TreeSHAP contribution on the VALIDATION samples is reported per feature and group -> reports/long_importance.md
No new test evaluation; nothing is selected. Usage: py scripts/analyze_long.py
"""
import importlib
import json
import sys
from pathlib import Path

import numpy as np
import pandas as pd
import xgboost as xgb

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "scripts"))
rb = importlib.import_module("run_baselines")
ft = importlib.import_module("features_tabular")
rx = importlib.import_module("run_xgboost")
rt = importlib.import_module("run_test_evaluation")
SEASONS = ["winter", "pre_monsoon_summer", "monsoon", "post_monsoon"]


def samples(df, h):
    b = rb.build(df, h)
    Xs = {n: rb.design(b, rel, full) for n, (rel, full) in
          {"g01_abs": (False, False), "g01_rel": (True, False), "full_abs": (False, True), "full_rel": (True, True)}.items()}
    need = pd.concat(Xs.values(), axis=1).notna().all(axis=1) & b["y"].notna() & b["anchors"]["a24"].notna() & b["anchors"]["a168"].notna()
    return b, need & b["target_obs"]


def main():
    cfg = json.loads((ROOT / "reports" / "tables" / "long_horizon_config.json").read_text(encoding="utf-8"))
    df = pd.read_csv(rb.SRC, parse_dates=["timestamp"]).set_index("timestamp")
    peak_thr = df.loc[:rb.TRAIN_END, "electricity_demand_mw"].quantile(0.95)
    bd = ["# Breakdowns of the test predictions at 72 h and 168 h (generated by `scripts/analyze_long.py`)", "",
          "MAE in MW of the single-run test predictions of `reports/long_horizons_test.md`. Descriptive; the festival subset is small (about 360 hours).", ""]
    for h in (72, 168):
        b, valid = samples(df, h)
        Tt = b["T"]
        in_te = valid & (Tt >= rt.TEST_START) & (Tt <= rt.TEST_END)
        pos = np.arange(len(df))
        idx = pos[in_te.to_numpy()]
        z = np.load(ROOT / "data" / "interim" / "predictions" / f"long_h{h}.npz")
        y = b["target"].to_numpy()[idx]
        assert np.allclose(z["y_te"], y), "sample set differs from the saved predictions"
        P = {"best naive": z["persistence"] if h == 72 else z["snaive168"], "ridge": z["ridge"], "XGBoost S4": z["XGBoost_S4"], "LSTM L4": z["LSTM_L4"]}
        dft = df.shift(-h)
        season = b["season_T"].to_numpy()[idx]
        hol = dft["is_holiday"].to_numpy()[idx] == 1
        wk = dft["is_weekend"].to_numpy()[idx] == 1
        daytype = np.where(hol, "holiday", np.where(wk, "weekend", "weekday"))
        fw = ft.build_features(df, h, ["g2"], True).iloc[idx]
        near = ((fw["d_next_major"] <= 1) | (fw["d_since_major"] <= 1)).to_numpy()
        hours = pd.DatetimeIndex(Tt.to_numpy()[idx]).hour.to_numpy()
        groups = [(f"season: {s}", season == s) for s in SEASONS] + [(f"day type: {d}", daytype == d) for d in ("weekday", "weekend", "holiday")] + \
                 [("within 1 day of a major festival", near), (f"peak hours (>= training 95th pct, {peak_thr / 1000:.0f} GW)", y >= peak_thr)]
        bd += [f"## Horizon {h} h", "", "| subset | n | " + " | ".join(P) + " |", "|---|---:|" + "---:|" * len(P)]
        for name, mask in groups:
            if mask.sum():
                bd.append(f"| {name} | {int(mask.sum()):,} | " + " | ".join(f"{np.mean(np.abs(v[mask] - y[mask])):,.0f}" for v in P.values()) + " |")
        bd += ["", "MAE by hour of the target time (IST):", "", "| hour | " + " | ".join(P) + " |", "|---:|" + "---:|" * len(P)]
        for hr in range(24):
            m = hours == hr
            bd.append(f"| {hr:02d} | " + " | ".join(f"{np.mean(np.abs(v[m] - y[m])):,.0f}" for v in P.values()) + " |")
        bd.append("")
    (ROOT / "reports" / "long_breakdowns.md").write_text(chr(10).join(bd) + chr(10), encoding="utf-8")
    print("wrote reports/long_breakdowns.md", flush=True)
    # ---- feature importance on validation samples
    imp_md = ["# XGBoost feature importance at 72 h and 168 h (generated by `scripts/analyze_long.py`)", "",
              "Mean absolute TreeSHAP contribution in percentage points of the ratio target on validation samples; S4_full_A, long-horizon parameters, number of trees of seed 0, fitted on the "
              "training period. Describes the model, not causal effects. At 168 h the model has only 2 trees, so its importances are shallow.", ""]
    dfv = df.loc[:rb.VAL_END]
    for h in (72, 168):
        c = cfg[str(h)]
        b, valid = samples(dfv, h)
        Tt = b["T"]
        in_tr = valid & (Tt <= rb.TRAIN_END)
        in_va = valid & (Tt >= rb.VAL_START) & (Tt <= rb.VAL_END)
        a24 = b["anchors"]["a24"]
        X = ft.build_features(dfv, h, ft.FEATURE_SETS["S4_full_A"], True)
        zx = b["target"] / a24
        m = xgb.XGBRegressor(n_estimators=c["xgb_trees"]["0"], objective="reg:squarederror", tree_method="hist", n_jobs=rx.NJOBS, random_state=0, **c["xgb_params"])
        m.fit(X[in_tr], (zx[in_tr] - 1.0) * 100.0, verbose=False)
        contrib = m.get_booster().predict(xgb.DMatrix(X[in_va]), pred_contribs=True)[:, :-1]
        imp = pd.Series(np.abs(contrib).mean(axis=0), index=X.columns).sort_values(ascending=False)
        grp = {"history (g0)": [c_ for c_ in X if c_.startswith(("lag", "roll", "anchor"))],
               "calendar (g1)": [c_ for c_ in X if c_.endswith(("_T", "_origin")) and not c_.startswith(("is_", "d_"))],
               "holidays (g2)": [c_ for c_ in X if c_.startswith(("is_holiday", "is_major", "d_"))],
               "weather (g3a)": [c_ for c_ in X if c_.endswith("_t") and not c_.startswith(("solar_", "wind_t"))] + [c_ for c_ in X if c_.startswith(("temp_lag", "temp_roll", "precip_roll"))],
               "solar/wind (g4)": [c_ for c_ in X if c_.startswith(("solar_", "wind_t", "wind_lag", "wind_roll"))]}
        imp_md += [f"## Horizon {h} h ({c['xgb_trees']['0']} trees)", "", "Top 10 features: " + "; ".join(f"{k} ({v:.2f})" for k, v in imp.head(10).items()), "",
                   "By group (sum of mean |contribution|): " + "; ".join(f"{g}: {imp[[x for x in cs if x in imp.index]].sum():.2f}" for g, cs in grp.items()), ""]
    (ROOT / "reports" / "long_importance.md").write_text(chr(10).join(imp_md) + chr(10), encoding="utf-8")
    print("wrote reports/long_importance.md")


if __name__ == "__main__":
    main()
