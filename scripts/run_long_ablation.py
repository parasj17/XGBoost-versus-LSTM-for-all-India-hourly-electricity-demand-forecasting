"""Feature-group ablation at the long horizons 72 h and 168 h (design in docs/experiment_protocol.md, deviation log 2026-10-16).

XGBoost with the cumulative feature sets S0..S5 (S5 uses oracle weather at the target time, an upper bound only), ratio target, the hyper-parameters selected for the
long horizons (reports/tables/long_horizon_config.json), 3 seeds, mean prediction.
  py scripts/run_long_ablation.py               PHASE 1, validation only: early stopping on validation gives the trees per (set, seed); writes
                                                reports/tables/long_ablation_config.json and reports/long_ablation.md (the test period is not loaded)
  py scripts/run_long_ablation.py --with-test   PHASE 2, single test evaluation with the trees fixed (lock reports/tables/LONG_ABLATION_TEST_DONE.lock);
                                                paired 95% block-bootstrap intervals for every step; writes reports/long_ablation_test.md
"""
import argparse
import importlib
import json
import sys
from pathlib import Path

import numpy as np
import pandas as pd
import xgboost as xgb

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "scripts"))
rb = importlib.import_module("run_baselines")
ft = importlib.import_module("features_tabular")
rx = importlib.import_module("run_xgboost")
rt = importlib.import_module("run_test_evaluation")
T = ROOT / "reports" / "tables"
CFG_IN, CFG_OUT, LOCK = T / "long_horizon_config.json", T / "long_ablation_config.json", T / "LONG_ABLATION_TEST_DONE.lock"
HORIZONS = [72, 168]
STEPS = [("calendar (S0 -> S1)", "S0_history", "S1_calendar"), ("holidays (S1 -> S2)", "S1_calendar", "S2_holidays"), ("past weather (S2 -> S3)", "S2_holidays", "S3_weatherA"),
         ("past solar and wind (S3 -> S4)", "S3_weatherA", "S4_full_A"), ("ORACLE weather (S4 -> S5)", "S4_full_A", "S5_oracle_B")]


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--with-test", action="store_true")
    args = ap.parse_args()
    rx.MAX_TREES = 3000
    commit, dirty = rb.git_state()
    if args.with_test:
        if LOCK.exists():
            sys.exit("The long-horizon ablation test evaluation was already run.")
        if dirty:
            sys.exit("Working tree is not clean: commit first.")
        trees_cfg = json.loads(CFG_OUT.read_text(encoding="utf-8"))
    cfg = json.loads(CFG_IN.read_text(encoding="utf-8"))
    df = pd.read_csv(rb.SRC, parse_dates=["timestamp"]).set_index("timestamp").loc[:(rt.TEST_END if args.with_test else rb.VAL_END)]
    md = ["# " + ("Long-horizon feature ablation: single test evaluation" if args.with_test else "Long-horizon feature ablation: validation") + " (generated by `scripts/run_long_ablation.py`)", "",
          f"Git commit `{(commit or 'n/a')[:10]}`. XGBoost, ratio target, long-horizon hyper-parameters, 3 seeds, MAE in MW. " +
          ("Trees fixed from validation; models fitted on the training period only. Differences are second set minus first set (negative = the added group helps), 95% block bootstrap." if args.with_test else
           "Early stopping on validation (mildly optimistic). At 168 h the early-stopped models are very shallow, so that ablation is weak evidence."), ""]
    rng = np.random.default_rng(0)
    out_cfg = {}
    for h in HORIZONS:
        b = rb.build(df, h)
        Xs = {n: rb.design(b, rel, full) for n, (rel, full) in
              {"g01_abs": (False, False), "g01_rel": (True, False), "full_abs": (False, True), "full_rel": (True, True)}.items()}
        need = pd.concat(Xs.values(), axis=1).notna().all(axis=1) & b["y"].notna() & b["anchors"]["a24"].notna() & b["anchors"]["a168"].notna()
        valid = need & b["target_obs"]
        Tt = b["T"]
        in_tr = valid & (Tt <= rb.TRAIN_END)
        in_va = valid & (Tt >= rb.VAL_START) & (Tt <= rb.VAL_END)
        in_te = valid & (Tt >= rt.TEST_START) & (Tt <= rt.TEST_END) if args.with_test else None
        a24 = b["anchors"]["a24"]
        a24v = a24.fillna(1.0).to_numpy()
        pos = np.arange(len(df))
        idx_va = pos[in_va.to_numpy()]
        y_va, a_va = b["target"].to_numpy()[idx_va], a24v[idx_va]
        if args.with_test:
            idx_te = pos[in_te.to_numpy()]
            y_te, a_te = b["target"].to_numpy()[idx_te], a24v[idx_te]
        zx = b["target"] / a24
        prm = cfg[str(h)]["xgb_params"]
        pred_va, pred_te, ntrees = {}, {}, {}
        for sname, groups in ft.FEATURE_SETS.items():
            X = ft.build_features(df, h, groups, True)
            pv, pt = [], []
            for sd in rt.SEEDS:
                if not args.with_test:
                    p, m, *_ = rx.fit_predict(X[in_tr], zx[in_tr], X[in_va], zx[in_va], prm, sd, a_va, True)
                    pv.append(p)
                    ntrees[f"{sname}|{sd}"] = int(m.best_iteration) + 1
                else:
                    n = trees_cfg[str(h)][f"{sname}|{sd}"]
                    mdl = xgb.XGBRegressor(n_estimators=n, objective="reg:squarederror", tree_method="hist", device="cpu", n_jobs=rx.NJOBS, random_state=sd, eval_metric="mae", **prm)
                    mdl.fit(X[in_tr], (zx[in_tr] - 1.0) * 100.0, verbose=False)
                    pt.append((1.0 + mdl.predict(X[in_te]) / 100.0) * a_te)
            if not args.with_test:
                pred_va[sname] = np.mean(pv, axis=0)
            else:
                pred_te[sname] = np.mean(pt, axis=0)
        out_cfg[str(h)] = ntrees
        P, y = (pred_te, y_te) if args.with_test else (pred_va, y_va)
        md += [f"## Horizon {h} h", "", "| feature set | MAE (MW) |" + (" trees per seed |" if not args.with_test else ""), "|---|---:|" + ("---|" if not args.with_test else "")]
        for sname in ft.FEATURE_SETS:
            md.append(f"| {sname}{' (oracle weather)' if sname == 'S5_oracle_B' else ''} | {np.mean(np.abs(P[sname] - y)):,.0f} |" +
                      ("" if args.with_test else " " + ", ".join(str(ntrees[f'{sname}|{sd}']) for sd in rt.SEEDS) + " |"))
        md += ["", "| step | MAE difference (95% CI) |", "|---|---|"]
        for name, a_, b_ in STEPS:
            d = np.abs(P[b_] - y) - np.abs(P[a_] - y)
            lo, hi = rb.block_ci(d, rng)
            md.append(f"| {name} | {d.mean():+,.0f} ({lo:+,.0f} to {hi:+,.0f}) |")
        md.append("")
        print(f"h={h} done: " + "; ".join(f"{k} {np.mean(np.abs(v - y)):.0f}" for k, v in P.items()), flush=True)
    if args.with_test:
        (ROOT / "reports" / "long_ablation_test.md").write_text(chr(10).join(md) + chr(10), encoding="utf-8")
        LOCK.write_text(f"long-horizon ablation test run completed at commit {commit}" + chr(10), encoding="utf-8")
    else:
        CFG_OUT.write_text(json.dumps(out_cfg, indent=1), encoding="utf-8")
        (ROOT / "reports" / "long_ablation.md").write_text(chr(10).join(md) + chr(10), encoding="utf-8")
    print("wrote the report")


if __name__ == "__main__":
    main()
