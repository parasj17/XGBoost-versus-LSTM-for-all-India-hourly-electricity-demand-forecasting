"""Compare the sensitivity runs of run_baselines.py with the main baseline run.

Reads reports/tables/baselines_validation*.jsonl (last entry per horizon of each file)
and writes reports/sensitivity_summary.md.
Usage: py scripts/summarize_sensitivity.py
"""
import json
from pathlib import Path

import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
T = ROOT / "reports" / "tables"
RUNS = {"main (equal weights, snapshot target)": "baselines_validation.jsonl",
        "population-weighted weather": "baselines_validation_weights_population.jsonl",
        "consumption-weighted weather": "baselines_validation_weights_consumption.jsonl",
        "trained on hourly-mean target": "baselines_validation_trainhourmean.jsonl"}
MODELS = ["ridge_g01_rel", "ridge_full_rel", "ridge_full_abs"]


def load(fn):
    last = {}
    for line in (T / fn).read_text(encoding="utf-8").splitlines():
        r = json.loads(line)
        last[r["horizon"]] = r
    return last


def main():
    data = {k: load(v) for k, v in RUNS.items()}
    out = ["# Sensitivity summary (validation period, MAE in MW)", "",
           "Generated by `scripts/summarize_sensitivity.py`. All runs score the same validation samples against the HH:00 snapshot; "
           "only the weather aggregation or the training target changes. Ridge models; scenario A.", ""]
    for m in MODELS:
        out += [f"## {m}", "", "| run | 1 h | 6 h | 24 h | 48 h |", "|---|---:|---:|---:|---:|"]
        base = {h: data["main (equal weights, snapshot target)"][h]["metrics"][m]["MAE_MW"] for h in (1, 6, 24, 48)}
        for k, d in data.items():
            cells = []
            for h in (1, 6, 24, 48):
                v = d[h]["metrics"][m]["MAE_MW"]
                cells.append(f"{v:,.0f} ({v - base[h]:+,.0f})" if k != "main (equal weights, snapshot target)" else f"{v:,.0f}")
            out.append(f"| {k} | " + " | ".join(cells) + " |")
        out.append("")
    out += ["Numbers in brackets are the difference to the main run (negative = better).",
            "Interpretation guide: a change much smaller than the block-bootstrap uncertainty of the main comparison (tens to a few hundred MW at 24-48 h) "
            "means the choice does not matter for forecasting accuracy at this level."]
    (ROOT / "reports" / "sensitivity_summary.md").write_text("\n".join(out) + "\n", encoding="utf-8")
    print("\n".join(out))


if __name__ == "__main__":
    main()
