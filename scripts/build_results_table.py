"""Consolidated test-period results table for the write-up: every model on every task (reports/results_summary.md). No model is fitted; it reads the saved test predictions.
Test MAE (MW), MAPE (%) and skill against the best naive baseline of the same task (1 - MAE / MAE of the better of the naive baselines on that task's test samples).
Usage: py -I scripts/build_results_table.py
"""
from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parents[1]
PRED = ROOT / "data" / "interim" / "predictions"
L = lambda n: np.load(PRED / n, allow_pickle=True)
HZ = [1, 6, 24, 48, 72, 168]
rows = {}                                               # task -> (y, {model: prediction}, naive keys)
lg, gr = L("lightgbm.npz"), L("neural_gru.npz")
for h in HZ:
    if h <= 48:
        z = L(f"h{h}.npz")
        y = z["y_te"].astype(float)
        P = {"ridge": z["te__ridge_best"], "XGBoost S4": z["te__xgb_S4_full_A"], "LSTM L4": z["te__lstm_L4_full_A"], "LSTM L1 (history + calendar)": z["te__lstm_L1_history_calendar"]}
        N = {"persistence": z["te__persistence"], "same hour yesterday": z["te__snaive24"], "same hour last week": z["te__snaive168"]}
    else:
        z = L(f"long_h{h}.npz")
        y = z["y_te"].astype(float)
        P = {"ridge": z["ridge"], "XGBoost S4": z["XGBoost_S4"], "LSTM L4": z["LSTM_L4"]}
        N = {"persistence": z["persistence"], "same hour 3 or 7 days earlier": z["same_hour_3_or_7_days_earlier"], "same hour last week": z["snaive168"]}
    P["LightGBM S4"] = lg[str(h)]
    assert np.allclose(lg[str(h) + "_y"], y)
    if str(h) in gr.files:
        P["GRU"] = gr[str(h)]
        assert np.allclose(gr[str(h) + "_y"], y)
    rows[f"{h} h"] = (y, {k: np.asarray(v, float) for k, v in P.items()}, {k: np.asarray(v, float) for k, v in N.items()})
da, ex, l24 = L("dayahead.npz"), L("dayahead_ext.npz"), L("dayahead_lstm24.npz")
y = da["y"].astype(float)
assert np.allclose(lg["dayahead_y"], y) and np.allclose(ex["y"], y) and np.allclose(l24["y"], y) and np.array_equal(ex["T"], da["T"])
# the GRU file stores its own (equal-sized, lead-major) rows; check by actuals
assert np.allclose(gr["dayahead_y"], y)
zv = L("dayahead_val.npz")
nk = "naive_a24" if np.mean(np.abs(zv["naive_a24"] - zv["y"])) <= np.mean(np.abs(zv["naive_a168"] - zv["y"])) else "naive_a168"
P = {"ridge": da["ridge"], "XGBoost S4 (pooled)": da["xgb"], "LSTM L4 (pooled)": da["lstm"], "XGBoost S4, one model per hour": ex["xgb_perhour"], "LSTM L1 (pooled)": ex["lstm_l1"],
     "LSTM L4, 24 outputs": l24["lstm24"], "LightGBM S4 (pooled)": lg["dayahead"], "GRU (pooled)": gr["dayahead"]}
rows["day-ahead"] = (y, {k: np.asarray(v, float) for k, v in P.items()}, {"same hour on the latest earlier day": da["naive_a24"].astype(float), "same hour last week": da["naive_a168"].astype(float)})

md = ["# Consolidated test-period results (generated by `scripts/build_results_table.py`)", "",
      "Every model on every task, test period 2024-07-01 to 2025-06-24, from the saved predictions of the single test runs. MAE in MW; skill = 1 - MAE / MAE of the better naive baseline of the same task on the same samples. "
      "The tuning budgets differ between models and tasks (see `reports/research_question_answers.md` and the protocol log); differences between models are only meaningful with the paired intervals in the other reports. "
      "Day-ahead = forecasts issued at 10:00 on the previous day for the 24 hours of a day (8,611 hours); the other tasks are direct forecasts at the stated horizon from every hourly origin.", ""]
for task, (y, P, N) in rows.items():
    nv = {k: float(np.mean(np.abs(v - y))) for k, v in N.items()}
    best = min(nv, key=nv.get)
    md += [f"## {task}", "", "| model | MAE (MW) | MAPE % | skill vs best naive |", "|---|---:|---:|---:|"]
    for k, v in N.items():
        md.append(f"| naive: {k}{' (best)' if k == best else ''} | {nv[k]:,.0f} | {100 * np.mean(np.abs(v - y) / y):.2f} | |")
    for k, v in sorted(P.items(), key=lambda kv: np.mean(np.abs(kv[1] - y))):
        e = np.abs(v - y)
        md.append(f"| {k} | {e.mean():,.0f} | {100 * np.mean(e / y):.2f} | {100 * (1 - e.mean() / nv[best]):+.1f}% |")
    md.append("")
md += ["Not evaluated: SARIMAX, Prophet, TCN and Transformer (dropped before any run; see `docs/limitations.md`). The GRU was evaluated at 1 h, 24 h and the day-ahead task only; LSTM L1 at 1-48 h and in the day-ahead task.", ""]
(ROOT / "reports" / "results_summary.md").write_text(chr(10).join(md), encoding="utf-8")
print(chr(10).join(md))
