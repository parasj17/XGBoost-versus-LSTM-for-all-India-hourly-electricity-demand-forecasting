"""Region weights for aggregating the 12-city weather into a national series (task 3.7).

Three weightings over the five grid regions:
  equal        0.2 each (decision D-03 baseline)
  population   share of Census-2011 population  (data/raw/population/census2011_state_population.csv)
  consumption  share of energy met (MU) over the TRAINING period 2021-09-01..2023-12-31
               from the Zenodo state table (data/raw/zenodo_state_daily/corrected_daily_energy_met_MU.csv)

State -> grid region mapping is the standard composition of India's five
regional grids. ASSUMPTION: it was not confirmed against a current Grid-India/CEA
document (the one source found was a 2012 article that still lists Chhattisgarh in
the Eastern grid). Chhattisgarh is placed in the Western grid here; moving it would
change shares by about 2 percentage points of population. Lakshadweep and
Andaman & Nicobar are not on the mainland grids and are excluded; AMNSIL and
Damodar Valley Corporation columns of the Zenodo table are excluded (no clean
state mapping).

Output: data/interim/weather_region_weights.csv, reports/weather_weights.md
Usage:  py scripts/compute_region_weights.py
"""
from pathlib import Path

import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
POP = ROOT / "data" / "raw" / "population" / "census2011_state_population.csv"
ENERGY = ROOT / "data" / "raw" / "zenodo_state_daily" / "corrected_daily_energy_met_MU.csv"
OUT_CSV = ROOT / "data" / "interim" / "weather_region_weights.csv"
OUT_MD = ROOT / "reports" / "weather_weights.md"

REGIONS = {
    "Northern": ["Delhi", "Haryana", "Himachal Pradesh", "Jammu and Kashmir", "Ladakh", "Punjab",
                 "Rajasthan", "Uttar Pradesh", "Uttarakhand", "Chandigarh"],
    "Western": ["Chhattisgarh", "Goa", "Gujarat", "Madhya Pradesh", "Maharashtra",
                "Dadra and Nagar Haveli and Daman and Diu"],
    "Southern": ["Andhra Pradesh", "Karnataka", "Kerala", "Tamil Nadu", "Telangana", "Puducherry"],
    "Eastern": ["Bihar", "Jharkhand", "Odisha", "West Bengal", "Sikkim"],
    "North-Eastern": ["Arunachal Pradesh", "Assam", "Manipur", "Meghalaya", "Mizoram", "Nagaland", "Tripura"],
}
# Zenodo column names that differ from the census names
ZEN_ALIAS = {"Delhi": "Delhi"}  # same; Dadra/Daman are separate columns in Zenodo (see below)


def main():
    pop = pd.read_csv(POP).set_index("state_or_ut")["population_2011"]
    region_pop = {r: int(pop[s].sum()) for r, s in REGIONS.items()}
    en = pd.read_csv(ENERGY, parse_dates=["Date"]).drop_duplicates("Date").set_index("Date")
    en = en.loc["2021-09-01":"2023-12-31"]
    region_en = {}
    for r, states in REGIONS.items():
        cols = []
        for s in states:
            if s == "Dadra and Nagar Haveli and Daman and Diu":
                cols += ["Dadra and Nagar Haveli", "Daman and Diu"]
            else:
                cols.append(s)
        cols = [c for c in cols if c in en.columns]   # Ladakh has no column of its own (counted inside J&K)
        region_en[r] = float(en[cols].sum(axis=0, skipna=True).sum())
    w = pd.DataFrame({"equal": 0.2, "population": pd.Series(region_pop) / sum(region_pop.values()),
                      "consumption": pd.Series(region_en) / sum(region_en.values())})
    w = w.loc[list(REGIONS)]
    OUT_CSV.parent.mkdir(parents=True, exist_ok=True)
    w.to_csv(OUT_CSV, float_format="%.6f")
    tot_state_sum = float(en.drop(columns=["Total"]).sum(axis=0, skipna=True).sum())
    lines = ["# Region weights for the national weather aggregate", "",
             "Generated by `scripts/compute_region_weights.py`. Decision D-03 baseline is equal weights; the others are sensitivity analyses.", "",
             "| region | equal | population (Census 2011) | consumption (Zenodo energy met, 2021-09 to 2023-12) |", "|---|---:|---:|---:|"]
    for r in w.index:
        lines.append(f"| {r} | {w.loc[r, 'equal']:.3f} | {w.loc[r, 'population']:.3f} | {w.loc[r, 'consumption']:.3f} |")
    lines += ["", f"Energy used: {sum(region_en.values()):,.0f} MU on mapped states of {tot_state_sum:,.0f} MU in all state columns "
              f"({100 * sum(region_en.values()) / tot_state_sum:.1f}% mapped).",
              "Assumptions: standard state-to-region mapping (Chhattisgarh in Western), not confirmed against a current Grid-India document; "
              "Lakshadweep, Andaman & Nicobar, AMNSIL and DVC excluded. Census populations sum to 0.024% below the printed national total.",
              "Consumption weights use training-period data only, so they do not leak validation/test information."]
    OUT_MD.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
