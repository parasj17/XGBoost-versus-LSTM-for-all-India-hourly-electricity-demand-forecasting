"""Paired feature-group comparisons on the test period, from saved predictions (no fitting).

For XGBoost (same hyper-parameters, 3-seed mean prediction): the effect of each cumulative feature group, with a 95% moving-block
bootstrap interval for the MAE difference, plus how far test inputs lie outside the training range.
Needs data/interim/predictions/h*.npz.   Output: reports/ablation_paired.md
Usage: py scripts/analyze_ablation_ci.py
"""
import importlib
import sys
from pathlib import Path

import numpy as np
import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "scripts"))
rb = importlib.import_module("run_baselines")
PD = ROOT / "data" / "interim" / "predictions"
STEPS = [("calendar features (S0 -> S1)", "xgb_S0_history", "xgb_S1_calendar"),
         ("holiday / festival features (S1 -> S2)", "xgb_S1_calendar", "xgb_S2_holidays"),
         ("past observed weather (S2 -> S3)", "xgb_S2_holidays", "xgb_S3_weatherA"),
         ("past solar and wind (S3 -> S4)", "xgb_S3_weatherA", "xgb_S4_full_A"),
         ("ORACLE weather at the target hour (S4 -> S5; not available in reality)", "xgb_S4_full_A", "xgb_S5_oracle_B"),
         ("LSTM: history+calendar -> full features (L1 -> L4)", "lstm_L1_history_calendar", "lstm_L4_full_A")]


def main():
    rng = np.random.default_rng(0)
    md = ["# Paired feature-group effects on the test period (generated by `scripts/analyze_ablation_ci.py`)", "",
          "MAE of the second configuration minus the first, in MW (negative = adding the group helps); 95% moving-block bootstrap interval (block 168 h). "
          "Same hyper-parameters in every XGBoost configuration (tuned for S4), so the comparison is at a fixed model budget but not separately tuned per set. "
          "Intervals that include zero mean the effect is not distinguishable from zero on this single test year.", "",
          "| step | 1 h | 6 h | 24 h | 48 h |", "|---|---|---|---|---|"]
    cells = {s[0]: [] for s in STEPS}
    for h in rb.HORIZONS:
        z = np.load(PD / f"h{h}.npz")
        y = z["y_te"]
        for name, a, b in STEPS:
            d = np.abs(z[f"te__{b}"] - y) - np.abs(z[f"te__{a}"] - y)
            lo, hi = rb.block_ci(d, rng)
            rel = 100 * d.mean() / np.mean(np.abs(z[f"te__{a}"] - y))
            cells[name].append(f"{d.mean():+,.0f} ({lo:+,.0f} to {hi:+,.0f}; {rel:+.1f}%)")
    for name, *_ in STEPS:
        md.append(f"| {name} | " + " | ".join(cells[name]) + " |")
    df = pd.read_csv(rb.SRC, parse_dates=["timestamp"]).set_index("timestamp")
    tr = df.loc[:rb.TRAIN_END]
    va = df.loc[rb.VAL_START:rb.VAL_END]
    te = df.loc[rb.VAL_END + pd.Timedelta(hours=1):]
    md += ["", "## How far do the inputs move outside the training range?", "",
           "| variable | training max | share of validation hours above it | share of test hours above it | mean: train / validation / test |", "|---|---:|---:|---:|---|"]
    for c, lab in (("electricity_demand_mw", "demand (MW)"), ("solar_generation_mw", "solar generation (MW)"), ("wind_generation_mw", "wind generation (MW)"),
                   ("temp_c", "national temperature (C)")):
        mx = tr[c].max()
        md.append(f"| {lab} | {mx:,.0f} | {100 * (va[c] > mx).mean():.1f}% | {100 * (te[c] > mx).mean():.1f}% | {tr[c].mean():,.0f} / {va[c].mean():,.0f} / {te[c].mean():,.0f} |")
    md += ["", "A large share of test hours above the training maximum means tree models cannot have seen such values (a tree predicts a constant beyond its last split) and a recurrent network is extrapolating; "
           "this matters for solar, whose installed capacity keeps growing (15% of test hours exceed the training maximum, mean +59% against training). "
           "Demand itself rarely exceeds the training maximum (0.1% of test hours) although its mean level is about 12% higher than in training; the anchor-relative target absorbs that shift."]
    (ROOT / "reports" / "ablation_paired.md").write_text(chr(10).join(md) + chr(10), encoding="utf-8")
    print(chr(10).join(md))


if __name__ == "__main__":
    main()
